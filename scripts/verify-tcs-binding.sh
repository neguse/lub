#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT
cflags=(-std=gnu11 -O2 -fwrapv -ffp-contract=off -fexcess-precision=standard -Iinclude -Ithird_party/SDL/include -I"$work")
LUB_TCS="${LUB_TCS:-$(scripts/build-tcs-dotnet.sh)}"
export LUB_TCS
dotnet build tools/lub-gen/lub-gen.csproj -c Release
scripts/tcs.sh c --lib \
  --ref cs-lib/lub_stub.cs tests/c/tcs_binding.cs -o "$work/game.c"
dotnet tools/lub-gen/bin/Release/net11.0/lub-gen.dll tcs --stub cs-lib/lub_stub.cs \
  --source tests/c/tcs_binding.cs -o "$work/binding.c"
cp tests/c/tcs_binding.c "$work/test.c"
printf '\nint main(void) { tcs_lib_init(); tcs_entry_BindingTest_Main(); return 0; }\n' >> "$work/test.c"
"${CC:-cc}" "${cflags[@]}" "$work/test.c" -lm -o "$work/test"
[[ "$("$work/test" | tr -d '\r')" == $'0\n7\n123\n1\nTrue\nTrue\n9\n4\nTrue\n48000\n6\nb\nTrue\n2\n8\nTrue\n10\n3\n3 8 1.5 -2\n1.25 -0.5 4\n2.5\nTrue\nTrue\n11\nTrue\n2\n1\n0000000000000abc\n7\n12.5 -3\nTrue image 7\nFalse True\n0.5 1 1.5' ]]
echo 'tcs2c binding: main target, handles, Bindings, array and list uniforms, voice options, nullable XR views, byte views, record results, record lists, list results, maybe results, view methods, nullable scalar results, nullable record outs, scalar and string outs, struct records by value and in record fields, optional record fields, bit masks and callbacks passed'

# An empty bit mask string and one with 17 or more digits are errors (the same rule as the tcs VM and .NET bindings).
for mask_case in 'EmptyMask:empty hex string' 'LongMask:more than 16 hex digits'; do
  entry=${mask_case%%:*}
  cp tests/c/tcs_binding.c "$work/$entry.c"
  printf '\nint main(void) { tcs_lib_init(); tcs_entry_BindingTest_%s(); return 0; }\n' "$entry" >> "$work/$entry.c"
  "${CC:-cc}" "${cflags[@]}" "$work/$entry.c" -lm -o "$work/$entry"
  if "$work/$entry" 2> "$work/$entry.err"; then
    echo "tcs2c binding: $entry did not fault" >&2
    exit 1
  fi
  grep -qF "bit mask: ${mask_case#*:}" "$work/$entry.err"
done
echo 'tcs2c binding: empty and over-long bit masks fault'

cp tests/c/tcs_binding.c "$work/ArrayCount.c"
printf '\nint main(void) { tcs_lib_init(); tcs_entry_BindingTest_ArrayCount(); return 0; }\n' >> "$work/ArrayCount.c"
"${CC:-cc}" "${cflags[@]}" "$work/ArrayCount.c" -lm -o "$work/ArrayCount"
if "$work/ArrayCount" 2> "$work/ArrayCount.err"; then
  echo 'tcs2c binding: ArrayCount did not fault' >&2
  exit 1
fi
grep -qF 'lub-array-length' "$work/ArrayCount.err"
echo 'tcs2c binding: a count past the end of the array faults'

# How struct records are written and passed (the same stub, game and fake C API as scripts/verify-vm-binding.sh)
cat cs-lib/lub_stub.cs tests/c/struct_stub.cs > "$work/struct_stub.cs"
mkdir -p "$work/struct/lub"
dotnet tools/lub-gen/bin/Release/net11.0/lub-gen.dll header --stub "$work/struct_stub.cs" -o "$work/struct/lub/lub_api.h"
scripts/tcs.sh c --lib \
  --ref "$work/struct_stub.cs" tests/c/struct_test.cs -o "$work/struct/game.c"
dotnet tools/lub-gen/bin/Release/net11.0/lub-gen.dll tcs --stub "$work/struct_stub.cs" \
  --source tests/c/struct_test.cs -o "$work/struct/binding.c"
cp tests/c/struct_test.c "$work/struct/test.c"
printf '\nint main(void) { tcs_lib_init(); tcs_entry_StructGame_Main(); return 0; }\n' >> "$work/struct/test.c"
"${CC:-cc}" -I"$work/struct" "${cflags[@]}" "$work/struct/test.c" -lm -o "$work/struct/test"
[[ "$("$work/struct/test" | tr -d '\r')" == $'13 0.5 True 7 9\n0 False\nTrue 8 True -4 True 2\nFalse 0 False\nFalse 4' ]]
echo 'tcs2c binding: struct records pass by value, as outs and as results, and as record fields'

# The Math of the C generated by tcs2c (the tcs runtime/math embedded in the generated C) must give the same results as the tcs VM path.
# The expected values are the table in tests/cs/TestMathDeterminism.cs (a single one, not split by OS).
scripts/tcs.sh c tests/c/tcs_math.cs -o "$work/math_game.c"
"${CC:-cc}" "${cflags[@]}" -fno-fast-math "$work/math_game.c" -lm -o "$work/math"
"$work/math" | tr -d '\r' > "$work/math.out"
sed -nE 's/^ *"([a-z0-9]+ = -?[0-9]+)",$/\1/p' tests/cs/TestMathDeterminism.cs > "$work/math.expected"
[[ -s "$work/math.out" ]]
if grep -vxFf "$work/math.expected" "$work/math.out"; then
  echo 'tcs2c math: the digests above differ from tests/cs/TestMathDeterminism.cs' >&2
  exit 1
fi
echo "tcs2c math: $(wc -l < "$work/math.out") functions match tests/cs/TestMathDeterminism.cs"

# All of cs-lib (lub and lubx) must go through the same path as a game (tcs2c → lub-gen tcs → C).
# It uses many APIs, so the C implementation is not linked; it is checked up to compile.
lubx=(cs-lib/lub/*.cs cs-lib/lubx/*.cs)
lubx_sources=()
for source in "${lubx[@]}"; do lubx_sources+=(--source "$source"); done
scripts/tcs.sh c --lib \
  --ref cs-lib/lub_stub.cs "${lubx[@]}" -o "$work/lubx_game.c"
dotnet tools/lub-gen/bin/Release/net11.0/lub-gen.dll tcs --stub cs-lib/lub_stub.cs \
  "${lubx_sources[@]}" -o "$work/lubx_binding.c"
printf '#include "lubx_game.c"\n#include "lubx_binding.c"\n' > "$work/lubx.c"
"${CC:-cc}" "${cflags[@]}" -c "$work/lubx.c" -o "$work/lubx.o"
echo "tcs2c binding: cs-lib (${#lubx[@]} files) generated and compiled"

# src/tcs_host.c must build regardless of the entry class name, even for a game without OnQuit.
# 13_sprites has the class Sprites13 and no OnQuit.
# If no unresolved tcs_entry_* remain in the host object, it can link with the runtime.
host_sources=(samples/13_sprites/Sprites13.cs "${lubx[@]}")
host_args=()
for source in "${host_sources[@]}"; do host_args+=(--source "$source"); done
scripts/tcs.sh c --lib \
  --ref cs-lib/lub_stub.cs "${host_sources[@]}" -o "$work/host_game.c"
dotnet tools/lub-gen/bin/Release/net11.0/lub-gen.dll tcs --stub cs-lib/lub_stub.cs \
  "${host_args[@]}" -o "$work/host_binding.c"
grep -qF 'static void tcs_game_on_quit(void) {}' "$work/host_binding.c"
"${CC:-cc}" "${cflags[@]}" -Isrc -DLUB_TCS_GAME="\"$work/host_game.c\"" \
  -DLUB_TCS_BINDING="\"$work/host_binding.c\"" -c src/tcs_host.c -o "$work/host.o"
if nm -u "$work/host.o" | grep tcs_entry_; then
  echo 'tcs host: unresolved tcs_entry_* symbols (an entry hook is not defined by the game)' >&2
  exit 1
fi
echo "tcs host: entry class Sprites13 without OnQuit compiled and linked cleanly"

# src/tcs_host.c must pass polled events to the OnEvent of the entry.
# The fake lub_host_* (tests/c/tcs_event_host.c) feeds a fixed sequence of events.
# After receiving Quit, the remaining events are not passed, and that frame is not run.
# The game carries the received EventData over in a List, so the output must be the same even with TCS_GC_STRESS, which collects up to the old generation at every frame boundary.
# On an iteration where a frame cannot be started (the fake frame_begin returns false once on frame 1), wait 16ms before the next iteration.
scripts/tcs.sh c --lib \
  --ref cs-lib/lub_stub.cs tests/c/tcs_event.cs -o "$work/event_game.c"
dotnet tools/lub-gen/bin/Release/net11.0/lub-gen.dll tcs --stub cs-lib/lub_stub.cs \
  --source tests/c/tcs_event.cs -o "$work/event_binding.c"
cat > "$work/event.expected" <<'OUT'
init
event 2 key=4 button=0 x=0 y=0 dy=0
event 4 key=0 button=1 x=10.5 y=20 dy=0
frame 1 2:4:0 4:0:10.5
event 7 key=0 button=0 x=0 y=0 dy=-1
delay 16
frame 2 2:4:0 4:0:10.5 7:0:0
event 3 key=4 button=0 x=0 y=0 dy=0
quit frames=2 seen=4
OUT
for stress in '' -DTCS_GC_STRESS=1; do
  "${CC:-cc}" "${cflags[@]}" -Isrc $stress -DLUB_TCS_GAME="\"$work/event_game.c\"" \
    -DLUB_TCS_BINDING="\"$work/event_binding.c\"" src/tcs_host.c tests/c/tcs_event_host.c \
    -lm -o "$work/event"
  "$work/event" | tr -d '\r' | diff "$work/event.expected" -
done
echo "tcs host: OnEvent receives events until Quit, and kept EventData survive GC stress"

# A fault in a callback aborts that callback and is passed to the OnError of the entry.
# With Log, it moves on to the next callback, and the failed frame reaches frame_end as failed.
# If OnError itself faults, it is Abort: OnQuit is called and it exits with exit code 1.
# A message that OnError carries over survives the GC at the boundary after the fault.
scripts/tcs.sh c --lib \
  --ref cs-lib/lub_stub.cs tests/c/tcs_error.cs -o "$work/error_game.c"
dotnet tools/lub-gen/bin/Release/net11.0/lub-gen.dll tcs --stub cs-lib/lub_stub.cs \
  --source tests/c/tcs_error.cs -o "$work/error_binding.c"
cat > "$work/error.expected" <<'OUT'
init
error 1 null
event 4
frame null
error 2 divide-by-zero
frame failed
event 7
delay 16
frame null divide-by-zero
error 3 divide-by-zero
frame failed
quit errors=3 kept=3
exit 1
OUT
for stress in '' -DTCS_GC_STRESS=1; do
  "${CC:-cc}" "${cflags[@]}" -Isrc $stress -DLUB_TCS_GAME="\"$work/error_game.c\"" \
    -DLUB_TCS_BINDING="\"$work/error_binding.c\"" src/tcs_host.c tests/c/tcs_event_host.c \
    -lm -o "$work/error"
  { "$work/error" 2> "$work/error.err" && echo 'exit 0' || echo "exit $?"; } | tr -d '\r' | diff "$work/error.expected" -
  grep -qF 'TinyC# fault: divide-by-zero' "$work/error.err"
done
echo "tcs host: a fault reaches OnError, Log continues, and a fault in OnError aborts with exit code 1"

# OnError becomes an entry only if it is static Lub.ErrorAction OnError(string).
printf 'using Lub;\nstatic class Game\n{\n    public static void OnError(string message) { }\n    public static void OnFrame(float dt) { }\n}\n' > "$work/bad_error.cs"
if dotnet tools/lub-gen/bin/Release/net11.0/lub-gen.dll tcs --stub cs-lib/lub_stub.cs \
  --source "$work/bad_error.cs" -o "$work/bad_error.c" 2> "$work/bad_error.err"; then
  echo 'tcs host: lub-gen accepted an OnError without a result' >&2
  exit 1
fi
grep -qF 'OnError must be static Lub.ErrorAction (string)' "$work/bad_error.err"
echo "tcs host: lub-gen rejects OnError with another signature"

# OnEvent becomes an entry only if it is static void OnEvent(Lub.EventData).
for bad in 'void OnEvent(int key) { }' 'int OnEvent(EventData e) { return 0; }' 'void OnEvent() { }'; do
  printf 'using Lub;\nstatic class Game\n{\n    public static %s\n    public static void OnFrame(float dt) { }\n}\n' "$bad" > "$work/bad_event.cs"
  if dotnet tools/lub-gen/bin/Release/net11.0/lub-gen.dll tcs --stub cs-lib/lub_stub.cs \
    --source "$work/bad_event.cs" -o "$work/bad_event.c" 2> "$work/bad_event.err"; then
    echo "tcs host: lub-gen accepted $bad" >&2
    exit 1
  fi
  grep -qF 'OnEvent must be static void (Lub.EventData)' "$work/bad_event.err"
done
echo "tcs host: lub-gen rejects OnEvent without a single EventData parameter or with a result"

# Resolving --entry: a class with a namespace can also be specified by its C# name (MyGame.Game), and a class without a static OnFrame cannot be an entry.
cat > "$work/entry.cs" <<'CS'
namespace MyGame
{
    public static class Game
    {
        public static void OnFrame(float dt) { }
    }
    public static class Helper
    {
        public static void Run() { }
    }
}
CS
lub_gen=(dotnet tools/lub-gen/bin/Release/net11.0/lub-gen.dll tcs --stub cs-lib/lub_stub.cs --source "$work/entry.cs")
"${lub_gen[@]}" -o "$work/entry_default.c"
"${lub_gen[@]}" --entry MyGame.Game -o "$work/entry_display.c"
"${lub_gen[@]}" --entry MyGame_Game -o "$work/entry_il.c"
for generated in default display il; do
  grep -qF 'tcs_entry_MyGame_Game_OnFrame(dt)' "$work/entry_$generated.c"
done
if "${lub_gen[@]}" --entry MyGame.Helper -o "$work/entry_helper.c" 2> "$work/entry_helper.err"; then
  echo 'tcs host: --entry accepted a class without static OnFrame' >&2
  exit 1
fi
grep -q 'no static OnFrame' "$work/entry_helper.err"
echo "tcs host: --entry accepts the C# name and rejects a class without OnFrame"

#ifndef LUB_EMBEDDED_SERVE_PAGE_H
#define LUB_EMBEDDED_SERVE_PAGE_H

// Self-contained HTML page for lub --serve.
// Includes: WebGPU init, Slang WASM bridge, EventSource (SSE) client,
// lub.js loader with MEMFS overlay.
// Template variable: {{ENTRY}} is replaced at runtime with the MEMFS path of
// the generated Lua (JSON-escaped, so it sits inside a JS string literal).

static const char SERVE_PAGE_HTML[] =
    "<!DOCTYPE html>\n"
    "<html><head><meta charset=\"UTF-8\">\n"
    "<style>\n"
    "html,body{margin:0;height:100%;background:#000;overflow:hidden;"
    "display:flex;align-items:center;justify-content:center}\n"
    "canvas{display:block;max-width:100%;max-height:100%}\n"
    "#status{position:fixed;top:10px;left:10px;color:#0f0;font:14px monospace;"
    "z-index:10;pointer-events:none}\n"
    "</style></head><body>\n"
    "<div id=\"status\">connecting...</div>\n"
    "<canvas id=\"canvas\" width=\"1280\" height=\"720\" "
    "tabindex=\"0\"></canvas>\n"
    // Host bridge (window.lubHost) from the game dir; the server answers an
    // empty script when the game has none. Loaded synchronously before the
    // main script so lubHost exists before any Lua runs.
    "<script src=\"/host.js\"></script>\n"
    "<script>\n"
    "'use strict';\n"
    "const ENTRY=\"{{ENTRY}}\";\n"
    "const canvas=document.getElementById('canvas');\n"
    "const statusEl=document.getElementById('status');\n"
    "// game files fetched before main(); written into MEMFS once lub.data is\n"
    "// unpacked (overlayed), later updates go straight to MEMFS\n"
    "let pendingFiles={},overlayed=false,wasmStarted=false;\n"
    "// tcs の reload chunk。起動前に届いた分は溜め、届いた順に渡す\n"
    "let pendingChunks=[],runtimeReady=false;\n"
    "\n"
    "function queueChunk(lua){\n"
    "  const M=window.Module,FS=M.FS??window.FS,path='/lub_reload_chunk.lua';\n"
    "  FS.writeFile(path,lua);\n"
    "  M.ccall('lub_queue_reload_chunk_file',null,['string'],[path]);\n"
    "}\n"
    "\n"
    "function writeFileEnsureDir(FS,path,content){\n"
    "  const parts=path.split('/');\n"
    "  let cur='';\n"
    "  for(let i=0;i<parts.length-1;i++){\n"
    "    cur=cur?cur+'/'+parts[i]:parts[i];\n"
    "    try{FS.mkdir(cur);}catch{}\n"
    "  }\n"
    "  try{FS.unlink(path);}catch{}\n"
    "  FS.writeFile(path,content);\n"
    "}\n"
    "\n"
    "function fetchFile(p){\n"
    "  const url='/files/'+p.split('/').map(encodeURIComponent).join('/');\n"
    "  return fetch(url).then(r=>{\n"
    "    if(!r.ok)throw new Error(p+': '+r.status);\n"
    "    return r.arrayBuffer();\n"
    "  }).then(b=>[p,new Uint8Array(b)]).catch(e=>{\n"
    "    console.error('[serve] fetch failed:',e.message);return null;\n"
    "  });\n"
    "}\n"
    "\n"
    "// files events carry names only. Fetch in arrival order so an\n"
    "// older copy never lands after a newer one; start after the first.\n"
    "let fileChain=Promise.resolve();\n"
    "function receiveFiles(names){\n"
    "  fileChain=fileChain.then(()=>Promise.all(names.map(fetchFile)))"
    ".then(got=>{\n"
    "    for(const f of got){\n"
    "      if(!f)continue;\n"
    "      if(overlayed)writeFileEnsureDir(window.Module.FS,f[0],f[1]);\n"
    "      else pendingFiles[f[0]]=f[1];\n"
    "    }\n"
    "    if(!wasmStarted){\n"
    "      statusEl.textContent='files received, starting...';\n"
    "      startWasm();\n"
    "    }\n"
    "  });\n"
    "}\n"
    "\n"
    "// --- WebGPU init ---\n"
    "async function initWebGPU(){\n"
    "  if(!('gpu' in navigator))throw new Error('WebGPU not available');\n"
    "  const adapter=await navigator.gpu.requestAdapter();\n"
    "  if(!adapter)throw new Error('No WebGPU adapter');\n"
    "  const wanted=[];\n"
    "  for(const f of['depth32float-stencil8','float32-filterable']){\n"
    "    if(adapter.features?.has?.(f))wanted.push(f);\n"
    "  }\n"
    "  return await adapter.requestDevice({requiredFeatures:wanted});\n"
    "}\n"
    "\n"
    "// --- Slang WASM bridge ---\n"
    "let slangReady=false;\n"
    "async function initSlang(){\n"
    "  try{\n"
    "    const importer=new Function('u','return import(u)');\n"
    "    const mod=await importer('/slang/slang-wasm.js');\n"
    "    const factory=mod.default;\n"
    "    if(typeof factory!=='function')throw new Error('no factory');\n"
    "    const main=await factory({\n"
    "      locateFile:p=>p.endsWith('.wasm')?'/slang/'+p:p\n"
    "    });\n"
    "    const gs=main.createGlobalSession();\n"
    "    if(!gs)throw new Error('createGlobalSession failed');\n"
    "    const targets=main.getCompileTargets();\n"
    "    let wgslTarget=-1;\n"
    "    for(const t of "
    "targets){if(t.name==='WGSL'){wgslTarget=t.value;break;}}\n"
    "    if(wgslTarget<0)throw new Error('no WGSL target');\n"
    "    let sharedSession=null,moduleSeq=0;\n"
    "\n"
    "    window.slangCompile=async(src,entry,stage)=>{\n"
    "      const STAGES=[1,5,6];\n"
    "      let "
    "userModule=null,ep=null,composite=null,linked=null,layout=null;\n"
    "      try{\n"
    "        if(!sharedSession){\n"
    "          sharedSession=gs.createSession(wgslTarget);\n"
    "          if(!sharedSession)return{error:'createSession failed'};\n"
    "        }\n"
    "        const modName='user_'+(moduleSeq++);\n"
    "        "
    "userModule=sharedSession.loadModuleFromSource(src,modName,modName+'.slang'"
    ");\n"
    "        if(!userModule){const "
    "e=main.getLastError?.();return{error:'loadModule: '+(e?.message||'?')};}\n"
    "        ep=userModule.findAndCheckEntryPoint(entry,STAGES[stage]);\n"
    "        if(!ep){const e=main.getLastError?.();return{error:'entryPoint: "
    "'+(e?.message||'?')};}\n"
    "        "
    "composite=sharedSession.createCompositeComponentType([userModule,ep]);\n"
    "        if(!composite){const "
    "e=main.getLastError?.();return{error:'composite: '+(e?.message||'?')};}\n"
    "        linked=composite.link();\n"
    "        if(!linked){const e=main.getLastError?.();return{error:'link: "
    "'+(e?.message||'?')};}\n"
    "        const wgsl=linked.getEntryPointCode(0,0);\n"
    "        if(!wgsl||wgsl==='Error'||!wgsl.length){\n"
    "          const e=main.getLastError?.();return{error:'getEntryPointCode: "
    "'+(e?.message||'?')};\n"
    "        }\n"
    "        let reflectObj={};\n"
    "        "
    "try{layout=linked.getLayout(0);if(layout)reflectObj=layout.toJsonObject()?"
    "?{};}catch{}\n"
    "        return{wgsl,reflectJson:JSON.stringify(reflectObj)};\n"
    "      }catch(e){return{error:'slangCompile threw: '+(e?.message??e)};}\n"
    "      finally{\n"
    "        try{layout?.delete?.();}catch{}\n"
    "        try{linked?.delete?.();}catch{}\n"
    "        try{composite?.delete?.();}catch{}\n"
    "        try{ep?.delete?.();}catch{}\n"
    "        try{userModule?.delete?.();}catch{}\n"
    "      }\n"
    "    };\n"
    "    slangReady=true;\n"
    "    console.log('[serve] slang-wasm ready');\n"
    "  }catch(e){\n"
    "    console.error('[serve] slang-wasm init failed:',e);\n"
    "  }\n"
    "}\n"
    "\n"
    "// --- WASM startup ---\n"
    "async function startWasm(){\n"
    "  if(wasmStarted)return;\n"
    "  wasmStarted=true;\n"
    "  statusEl.textContent='initializing WebGPU...';\n"
    "  let device;\n"
    "  try{device=await initWebGPU();}catch(e){\n"
    "    statusEl.textContent='WebGPU init failed: '+e.message;return;\n"
    "  }\n"
    "  const seenErrors=new Set();\n"
    "  device.addEventListener('uncapturederror',e=>{\n"
    "    const msg=String(e.error?.message??e.error);\n"
    "    if(seenErrors.has(msg))return;seenErrors.add(msg);\n"
    "    console.error('[webgpu]',msg);\n"
    "  });\n"
    "  statusEl.textContent='initializing Slang...';\n"
    "  await initSlang();\n"
    "  statusEl.textContent='loading WASM...';\n"
    "  const moduleConfig={\n"
    "    canvas,\n"
    "    preinitializedWebGPUDevice:device,\n"
    "    print:t=>console.log(t),\n"
    "    printErr:t=>console.error(t),\n"
    "    locateFile:p=>'/wasm/'+p,\n"
    "    preRun:[],\n"
    "    arguments:[ENTRY],\n"
    "    onRuntimeInitialized:()=>{\n"
    "      runtimeReady=true;\n"
    "      for(const c of pendingChunks)queueChunk(c);\n"
    "      pendingChunks=[];\n"
    "    }\n"
    "  };\n"
    "  const DEP='serve_overlay';\n"
    "  moduleConfig.preRun.push(function(){\n"
    "    const M=moduleConfig;\n"
    "    M.addRunDependency(DEP);\n"
    "    const origRemove=M.removeRunDependency;\n"
    "    M.removeRunDependency=function(id){\n"
    "      origRemove.call(M,id);\n"
    "      if(id==='datafile_lub.data'){\n"
    "        try{\n"
    "          const FS=M.FS??window.FS;\n"
    "          for(const[p,c]of Object.entries(pendingFiles))"
    "writeFileEnsureDir(FS,p,c);\n"
    "          pendingFiles={};\n"
    "          overlayed=true;\n"
    "          console.log('[serve] game files overlayed');\n"
    "          statusEl.style.display='none';\n"
    "        }catch(e){console.error('[serve] overlay error:',e);}\n"
    "        "
    "finally{origRemove.call(M,DEP);M.removeRunDependency=origRemove;}\n"
    "      }\n"
    "    };\n"
    "  });\n"
    "  window.Module=moduleConfig;\n"
    "  const s=document.createElement('script');\n"
    "  s.src='/wasm/lub.js';\n"
    "  document.body.appendChild(s);\n"
    "}\n"
    "\n"
    "// --- SSE connection ---\n"
    "const es=new EventSource('/events');\n"
    "es.addEventListener('files',e=>receiveFiles(JSON.parse(e.data).files));\n"
    "es.addEventListener('reload',e=>{\n"
    "  const lua=JSON.parse(e.data);\n"
    "  if(runtimeReady)queueChunk(lua);else pendingChunks.push(lua);\n"
    "});\n"
    "// 移行できない変更。書き終わった出力から起動し直す\n"
    "es.addEventListener('restart',e=>{\n"
    "  const reasons=JSON.parse(e.data);\n"
    "  console.warn('tcs: restart required\\n'+reasons);\n"
    "  statusEl.textContent='restarting: '+reasons.split('\\n')[0];\n"
    "  statusEl.style.display='block';\n"
    "  location.reload();\n"
    "});\n"
    "es.onerror=()=>{statusEl.textContent='SSE "
    "disconnected';statusEl.style.display='block';};\n"
    "// 切れている間の reload chunk は届かず、VM は追いつけない。再接続したら\n"
    "// 最新の出力から起動し直す\n"
    "let opened=false;\n"
    "es.onopen=()=>{\n"
    "  if(opened){location.reload();return;}\n"
    "  opened=true;\n"
    "  if(wasmStarted)statusEl.style.display='none';\n"
    "};\n"
    "</script></body></html>\n";

#endif

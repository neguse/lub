#!/bin/bash
# tcs (SelfHost/Compiler、SelfHost/CBackend、SelfHost/VmBackend、SelfHost/Tool) を作り、固定点を確かめる。
#   stage1: .NET の tcs (同じソースを .NET で動かしたもの) が tcs を Lua にしたもの
#   stage2: stage1 (Lua の上、Host/tcsc.lua) が同じソースを Lua にしたもの
#   stage3: stage2 が同じソースを Lua にしたもの。stage2 と byte で一致すれば固定点。実装は 1 つなので stage1 とも一致する
#   C: tcs2c が同じソースを C にし、Native/host.c と build した実行ファイル (out/tcs)。
#      同じソースを変換した出力が stage2 と byte で一致すること (C compiler がある環境だけ。--no-c で省く)
#   C の出力 (tcs c): stage2 (Lua) と out/tcs (C) が tcs 自身を C にした結果が、tcs2c の出力 (out/tcs.c) と byte で一致すること
# 出力は SelfHost/out/ (git に入れない)。out/ には tcs と一緒に配るファイル (runtime/、lib/) も置き、
# out/tcs と out/stage*.lua はそこから読む。
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/SelfHost/out"
LUA="${TCS_LUA:-$ROOT/deps/lua/lua32}"
TCS="$ROOT/Transpiler/bin/Debug/net10.0/Transpiler.dll"
TCS2C="$ROOT/tcs2c/bin/Debug/net10.0/tcs2c.dll"
CC="${CC:-cc}"
mkdir -p "$OUT/runtime" "$OUT/lib/TinySystem"
unset TCS_HOME

# 成功したときの "Wrote ..." は出さず、失敗したときだけ stderr を見せる
run() {
  if ! "$@" 2>"$OUT/last.log"; then
    cat "$OUT/last.log" >&2
    exit 1
  fi
}

if [ ! -f "$TCS" ] || [ -n "${TCS_BUILD:-}" ]; then
  dotnet build "$ROOT/Transpiler" -v q -nologo >/dev/null
fi
cp "$ROOT/runtime/tinysystem.lua" "$ROOT/runtime/module_registry.lua" "$OUT/runtime/"
for d in core math fmt model utf8; do
  mkdir -p "$OUT/runtime/$d"
  cp "$ROOT/runtime/$d"/*.c "$ROOT/runtime/$d"/*.h "$OUT/runtime/$d/"
done
cp "$ROOT/TinySystem/Linq.cs" "$ROOT/TinySystem/ValueTuple.cs" "$OUT/lib/TinySystem/"

# runtime の前置き (web の build が使う): 空のプログラムの出力のうち、変換結果の前の部分
printf '// empty\n' > "$OUT/empty.cs"
run dotnet "$TCS" "$OUT/empty.cs" -o "$OUT/empty.lua"
awk 'NR > 1 && /^-- Generated by TinyC# transpiler$/ { exit } { print }' "$OUT/empty.lua" > "$OUT/prelude.lua"

SRC=("$ROOT"/SelfHost/Compiler/*.cs "$ROOT"/SelfHost/CBackend/*.cs "$ROOT"/SelfHost/VmBackend/*.cs)
for f in "$ROOT"/SelfHost/Tool/*.cs; do
  [ "$(basename "$f")" = TcsHost.cs ] || SRC+=("$f")
done
ARGS=(--ref "$ROOT/SelfHost/Tool/TcsHost.cs" "${SRC[@]}")
run dotnet "$TCS" "${ARGS[@]}" -o "$OUT/stage1.lua"
echo "stage1: .NET -> $OUT/stage1.lua"

if [ "${1:-}" = "--stage1" ]; then exit 0; fi

stage() {
  local t0=$SECONDS
  run "$LUA" "$ROOT/SelfHost/Host/tcsc.lua" "$OUT/$1.lua" "${ARGS[@]}" -o "$OUT/$2.lua"
  echo "$2: $1 -> $OUT/$2.lua ($((SECONDS - t0)) s)"
}
stage stage1 stage2
stage stage2 stage3
same() {
  if cmp -s "$OUT/$1.lua" "$OUT/$2.lua"; then
    echo "$3: $1 == $2"
  else
    echo "$3: $1 != $2" >&2
    diff "$OUT/$1.lua" "$OUT/$2.lua" | head -40 >&2
    exit 1
  fi
}
same stage2 stage3 "fixed point"
# Lua の host も出力の dir が無ければ作る (.NET と C の host と同じ)
rm -rf "$OUT/check-lua"
run "$LUA" "$ROOT/SelfHost/Host/tcsc.lua" "$OUT/stage2.lua" "$ROOT/samples/hello.cs" -o "$OUT/check-lua/new/hello.lua"
echo "Lua host: wrote into a new dir"
same stage1 stage2 ".NET and Lua"

if [ "${1:-}" = "--no-c" ] || ! command -v "$CC" >/dev/null 2>&1; then
  echo "C: skipped"
  exit 0
fi
if [ ! -f "$TCS2C" ] || [ -n "${TCS_BUILD:-}" ]; then
  dotnet build "$ROOT/tcs2c" -v q -nologo >/dev/null
fi
dotnet "$TCS2C" --lib "${ARGS[@]}" -o "$OUT/tcs.c"
"$CC" -O2 -ffp-contract=off -fwrapv -fexcess-precision=standard -I "$OUT" "$ROOT/SelfHost/Native/host.c" -o "$OUT/tcs" -lm
run "$OUT/tcs" "${ARGS[@]}" -o "$OUT/stageC.lua"
echo "C: tcs2c -> $OUT/tcs -> $OUT/stageC.lua"
same stage2 stageC "C build"

# C の出力 (tcs c) の固定点
sameC() {
  if cmp -s "$OUT/tcs.c" "$OUT/$1.c"; then
    echo "$2: tcs.c == $1.c"
  else
    echo "$2: tcs.c != $1.c" >&2
    diff "$OUT/tcs.c" "$OUT/$1.c" | head -40 >&2
    exit 1
  fi
}
t0=$SECONDS
run "$LUA" "$ROOT/SelfHost/Host/tcsc.lua" "$OUT/stage2.lua" c --lib "${ARGS[@]}" -o "$OUT/stage2.c"
echo "tcs c: stage2 -> $OUT/stage2.c ($((SECONDS - t0)) s)"
sameC stage2 "tcs c on Lua"
run "$OUT/tcs" c --lib "${ARGS[@]}" -o "$OUT/stageC.c"
sameC stageC "tcs c on C"

# tcs VM の .tcsb (tcs vm) も Lua と C と .NET で同じ
KERNEL="$ROOT/Transpiler.Tests/DigestKernels/particles.cs"
run dotnet "$TCS" vm --entry Particles "$KERNEL" -o "$OUT/vm.dotnet.tcsb"
run "$LUA" "$ROOT/SelfHost/Host/tcsc.lua" "$OUT/stage2.lua" vm --entry Particles "$KERNEL" -o "$OUT/vm.stage2.tcsb"
run "$OUT/tcs" vm --entry Particles "$KERNEL" -o "$OUT/vm.stageC.tcsb"
for v in stage2 stageC; do
  if cmp -s "$OUT/vm.dotnet.tcsb" "$OUT/vm.$v.tcsb"; then
    echo "tcs vm: dotnet == $v"
  else
    echo "tcs vm: dotnet != $v" >&2
    exit 1
  fi
done

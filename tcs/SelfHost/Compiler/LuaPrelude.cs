using System.Collections.Generic;

namespace TcsSelf;

// chunk の prelude: 言語の lowering 用の chunk-local の helper (整数除算、trunc、Nullable、型判定、float の文字列化、
// `new T[n]`、method group、hot reload の registry)。module mode の define chunk は同名の global (_G 経由、runtime の TinySystem.*)
// へ fallback する (ModuleArtifacts の alias の一覧と対応)。参照実装の LuaEmitter.Prelude.cs を写したもの
public static class LuaPrelude
{
    // 型の table の local の宣言の行を置く印 (全型を出した後に置き換える)
    public const string TypeLocalsPlaceholder = "-- tcs:type-locals";

    // typeLocalsChunk: 型の local の宣言の行を置く断片の位置 (無ければ -1)
    public static int Emit(LuaGen g, bool instanceRegistry, bool trace, bool typeLocals)
    {
        g.AppendLine("-- Generated by TinyC# transpiler");
        // C# の整数除算/剰余 (0 方向 truncation) は Lua の // と % (floor
        // 由来) と負数で結果がずれるため、言語 lowering 用 helper を
        // chunk-local で常時定義する (--no-runtime でも動く言語機能)。
        // module mode の define chunk は同名 global (_G 経由、runtime の
        // TinySystem.idiv/irem) へ fallback する。
        g.AppendLine("local function __tcs_idiv(a, b)");
        g.AppendLine("  local q = a // b");
        g.AppendLine("  if a % b ~= 0 and (a < 0) ~= (b < 0) then q = q + 1 end");
        g.AppendLine("  return q");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_irem(a, b)");
        g.AppendLine("  return a - __tcs_idiv(a, b) * b");
        g.AppendLine("end");
        // List / 配列の添字は範囲外で fault する (il-spec §12)。値型の要素は nil を
        // 持たないので、範囲内の key は必ず値を持つ (読み書きとも nil なら範囲外)。
        // 要素が null になりうる List は nil か false を読んだときだけ長さと比べる
        g.AppendLine("local function __tcs_oob() error(\"Index was out of range.\") end");
        g.AppendLine("local function __tcs_get(t, i)");
        g.AppendLine("  local v = t[i + 1]");
        g.AppendLine("  if v == nil then __tcs_oob() end");
        g.AppendLine("  return v");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_set(t, i, v)");
        g.AppendLine("  if t[i + 1] == nil then __tcs_oob() end");
        g.AppendLine("  t[i + 1] = v");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_count(t) return t.n or #t end");
        g.AppendLine("local function __tcs_lchk(t, i)");
        g.AppendLine("  if i < 0 or i >= (t.n or #t) then __tcs_oob() end");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_lget(t, i)");
        g.AppendLine("  local v = t[i + 1]");
        g.AppendLine("  if not v then __tcs_lchk(t, i) end");
        g.AppendLine("  return v");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_lset(t, i, v)");
        g.AppendLine("  if t[i + 1] == nil then __tcs_lchk(t, i) end");
        g.AppendLine("  t[i + 1] = v");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_u8at(u, i)");
        g.AppendLine("  if i < 0 or i >= u.Length then __tcs_oob() end");
        g.AppendLine("  return string.byte(u.s, u.o + i + 1)");
        g.AppendLine("end");
        // checked(expr) の i32 の + - * と単項 - は overflow で fault する (il-spec §5)。
        // LUA_32BITS の integer は wrap するので、wrap の向きでも検出する
        g.AppendLine("local function __tcs_overflow() error(\"Arithmetic operation resulted in an overflow.\") end");
        g.AppendLine("local function __tcs_cadd(a, b)");
        g.AppendLine("  local s = a + b");
        g.AppendLine("  if s > 2147483647 or s < -2147483648 or (b < 0) ~= (s < a) then __tcs_overflow() end");
        g.AppendLine("  return s");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_csub(a, b)");
        g.AppendLine("  local d = a - b");
        g.AppendLine("  if d > 2147483647 or d < -2147483648 or (b > 0) ~= (d < a) then __tcs_overflow() end");
        g.AppendLine("  return d");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_cmul(a, b)");
        g.AppendLine("  local p = a * b");
        g.AppendLine("  if p > 2147483647 or p < -2147483648");
        g.AppendLine("      or a ~= 0 and (p // a ~= b or a == -1 and b == -2147483648) then __tcs_overflow() end");
        g.AppendLine("  return p");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_cneg(a)");
        g.AppendLine("  if a == -2147483648 then __tcs_overflow() end");
        g.AppendLine("  return -a");
        g.AppendLine("end");
        // C# の (int)f は 0 方向 truncation で整数になる。Lua の float を
        // そのまま流すと 2.7 のまま残る (添字・%d・整数演算で乖離) ため、
        // float→int cast は常にこの helper を通す (C backend も同じ契約)
        g.AppendLine("local function __tcs_trunc(x)");
        g.AppendLine("  local i = math.tointeger(x)");
        g.AppendLine("  if i then return i end");
        g.AppendLine("  if x >= 0 then return math.floor(x) end");
        g.AppendLine("  return math.ceil(x)");
        g.AppendLine("end");
        // (char)x: char は 1 byte の code unit
        g.AppendLine("local function __tcs_char(x)");
        g.AppendLine("  if x < 0 or x > 255 then error(\"(char) cast: value is not in 0-255; use char.ConvertFromUtf32 for a codepoint\") end");
        g.AppendLine("  return x");
        g.AppendLine("end");
        // float.Parse: tonumber は整数の文字列を integer で返すので float に
        // する (不正な文字列の nil はそのまま)
        g.AppendLine("local function __tcs_tofloat(v)");
        g.AppendLine("  if v == nil then return nil end");
        g.AppendLine("  return v * 1.0");
        g.AppendLine("end");
        // Math.Min / Max は MathF.Min / Max (NaN を伝播、-0 < +0)。Lua の
        // math.min / max は同値・NaN で第 1 引数を返すので helper を通す。
        // 本体は runtime の TinySystem.Math.Min / Max と同じ
        g.AppendLine("local function __tcs_min(a, b)");
        g.AppendLine("  if a < b then return a end");
        g.AppendLine("  if b < a then return b end");
        g.AppendLine("  if a ~= a or (a == 0 and 1 / a < 0) then return a end");
        g.AppendLine("  return b");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_max(a, b)");
        g.AppendLine("  if a > b then return a end");
        g.AppendLine("  if b > a then return b end");
        g.AppendLine("  if a ~= a or (b == 0 and 1 / b < 0) then return a end");
        g.AppendLine("  return b");
        g.AppendLine("end");
        // C# のシフト: count は 31 でマスク、int の >> は算術 (符号拡張)。
        // Lua native は count 無マスク・>> 論理なので helper を通す
        g.AppendLine("local function __tcs_shl(a, n) return a << (n & 31) end");
        g.AppendLine("local function __tcs_shr(a, n)");
        g.AppendLine("  n = n & 31");
        g.AppendLine("  if a >= 0 then return a >> n end");
        g.AppendLine("  return ~((~a) >> n)");
        g.AppendLine("end");
        // Nullable<T> (il-spec §13): nil = 値なし。.Value の値なしは fault、
        // lifted 演算は片方でも nil なら nil (比較は false)、bool? の & |
        // は三値論理。op 関数は定数なので closure 確保は無い
        g.AppendLine("local function __tcs_nval(v)");
        g.AppendLine("  if v == nil then error(\"Nullable object must have a value\") end");
        g.AppendLine("  return v");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_nget(v, d) if v == nil then return d end return v end");
        g.AppendLine("local function __tcs_nlift(a, b, f) if a == nil or b == nil then return nil end return f(a, b) end");
        g.AppendLine("local function __tcs_nlift1(a, f) if a == nil then return nil end return f(a) end");
        g.AppendLine("local function __tcs_ncmp(a, b, f) if a == nil or b == nil then return false end return f(a, b) end");
        g.AppendLine("local function __tcs_nand(a, b)");
        g.AppendLine("  if a == false or b == false then return false end");
        g.AppendLine("  if a == nil or b == nil then return nil end");
        g.AppendLine("  return true");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_nor(a, b)");
        g.AppendLine("  if a == true or b == true then return true end");
        g.AppendLine("  if a == nil or b == nil then return nil end");
        g.AppendLine("  return false");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_nnot(a) if a == nil then return nil end return not a end");
        g.AppendLine("local function __tcs_op_add(a, b) return a + b end");
        g.AppendLine("local function __tcs_op_sub(a, b) return a - b end");
        g.AppendLine("local function __tcs_op_mul(a, b) return a * b end");
        g.AppendLine("local function __tcs_op_div(a, b) return a / b end");
        g.AppendLine("local function __tcs_op_idiv(a, b) return __tcs_idiv(a, b) end");
        g.AppendLine("local function __tcs_op_irem(a, b) return __tcs_irem(a, b) end");
        g.AppendLine("local function __tcs_op_fmod(a, b) return math.fmod(a, b) end");
        g.AppendLine("local function __tcs_op_band(a, b) return a & b end");
        g.AppendLine("local function __tcs_op_bor(a, b) return a | b end");
        // bool? の ^ は boolean xor (a ~= b)
        g.AppendLine("local function __tcs_op_bxor(a, b) if type(a) == \"boolean\" then return a ~= b end return a ~ b end");
        g.AppendLine("local function __tcs_op_shl(a, b) return __tcs_shl(a, b) end");
        g.AppendLine("local function __tcs_op_shr(a, b) return __tcs_shr(a, b) end");
        g.AppendLine("local function __tcs_op_lt(a, b) return a < b end");
        g.AppendLine("local function __tcs_op_le(a, b) return a <= b end");
        g.AppendLine("local function __tcs_op_gt(a, b) return a > b end");
        g.AppendLine("local function __tcs_op_ge(a, b) return a >= b end");
        g.AppendLine("local function __tcs_op_neg(a) return -a end");
        g.AppendLine("local function __tcs_op_tofloat(a) return a * 1.0 end");
        g.AppendLine("local function __tcs_op_bnot(a) return ~a end");
        // C# の `is T` は「T またはその派生」(il-spec §9)。継承は
        // instance の metatable = class table、class table の
        // metatable.__index = base で表現しているため chain を辿る。
        g.AppendLine("local function __tcs_is(x, T)");
        g.AppendLine("  local mt = getmetatable(x)");
        g.AppendLine("  while mt do");
        g.AppendLine("    if mt == T then return true end");
        g.AppendLine("    local link = getmetatable(mt)");
        g.AppendLine("    mt = link and link.__index");
        g.AppendLine("  end");
        g.AppendLine("  return false");
        g.AppendLine("end");
        // class の interface の検査 (il-spec §9)。class table の __interfaces は実装する interface の名前の集合
        g.AppendLine("local function __tcs_implements(x, name)");
        g.AppendLine("  local mt = getmetatable(x)");
        g.AppendLine("  local set = mt and mt.__interfaces");
        g.AppendLine("  return set ~= nil and set[name] == true");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_castfail() error(\"Specified cast is not valid.\") end");
        g.AppendLine("local function __tcs_cast(x, T)");
        g.AppendLine("  if x ~= nil and not __tcs_is(x, T) then __tcs_castfail() end");
        g.AppendLine("  return x");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_icast(x, name)");
        g.AppendLine("  if x ~= nil and not __tcs_implements(x, name) then __tcs_castfail() end");
        g.AppendLine("  return x");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_tcast(x, t)");
        g.AppendLine("  if x ~= nil and type(x) ~= t then __tcs_castfail() end");
        g.AppendLine("  return x");
        g.AppendLine("end");
        // 値型への unbox は null も fault
        g.AppendLine("local function __tcs_vcast(x, t)");
        g.AppendLine("  if type(x) ~= t then __tcs_castfail() end");
        g.AppendLine("  return x");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_ncast(x, t)");
        g.AppendLine("  if math.type(x) ~= t then __tcs_castfail() end");
        g.AppendLine("  return x");
        g.AppendLine("end");
        // f32 の既定の文字列化 (il-spec §13)。
        // .NET の float.ToString() と同じ文字列を、host が登録する tcs_rt (runtime/lua/tcs_rt_lua.c) が作る
        g.AppendLine("local function __tcs_fstr(v) return tcs_rt.fstr(v) end");
        // `new T[n]` (値型 T): default を n 個詰めた sequence。init が
        // 関数 (struct の zero ctor) なら要素ごとに fresh な値
        // struct を入れた型引数の既定値は zero 値と copy の作り方 (記述子 `{__tcs_td = true, n, c}`)。
        // 既定値は使うたびに新しい zero 値、型引数の型の field / 要素への代入は copy
        g.AppendLine("local function __tcs_dv(d)");
        g.AppendLine("  if type(d) == \"table\" and d.__tcs_td then return d.n() end");
        g.AppendLine("  return d");
        g.AppendLine("end");
        // `new T()` の型引数。class を入れた型引数は作り方を持たない (既定値は null)
        g.AppendLine("local function __tcs_nt(d)");
        g.AppendLine("  if d == nil then error(\"new T() of a class type argument is not supported\") end");
        g.AppendLine("  return __tcs_dv(d)");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_tc(d, v)");
        g.AppendLine("  if type(d) == \"table\" and d.__tcs_td then return d.c(v) end");
        g.AppendLine("  return v");
        g.AppendLine("end");
        g.AppendLine("local function __tcs_arr(n, init)");
        g.AppendLine("  local t = {}");
        g.AppendLine("  if type(init) == \"function\" then");
        g.AppendLine("    for i = 1, n do t[i] = init() end");
        g.AppendLine("  elseif type(init) == \"table\" and init.__tcs_td then");
        g.AppendLine("    for i = 1, n do t[i] = init.n() end");
        g.AppendLine("  else");
        g.AppendLine("    for i = 1, n do t[i] = init end");
        g.AppendLine("  end");
        g.AppendLine("  return t");
        g.AppendLine("end");
        // T? と object の文字列化: null は C# と同じく空文字列
        // class の値は ToString の override を呼ぶ。他の table (override の無い class / record /
        // struct / List / Dictionary の値) の文字列化はサブセット外 (TCS1001 UnsupportedToString)。
        // object / 型引数の値は実行時に fault する
        // bool は .NET と同じ True / False
        // multi-return のタプルを保持するときの struct の table
        for (int arity = 2; arity <= 7; arity++)
        {
            var names = new List<string>();
            var fields = new List<string>();
            for (int k = 1; k <= arity; k++)
            {
                names.Add("v" + k);
                fields.Add("Item" + k + " = v" + k);
            }
            g.AppendLine("local function __tcs_tuple" + arity + "(" + string.Join(", ", names) + ") return {" + string.Join(", ", fields) + "} end");
        }
        g.AppendLine("local function __tcs_bstr(b) return b and \"True\" or \"False\" end");
        g.AppendLine("local function __tcs_nstr(v)");
        g.AppendLine("  if v == nil then return \"\" end");
        g.AppendLine("  if math.type(v) == \"float\" then return __tcs_fstr(v) end");
        g.AppendLine("  if type(v) == \"boolean\" then return __tcs_bstr(v) end");
        g.AppendLine("  if type(v) == \"table\" then");
        g.AppendLine("    local mt = getmetatable(v)");
        g.AppendLine("    if mt and mt.ToString then return mt.ToString(v) or \"\" end");
        g.AppendLine("    error(\"ToString of this value is not supported\")");
        g.AppendLine("  end");
        g.AppendLine("  return tostring(v)");
        g.AppendLine("end");
        // enum を入れた型引数の記述子 (名前の表ごとに 1 つ。module mode は TinySystem.etd)
        g.AppendLine("local __tcs_etd = __tcs_etd");
        g.AppendLine("if __tcs_etd == nil then");
        g.AppendLine("  local cache = {}");
        g.AppendLine("  __tcs_etd = function(spec)");
        g.AppendLine("    local d = cache[spec]");
        g.AppendLine("    if d then return d end");
        g.AppendLine("    d = {__tcs_td = true, n = function() return 0 end, c = function(v) return v end,");
        g.AppendLine("      s = function(v) return String.FormatEnum(v, spec) end}");
        g.AppendLine("    cache[spec] = d");
        g.AppendLine("    return d");
        g.AppendLine("  end");
        g.AppendLine("end");
        // 型引数の値の文字列化。記述子が名前の引き方 (enum) を持てば使う
        g.AppendLine("local function __tcs_tstr(d, v)");
        g.AppendLine("  if type(d) == \"table\" and d.s then return d.s(v) end");
        g.AppendLine("  return __tcs_nstr(v)");
        g.AppendLine("end");
        // static method group の struct parameter を copy してから呼ぶ wrapper (il-spec §10)。
        // c は parameter ごとの copy 関数 (不要なら false)。
        // 同じ関数には同じ wrapper を返す。cache は chunk をまたいで 1 つにする (module mode は TinySystem.mg)
        g.AppendLine("local __tcs_mg = __tcs_mg");
        g.AppendLine("if __tcs_mg == nil then");
        g.AppendLine("  local cache = setmetatable({}, { __mode = \"k\" })");
        g.AppendLine("  __tcs_mg = function(f, c1, c2, ...)");
        g.AppendLine("    local w = cache[f]");
        g.AppendLine("    if w then return w end");
        g.AppendLine("    if c2 == nil then");
        g.AppendLine("      w = function(a) return f(c1(a)) end");
        g.AppendLine("    elseif select(\"#\", ...) == 0 then");
        g.AppendLine("      w = function(a, b)");
        g.AppendLine("        if c1 then a = c1(a) end");
        g.AppendLine("        if c2 then b = c2(b) end");
        g.AppendLine("        return f(a, b)");
        g.AppendLine("      end");
        g.AppendLine("    else");
        g.AppendLine("      local cs = { c1, c2, ... }");
        g.AppendLine("      w = function(...)");
        g.AppendLine("        local args = table.pack(...)");
        g.AppendLine("        for i = 1, #cs do");
        g.AppendLine("          if cs[i] then args[i] = cs[i](args[i]) end");
        g.AppendLine("        end");
        g.AppendLine("        return f(table.unpack(args, 1, args.n))");
        g.AppendLine("      end");
        g.AppendLine("    end");
        g.AppendLine("    cache[f] = w");
        g.AppendLine("    return w");
        g.AppendLine("  end");
        g.AppendLine("end");
        // hot reload (il-design §6): 生存インスタンスの weak registry (opt-in)。
        // reload chunk と共有するため global。key = instance (weak)、value = 構築時の class table (reload 後も identity 不変)
        if (instanceRegistry)
            g.AppendLine("__tcs_instances = __tcs_instances or "
                + "setmetatable({}, { __mode = \"k\" })");
        // --trace: 実行した行の記録は host が読む global。出力も reload chunk も既存の table を置き換えず (host は in place で消す)、
        // global の lookup を省くため chunk-local に alias する
        if (trace)
        {
            g.AppendLine("__tcs_trace = __tcs_trace or {}");
            g.AppendLine("local __tcs_trace = __tcs_trace");
            g.AppendLine("__tcs_trace_classes = __tcs_trace_classes or {}");
        }
        // 型の table の chunk-local の宣言。名前は全型を出した後でしか確定しないので、行ごと置き換える (行数を変えず source map を保つ)
        if (typeLocals)
        {
            int at = g.Chunks.Count;
            g.AppendLine(TypeLocalsPlaceholder);
            return at;
        }
        return -1;
    }
}

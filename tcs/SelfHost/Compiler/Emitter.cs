            case "List.Contains": return "List.Contains(" + recv + ", " + a0 + EqArg(rt) + ")";
            case "List.IndexOf": return "List.IndexOf(" + recv + ", " + a0 + EqArg(rt) + ")";
            case "List.Clear":
                {
                    string l = SpillForStatement(recv);

    private string BuiltinCall(Node e, Symbol m, bool asStatement)
    {
        var callee = e.A!;
        string recv = "";
        TypeSym? rt = null;
        var nodes = new List<Node>();
        bool hasRecv = !m.IsStatic && callee.Kind == NodeKind.Member;
        if (hasRecv)
        {
            nodes.Add(callee.A!);
            rt = callee.A!.Type;
        }
        for (int i = 0; i < e.Count; i++)
        {
            if (!e.Item(i).Has(Mods.Out)) nodes.Add(e.Item(i).A!);
        }
        List<string> t;
        if (hasRecv && _condRecv.TryGetValue(callee.A!, out var cr))
        {
            nodes.RemoveAt(0);
            t = EmitOperands(nodes);
            CopyOperands(nodes, t);
            t.Insert(0, cr);
        }
        else
        {
            t = EmitOperands(nodes);
            if (hasRecv)
            {
                var argNodes = new List<Node>();
                var argTexts = new List<string>();
                for (int i = 1; i < nodes.Count; i++)
                {
                    argNodes.Add(nodes[i]);
                    argTexts.Add(t[i]);
                }
                CopyOperands(argNodes, argTexts);
                for (int i = 1; i < nodes.Count; i++) t[i] = argTexts[i - 1];
            }
            else CopyOperands(nodes, t);
        }
        if (hasRecv)
        {
            recv = t[0];
            t.RemoveAt(0);
        }
        string a0 = t.Count > 0 ? t[0] : "";
        string a1 = t.Count > 1 ? t[1] : "";
        string a2 = t.Count > 2 ? t[2] : "";
        string args = string.Join(", ", t);
        switch (m.Builtin)
        {
            case "List.Add":
                {
                    if (rt != null && rt.Elem.Kind == TypeKind.TypeParam) return "List.Add(" + recv + ", " + a0 + ")";
                    if (rt != null && NilElements(rt)) return "List.AddCounted(" + recv + ", " + a0 + ")";

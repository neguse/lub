    // 代入先。受け手と key は評価済みの Lua の式で、読む式と書く文を組み立てる
    sealed class LValue
    {
        public const int Plain = 0;
        public const int Field = 1;
        public const int Accessor = 2;
        public const int ListIndex = 3;
        public const int DictIndex = 4;
        public int Kind;
        public string Recv = "";
        public string Key = "";
        public string Name = "";
        public bool IsStatic;
        // struct の property の accessor は静的な関数 (Owner.get_P(recv))
        public string StructOwner = "";
        // 受け手が書き換わらない (型の table、self、temp)
        public bool Stable;
        // 書くときに struct の鎖を辿り直す (右辺の呼び出しが鎖の途中の struct を置き換えうる)
        public bool Rewalk;

        public string Read()
        {
            switch (Kind)
            {
                case Field: return Recv + Emitter.FieldAccess(Name);
                case Accessor:
                    if (StructOwner != "") return StructOwner + ".get_" + Name + "(" + Recv + ")";
                    return Recv + (IsStatic ? "." : ":") + "get_" + Name + "()";
                case ListIndex: return "(" + Recv + "[" + Emitter.Plus1(Key) + "] or __tcs_lget(" + Recv + ", " + Key + "))";
                case DictIndex: return Recv + "[" + Key + "]";
            }
            return Name;
        }

        public string Write(string v)
        {
            // ( で始まる文は前の行の続き (関数の呼び出し) に読まれるので ; を前に置く
            string r = Recv.StartsWith("(") ? ";" + Recv : Recv;
            switch (Kind)
            {
                case Field: return r + Emitter.FieldAccess(Name) + " = " + v;
                case Accessor:
                    if (StructOwner != "") return StructOwner + ".set_" + Name + "(" + Recv + ", " + v + ")";
                    return r + (IsStatic ? "." : ":") + "set_" + Name + "(" + v + ")";
                case ListIndex: return "__tcs_lset(" + Recv + ", " + Key + ", " + v + ")";
                case DictIndex: return r + "[" + Key + "] = " + v;
            }
            return Name + " = " + v;
        }
    }

    public static string Plus1(string idx) => IsIntLiteral(idx) ? IntLiteral(ParseIntText(idx) + 1) : idx + " + 1";

    private LValue EmitLValue(Node target)
    {
        var lv = new LValue();
        var t = target.Kind == NodeKind.Paren ? target.A! : target;
        switch (t.Kind)
        {
            case NodeKind.Name:
            case NodeKind.Member:
                {
                    if (t.Info == RefKind.Local)
                    {
                        lv.Name = t.Local!.LuaName;
                        lv.Stable = true;
                        return lv;
                    }
                    var sym = t.Sym!;
                    lv.Name = sym.Name;
                    lv.IsStatic = sym.IsStatic;
                    if (sym.IsStatic)
                    {
                        lv.Recv = sym.Owner != null ? sym.Owner.LuaName : "_ENV";
                        lv.Stable = true;
                    }
                    else if (t.Kind == NodeKind.Member && IsMutableStruct(t.A!.Type) && IsStructPath(t.A))
                    {
                        // struct の field の鎖: 根 (class の object など) だけを固定し、書くときに鎖を辿り直す
                        lv.Recv = StructPathText(t.A);
                        lv.Stable = true;
                        lv.Rewalk = true;
                    }
                    else if (t.Kind == NodeKind.Member)
                    {
                        lv.Recv = Paren(SpillIfComplex(ReceiverText(t.A!)));
                        lv.Stable = lv.Recv == "self" || IsTempName(lv.Recv);
                    }
                    else
                    {
                        lv.Recv = "self";
                        lv.Stable = true;
                    }
                    bool viaInterface = t.Kind == NodeKind.Member && t.A!.Type != null && t.A.Type.Kind == TypeKind.Interface;
                    lv.Kind = sym.Kind == SymKind.Property && (!IsFieldBacked(sym) || viaInterface) ? LValue.Accessor : LValue.Field;
                    if (lv.Kind == LValue.Accessor && sym.Owner != null && sym.Owner.IsStruct && !sym.IsStatic) lv.StructOwner = sym.Owner.LuaName;
                    return lv;
                }
            case NodeKind.Index:
                {
                    var rt = t.A!.Type!;
                    lv.Recv = SpillIfComplex(ReceiverText(t.A));
                    lv.Key = SpillIfComplex(Expr(t.Item(0)));
                    lv.Kind = rt.Kind == TypeKind.Dict || UncheckedArray(rt) ? LValue.DictIndex : LValue.ListIndex;
                    if (UncheckedArray(rt)) lv.Key = Plus1(lv.Key);
                    if (FloatKeyed(rt)) lv.Key = PinText("Dict.FloatKey(" + lv.Key + ")");
                    lv.Stable = (IsTempName(lv.Recv) || lv.Recv == "self") && (IsTempName(lv.Key) || IsLiteralText(lv.Key));
                    return lv;
                }
        }
        lv.Name = "_";
        return lv;
    }

    // struct の変数の鎖 (局所変数、field、static field、配列の要素の struct の field)
    private bool IsStructPath(Node n)
    {
        if (_condRecv.ContainsKey(n)) return false;
        switch (n.Kind)
        {
            case NodeKind.Paren:
                return IsStructPath(n.A!);
            case NodeKind.Name:
            case NodeKind.Member:
                return n.Info == RefKind.Local || n.Info == RefKind.Field;
            case NodeKind.Index:
                return n.A!.Type != null && n.A.Type.Kind == TypeKind.Array;
        }
        return false;
    }

    // 鎖の Lua の式。class の受け手は temp に固定する
    private string StructPathText(Node n)
    {
        switch (n.Kind)
        {
            case NodeKind.Paren:
                return StructPathText(n.A!);
            case NodeKind.Name:
                if (n.Info == RefKind.Local) return n.Local!.LuaName;
                if (n.Sym!.IsStatic) return n.Sym.Owner!.LuaName + FieldAccess(n.Sym.Name);
                return "self" + FieldAccess(n.Sym.Name);
            case NodeKind.Member:
                {
                    if (n.Info == RefKind.Local) return n.Local!.LuaName;
                    var sym = n.Sym!;
                    if (sym.IsStatic) return sym.Owner!.LuaName + FieldAccess(sym.Name);
                    var recv = n.A!;
                    string rt;
                    if (IsMutableStruct(recv.Type) && IsStructPath(recv)) rt = StructPathText(recv);
                    else
                    {
                        rt = ReceiverText(recv);
                        if (!IsTempName(rt) && rt != "self" && !(recv.Kind == NodeKind.Name && recv.Info == RefKind.Local)) rt = PinText(rt);
                    }
                    return (IsPathText(rt) ? rt : "(" + rt + ")") + FieldAccess(sym.Name);
                }
            case NodeKind.Index:
                {
                    string arr = PinText(ReceiverText(n.A!));
                    string idx = PinText(Expr(n.Item(0)));
                    return "(" + arr + "[" + Plus1(idx) + "] or __tcs_lget(" + arr + ", " + idx + "))";
                }
        }
        return Expr(n);
    }

    // a.b.c / a["k"] の形 (括弧で囲まなくても受け手になれる)
    private static bool IsPathText(string v)
    {
        var u = new Utf8Bytes(v);
        if (u.Length == 0) return false;
        int c0 = u[0];
        if (!(c0 >= 'a' && c0 <= 'z' || c0 >= 'A' && c0 <= 'Z' || c0 == '_')) return false;
        for (int i = 0; i < u.Length; i++)
        {
            int c = u[i];
            if (!(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c == '_' || c >= '0' && c <= '9' || c == '.')) return false;
        }
        return true;
    }

    private string PinText(string v)
    {
        if (IsTempName(v) || IsLiteralText(v) || v == "self") return v;
        string t = NewTemp();
        Line("local " + t + " = " + v);
        return t;
    }

    // 右辺の前置きの文が受け手と key を書き換えても、書く先が変わらないように temp に入れる
    private void PinLValue(LValue lv)
    {
        if (lv.Stable) return;
        if (lv.Kind == LValue.Plain) return;
        if (!IsTempName(lv.Recv) && lv.Recv != "self" && !lv.IsStatic)
        {
            string t = NewTemp();
            Line("local " + t + " = " + lv.Recv);
            lv.Recv = t;
        }
        if ((lv.Kind == LValue.ListIndex || lv.Kind == LValue.DictIndex) && !IsTempName(lv.Key) && !IsLiteralText(lv.Key))
        {
            string t = NewTemp();
            Line("local " + t + " = " + lv.Key);
            lv.Key = t;
        }
        lv.Stable = true;
    }

    // 値を 1 度だけ評価するため、単純な名前でなければ temp に入れる
    private string Spill(string v)
    {
        if (IsSimpleName(v) || IsLiteralText(v)) return v;
        string t = NewTemp();
        Line("local " + t + " = " + v);
        return t;
    }

    private static bool IsTempName(string v) => v.StartsWith("__t") && IsSimpleName(v);

    private static bool IsLiteralText(string v)
    {
        var u = new Utf8Bytes(v);
        if (u.Length == 0) return false;
        int c = u[0];
        if (c == '"') return true;
        if (c >= '0' && c <= '9') return true;
        return v == "nil" || v == "true" || v == "false";
    }

    private string EmitAssign(Node e, bool asExpr)
    {
        string op = e.Text;
        var target = e.A!;
        if (e.Info == 2)
        {
            // _ = expr
            string dv = Expr(e.B!);
            if (asExpr) return Spill(dv);
            if (IsCallText(dv)) Line(dv);
            else if (!IsSimpleName(dv) && !IsLiteralText(dv)) Line("local _ = " + dv);
            return "";
        }
        if (op == "=")
        {
            var lv = EmitLValue(target);
            int mark = _out.Count;
            string v = Val(e.B!);
            if (_out.Count > mark && !lv.Stable)
            {
                var pre = Extract(mark);
                PinLValue(lv);
                foreach (var p in pre) _out.Add(p);
            }
            if (asExpr || lv.Rewalk && MayCall(e.B!))
            {
                // Lua は代入先の受け手を右辺より先に評価するので、値を先に temp に入れてから書く
                v = PinText(v);
                // set accessor は値の引数を書き換えうるので、式の値とは別の copy を渡す
                if (asExpr && lv.Kind == LValue.Accessor && IsMutableStruct(e.B!.Type)) Line(lv.Write(e.B.Type!.Decl!.LuaName + ".__copy(" + v + ")"));
                else Line(lv.Write(v));
                return v;
            }
            Line(lv.Write(v));
            return "";
        }
        if (op == "??=")
        {
            var lv = EmitLValue(target);
            PinLValue(lv);
            string cur = NewTemp();
            Line("local " + cur + " = " + lv.Read());
            Line("if " + cur + " == nil then");
            _indent++;
            string v = Val(e.B!);
            Line(cur + " = " + v);
            Line(lv.Write(cur));
            _indent--;
            Line("end");
            return cur;
        }
        string bop = op.Replace("=", "");
        var lv2 = EmitLValue(target);
        string read = lv2.Read();
        int rmark = _out.Count;
        string rhs = Expr(e.B!);
        if (_out.Count > rmark)
        {
            // 右辺の前置きの文の前に、書く先を固定し今の値を読む
            var pre = Extract(rmark);
            PinLValue(lv2);
            string cur = NewTemp();
            Line("local " + cur + " = " + lv2.Read());
            read = cur;
            foreach (var p in pre) _out.Add(p);
        }
        string value;
        if (e.Sym != null)
        {
            string? lf = CopyFunc(target);
            string? rf = CopyFunc(e.B!);
            value = e.Sym.Owner!.LuaName + "." + e.Sym.LuaName + "(" + (lf != null ? lf + "(" + read + ")" : read) + ", " + (rf != null ? rf + "(" + rhs + ")" : rhs) + ")";
        }
        else if (e.Info == 1) value = "(" + StringOperand(read, target.Type!, target) + " .. " + StringOperand(rhs, e.B!.Type!, e.B) + ")";
        else value = ArithText(bop, read, rhs, e.Type2 ?? target.Type!, target.Type!);
        if (asExpr || lv2.Rewalk && MayCall(e.B!))
        {
            value = PinText(value);
            Line(lv2.Write(value));
            return value;
        }
        Line(lv2.Write(value));
        return "";
    }

    private string EmitIncDec(Node e, bool asExpr)
    {
        var lv = EmitLValue(e.A!);
        var t = e.Type!;
        string one = t.Kind == TypeKind.Float ? "1.0" : "1";
        string op = e.Text == "++" ? " + " : " - ";
        if (!asExpr)
        {
            Line(lv.Write(lv.Read() + op + one));
            return "";
        }
        PinLValue(lv);
        if (e.Kind == NodeKind.PostIncDec)
        {
            string old = NewTemp();
            Line("local " + old + " = " + lv.Read());
            Line(lv.Write(old + op + one));
            return old;
        }
        string nv = NewTemp();
        Line("local " + nv + " = " + lv.Read() + op + one);
        Line(lv.Write(nv));
        return nv;
    }

    // ---- 式 ----

    private static string Paren(string s)
    {
        if (IsSimpleName(s) || IsLiteralText(s)) return s;
        var u = new Utf8Bytes(s);
        if (u.Length >= 2 && u[0] == '(' && u[u.Length - 1] == ')' && Balanced(u)) return s;
        return "(" + s + ")";
    }

    // 先頭の ( が最後の ) と対応するか
    private static bool Balanced(Utf8Bytes u)
    {
        int depth = 0;
        bool inStr = false;
        for (int i = 0; i < u.Length; i++)
        {
            int c = u[i];
            if (inStr)
            {
                if (c == '\\') i++;
                else if (c == '"') inStr = false;
                continue;
            }
            if (c == '"') inStr = true;
            else if (c == '(') depth++;
            else if (c == ')')
            {
                depth--;
                if (depth == 0 && i != u.Length - 1) return false;
            }
        }
        return true;
    }

    private string Expr(Node e)
    {
        if (e.HasConst && e.Kind != NodeKind.Assign && e.Kind != NodeKind.Call) return ConstText(e.Const!, e.Type!);
        switch (e.Kind)
        {
            case NodeKind.Conv: return ConvText(e);
            case NodeKind.Paren: return Expr(e.A!);
            case NodeKind.Checked: return Expr(e.A!);
            case NodeKind.NullLit: return "nil";
            case NodeKind.DefaultLit:
                if (e.Type!.Kind == TypeKind.TypeParam) return "__tcs_dv(" + DescText(e.Type) + ")";
                return DefaultValue(e.Type) ?? "nil";
            case NodeKind.This: return "self";
            case NodeKind.Name: return NameText(e);
            case NodeKind.Member:
                if (e.CondTop) return GuardedChain(e, false);
                return MemberText(e);
            case NodeKind.Call:
                if (e.CondTop) return GuardedChain(e, false);
                return EmitCall(e, false);
            case NodeKind.Index:
                if (e.CondTop) return GuardedChain(e, false);
                return IndexText(e);
            case NodeKind.InterpString: return InterpText(e);
            case NodeKind.Binary: return BinaryText(e);
            case NodeKind.Unary: return UnaryText(e);
            case NodeKind.Assign: return EmitAssign(e, true);
            case NodeKind.PostIncDec:
            case NodeKind.PreIncDec:
                return EmitIncDec(e, true);
            case NodeKind.Conditional: return ConditionalText(e);
            case NodeKind.Is: return IsText(e);
            case NodeKind.As: return AsText(e);
            case NodeKind.Cast: return CastText(e);
            case NodeKind.Lambda: return LambdaText(e);
            case NodeKind.New: return NewText(e);
            case NodeKind.NewArray: return NewArrayText(e);
            case NodeKind.ArrayInit: return ArrayInitText(e);
            case NodeKind.CollectionExpr: return CollectionText(e);
            case NodeKind.SwitchExpr: return SwitchExprText(e);
        }
        return "nil";
    }

    private string NameText(Node e)
    {
        switch (e.Info)
        {
            case RefKind.Local: return e.Local!.LuaName;
            case RefKind.Field:
            case RefKind.Property:
                {
                    var sym = e.Sym!;
                    string recv = sym.IsStatic ? sym.Owner!.LuaName : "self";
                    return MemberValueText(recv, sym, false);
                }
            case RefKind.Type:
                if (e.Type != null && e.Type.Decl != null) return e.Type.Decl.LuaName;
                return "nil";
            case RefKind.MethodGroup:
                return MethodGroupText(e, null);
        }
        return "nil";
    }

    private string MemberValueText(string recv, Symbol sym, bool viaInterface)
    {
        if (sym.Builtin != "") return BuiltinPropValue(sym, recv, null);
        if (sym.Kind == SymKind.Property && (!IsFieldBacked(sym) || viaInterface))
        {
            if (sym.Owner != null && sym.Owner.IsStruct && !sym.IsStatic) return sym.Owner.LuaName + ".get_" + sym.Name + "(" + recv + ")";
            return recv + (sym.IsStatic ? "." : ":") + "get_" + sym.Name + "()";
        }
        return recv + FieldAccess(sym.Name);
    }

    private string MemberText(Node e)
    {
        if (e.Value == 1) return ConditionalAccess(e);
        if (e.Info == RefKind.Type)
        {
            if (e.Type != null && e.Type.Decl != null) return e.Type.Decl.LuaName;
            return "nil";
        }
        if (e.Info == RefKind.MethodGroup) return MethodGroupText(e, e.A);
        var sym = e.Sym;
        if (sym == null) return "nil";
        if (sym.Kind == SymKind.EnumMember) return ConstText(e.Const!, e.Type!);
        if (sym.IsStatic && sym.Builtin == "") return MemberValueText(sym.Owner!.LuaName, sym, false);
        string recv = ReceiverText(e.A!);
        if (sym.Builtin != "") return BuiltinPropValue(sym, recv, e.A!.Type);
        bool viaInterface = e.A!.Type != null && e.A.Type.Kind == TypeKind.Interface;
        return MemberValueText(Paren(recv), sym, viaInterface);
    }

    private string ReceiverText(Node recv)
    {
        if (_condRecv.TryGetValue(recv, out var s)) return s;
        return Expr(recv);
    }

    // ?. の鎖: 最も左の ?. の受け手が nil なら鎖全体が nil。受け手を 1 度だけ評価する。
    // 鎖に ?. が複数あれば、左から順に入れ子の if で囲む
    private string GuardedChain(Node top, bool asStatement)
    {
        string r = "";
        if (!asStatement)
        {
            r = NewTemp();
            Line("local " + r);
        }
        GuardChainInto(top, asStatement, r);
        return r;
    }

    private void GuardChainInto(Node top, bool asStatement, string r)
    {
        // 残っている ?. のうち最も左 (最も深い) もの
        Node? cond = null;
        Node? cur = top;
        while (cur != null && cur.CondChain)
        {
            if ((cur.Kind == NodeKind.Member || cur.Kind == NodeKind.Index) && cur.Value == 1) cond = cur;
            cur = cur.A;
        }
        if (cond == null)
        {
            top.CondTop = false;
            if (asStatement)
            {
                if (top.Kind == NodeKind.Call)
                {
                    string c = EmitCall(top, true);
                    if (c != "") EmitCallStatement(c);
                }
                else
                {
                    string v = Expr(top);
                    if (v != "" && !IsSimpleName(v) && !IsLiteralText(v)) Line("local _ = " + v);
                }
            }
            else Line(r + " = " + Expr(top));
            top.CondTop = true;
            return;
        }
        string recv = Spill(Expr(cond.A!));
        Line("if " + recv + " ~= nil then");
        _indent++;
        _condRecv[cond.A!] = recv;
        cond.Value = 0;
        GuardChainInto(top, asStatement, r);
        cond.Value = 1;
        _condRecv.Remove(cond.A!);
        _indent--;
        Line("end");
    }

    // a?.b、a?.M(): a が nil なら nil
    private string ConditionalAccess(Node e)
    {
        string recv = Spill(Expr(e.A!));
        string r = NewTemp();
        Line("local " + r);
        Line("if " + recv + " ~= nil then");
        _indent++;
        _condRecv[e.A!] = recv;
        int save = e.Value;
        e.Value = 0;
        string v;
        if (e.Info == RefKind.MethodGroup) v = "nil";
        else v = MemberText(e);
        e.Value = save;
        _condRecv.Remove(e.A!);
        Line(r + " = " + v);
        _indent--;
        Line("end");
        return r;
    }

    private string MethodGroupText(Node e, Node? receiver)
    {
        var m = e.Sym;
        if (m == null) return "nil";
        bool structParams = false;
        for (int i = 0; i < m.ParamCount; i++)
        {
            if (IsMutableStruct(m.Params![i].Type)) structParams = true;
        }
        if (m.IsStatic && structParams)
        {
            // delegate として呼ばれるときも struct の引数を copy する
            var ws = new List<string>();
            var cs = new List<string>();
            for (int i = 0; i < m.ParamCount; i++)
            {
                ws.Add("a" + (i + 1));
                cs.Add(CopyText("a" + (i + 1), m.Params![i].Type));
            }
            return "function(" + string.Join(", ", ws) + ") return " + m.Owner!.LuaName + "." + m.LuaName + "(" + string.Join(", ", cs) + ") end";
        }
        if (m.IsStatic) return m.Owner!.LuaName + "." + m.LuaName;
        string recv = receiver != null ? Spill(Expr(receiver)) : "self";
        var ps = new List<string>();
        var copied = new List<string>();
        for (int i = 0; i < m.ParamCount; i++)
        {
            ps.Add("a" + (i + 1));
            copied.Add(CopyText("a" + (i + 1), m.Params![i].Type));
        }
        string args = string.Join(", ", ps);
        string cargs = string.Join(", ", copied);
        if (m.Owner != null && m.Owner.IsStruct) return "function(" + args + ") return " + m.Owner.LuaName + "." + m.LuaName + "(" + recv + (args == "" ? "" : ", " + cargs) + ") end";
        return "function(" + args + ") return " + recv + ":" + m.LuaName + "(" + cargs + ") end";
    }

    private string IndexText(Node e)
    {
        var rt = e.A!.Type!;
        if (e.Value == 1)
        {
            // a?[i]
            string cr = Spill(Expr(e.A));
            string r = NewTemp();
            Line("local " + r);
            Line("if " + cr + " ~= nil then");
            _indent++;
            _condRecv[e.A] = cr;
            e.Value = 0;
            string v = IndexText(e);
            e.Value = 1;
            _condRecv.Remove(e.A);
            Line(r + " = " + v);
            _indent--;
            Line("end");
            return r;
        }
        if (rt.Kind == TypeKind.Nullable) rt = rt.Elem;
        string recv = ReceiverText(e.A);
        string idx = Expr(e.Item(0));
        switch (rt.Kind)
        {
            case TypeKind.List:
            case TypeKind.Array:
                {
                    recv = SpillIfComplex(recv);
                    idx = SpillIfComplex(idx);
                    return ElementRead(recv, idx, rt);
                }
            case TypeKind.Dict:
                recv = SpillIfComplex(recv);
                idx = SpillIfComplex(idx);
                return Paren(recv) + "[" + DictKey(idx, rt) + "]";
            case TypeKind.Utf8Bytes:
                return "__tcs_u8at(" + recv + ", " + idx + ")";
        }
        return "nil";
    }

    private string SpillIfComplex(string v)
    {
        if (IsSimpleName(v) || IsLiteralText(v)) return v;
        return Spill(v);
    }

    // null を要素に持ちうる配列 (参照型、T?、型引数) は Lua の sequence で長さを保てないので、参照実装と同じく添字を検査しない
    private static bool UncheckedArray(TypeSym rt)
    {
        if (rt.Kind != TypeKind.Array) return false;
        var el = rt.Elem;
        return el.IsReferenceLike || el.Kind == TypeKind.Nullable || el.Kind == TypeKind.TypeParam;
    }

    private string ElementRead(string recv, string idx, TypeSym rt)
    {
        string i1 = IsIntLiteral(idx) ? IntLiteral(ParseIntText(idx) + 1) : idx + " + 1";
        if (UncheckedArray(rt)) return Paren(recv) + "[" + i1 + "]";
        if (rt.Elem.Kind == TypeKind.Bool) return "__tcs_lget(" + recv + ", " + idx + ")";
        return "(" + recv + "[" + i1 + "] or __tcs_lget(" + recv + ", " + idx + "))";
    }

    private static bool IsIntLiteral(string s)
    {
        var u = new Utf8Bytes(s);
        if (u.Length == 0 || u.Length > 9) return false;
        for (int i = 0; i < u.Length; i++)
        {
            if (u[i] < '0' || u[i] > '9') return false;
        }
        return true;
    }

    private static int ParseIntText(string s)
    {
        int v = 0;
        int.TryParse(s, out v);
        return v;
    }

    private static bool NilElements(TypeSym listType)
    {
        if (listType.Args == null || listType.Args.Count == 0) return true;
        var el = listType.Args[0];
        return el.IsReferenceLike || el.Kind == TypeKind.Nullable || el.Kind == TypeKind.TypeParam;
    }

    // ---- 文字列 ----

    private string InterpText(Node e)
    {
        var parts = new List<string>();
        if (e.List != null)
        {
            var values = new List<Node>();
            foreach (var p in e.List) values.Add(p.Kind == NodeKind.InterpHole ? p.A! : p);
            var texts = EmitOperands(values);
            for (int i = 0; i < e.List.Count; i++)
            {
                var p = e.List[i];
                if (p.Kind == NodeKind.StringLit)
                {
                    parts.Add(LuaString(p.Text));
                    continue;
                }
                var v = p.A!;
                string s;
                if (p.Text != "") s = FormatText(texts[i], v.Type!, p.Text);
                else s = StringOperand(texts[i], v.Type!, v);
                if (p.B != null && p.B.HasConst)
                {
                    int width = p.B.Const!.I;
                    s = "string.format(\"%" + width + "s\", " + s + ")";
                }
                parts.Add(s);
            }
        }
        if (parts.Count == 0) return "\"\"";
        if (parts.Count == 1) return parts[0];
        return "(" + string.Join(" .. ", parts) + ")";
    }

    // 補間の書式 (参照実装の WrapNumberFormat / WrapEnumFormat / ConvertFormatSpecifier と同じ規則)
    private string FormatText(string v, TypeSym t0, string spec)
    {
        var t = t0.Kind == TypeKind.Nullable ? t0.Elem : t0;
        // bool / string / char / Rune と ToString を持つ型は書式を使わない
        if (t.Kind == TypeKind.Bool || t.Kind == TypeKind.String || t.Kind == TypeKind.Char || t.Kind == TypeKind.Rune || HasToStringMethod(t))
            return StringOperand(v, t0, null);
        if (t.Kind == TypeKind.Enum)
        {
            if (spec == "G" || spec == "g") return "String.FormatEnum(" + v + ", " + LuaString(EnumSpec(t.Decl!)) + ")";
            if (spec == "F" || spec == "f") return "String.FormatEnum(" + v + ", " + LuaString(EnumFlagsSpec(t.Decl!)) + ")";
            if (spec == "D" || spec == "d") return "tostring(" + v + ")";
            return "string.format(" + LuaString(LuaFormat(spec)) + ", " + v + ")";
        }
        bool isFloat = t.Kind == TypeKind.Float || t.Kind == TypeKind.Double;
        if (isFloat || t.IsIntegral)
        {
            string? ns = NumberSpec(spec, isFloat);
            if (ns != null) return (isFloat ? "String.FormatFloat(" : "String.FormatInt(") + v + ", " + LuaString(ns) + ")";
        }
        return "string.format(" + LuaString(LuaFormat(spec)) + ", " + v + ")";
    }

    // 標準の数値書式 (文字 + 9 桁までの精度)。精度は数に直す ("G03" は "G3")。R は G と同じ
    private static string? NumberSpec(string spec, bool isFloat)
    {
        var u = new Utf8Bytes(spec);
        if (u.Length == 0 || u.Length > 10) return null;
        for (int i = 1; i < u.Length; i++)
        {
            if (u[i] < '0' || u[i] > '9') return null;
        }
        int c = u[0];
        int kind = c == 'R' ? 'G' : c == 'r' ? 'g' : c;
        string letters = isFloat ? "GgEeFfNn" : "GgEeFfNnDdXx";
        string ks = char.ConvertFromUtf32(kind);
        if (!letters.Contains(ks)) return null;
        if (u.Length == 1 || isFloat && kind != c) return ks;
        int prec = 0;
        for (int i = 1; i < u.Length; i++) prec = prec * 10 + (u[i] - '0');
        return ks + prec;
    }

    private static string LuaFormat(string fmt)
    {
        var u = new Utf8Bytes(fmt);
        if (u.Length == 0) return "%s";
        int c0 = u[0];
        int c = c0 >= 'a' && c0 <= 'z' ? c0 - 32 : c0;
        string precision = u.Length > 1 ? u.Slice(1, u.Length - 1).ToString() : "";
        switch (c)
        {
            case 'F': return precision == "" ? "%.6f" : "%." + precision + "f";
            case 'N': return precision == "" ? "%.2f" : "%." + precision + "f";
            case 'D':
                {
                    string trimmed = precision;
                    while (trimmed.StartsWith("0")) trimmed = new Utf8Bytes(trimmed).Slice(1, new Utf8Bytes(trimmed).Length - 1).ToString();
                    return trimmed == "" ? "%d" : "%." + precision + "d";
                }
            case 'X':
                if (c0 == 'X') return precision == "" ? "%X" : "%0" + precision + "X";
                return precision == "" ? "%x" : "%0" + precision + "x";
            case 'E':
                if (c0 == 'E') return precision == "" ? "%E" : "%." + precision + "E";
                return precision == "" ? "%e" : "%." + precision + "e";
            case 'G': return precision == "" ? "%g" : "%." + precision + "g";
        }
        return "%s";
    }

    private static string EnumFlagsSpec(TypeDeclSym t)
    {
        string s = EnumSpec(t);
        return s.StartsWith("*") ? s : "*" + s;
    }

    private static string EnumSpec(TypeDeclSym t)
    {
        var parts = new List<string>();
        foreach (var m in t.Members)
        {
            if (m.Kind == SymKind.EnumMember) parts.Add(m.Name + ":" + (m.ConstVal != null ? m.ConstVal.I : 0));
        }
        string s = string.Join(",", parts);
        return t.IsFlags ? "*" + s : s;
    }

    // 文字列の連結の operand
    private string StringOperand(string v, TypeSym t, Node? n)
    {
        switch (t.Kind)
        {
            case TypeKind.String:
                if (n != null && (n.HasConst || n.Kind == NodeKind.InterpString || n.Kind == NodeKind.Binary && n.Info == 1)) return v;
                return "(" + v + " or \"\")";
            case TypeKind.Int:
            case TypeKind.Short:
            case TypeKind.Byte:
            case TypeKind.UInt:
            case TypeKind.Long:
                return IsIntLiteral(v) ? LuaString(v) : "tostring(" + v + ")";
            case TypeKind.Char:
                return "string.char(" + v + ")";
            case TypeKind.Float:
                return "__tcs_fstr(" + v + ")";
            case TypeKind.Bool:
                return "__tcs_bstr(" + v + ")";
            case TypeKind.Enum:
                return "String.FormatEnum(" + v + ", " + LuaString(EnumSpec(t.Decl!)) + ")";
            case TypeKind.Null:
                return "\"\"";
            case TypeKind.Rune:
                return "Char.ConvertFromUtf32(" + v + ")";
            case TypeKind.TypeParam:
                return "__tcs_tstr(" + DescText(t) + ", " + v + ")";
            case TypeKind.Class:
            case TypeKind.Struct:
                if (t.Kind == TypeKind.Struct && HasToStringMethod(t)) return "(" + t.Decl!.LuaName + ".ToString(" + v + ") or \"\")";
                if (n != null && HasToStringMethod(t)) return "(" + Paren(v) + ":ToString() or \"\")";
                return "__tcs_nstr(" + v + ")";
        }
        return "__tcs_nstr(" + v + ")";
    }

    private static bool HasToStringMethod(TypeSym t)
    {
        if (t.Decl == null) return false;
        var list = t.Decl.Lookup("ToString");
        if (list == null) return false;
        foreach (var m in list)
        {
            if (m.Kind == SymKind.Method && m.ParamCount == 0) return true;
        }
        return false;
    }

    // ---- 二項 ----

    // operand を左から評価し、後の operand が前置きの文を出したら前の operand を temp に入れる
    private List<string> EmitOperands(List<Node> nodes)
    {
        var result = new List<string>();
        for (int i = 0; i < nodes.Count; i++)
        {
            int mark = _out.Count;
            string s = Expr(nodes[i]);
            if (_out.Count > mark && i > 0)
            {
                var pre = Extract(mark);
                for (int j = 0; j < result.Count; j++)
                {
                    // 後の operand の前置きの文が書き換えうる値 (局所変数も) を先に読んでおく
                    if (!IsTempName(result[j]) && !IsLiteralText(result[j]) && result[j] != "self")
                    {
                        string t = NewTemp();
                        Line("local " + t + " = " + result[j]);
                        result[j] = t;
                    }
                }
                foreach (var p in pre) _out.Add(p);
            }
            // lambda に capture された局所変数は、後ろの operand の呼び出しが書き換えうる
            // (Lua は局所変数を読むのを演算の時まで遅らせる) ので先に読む
            if (IsCapturedLocal(nodes[i]) && i < nodes.Count - 1 && LaterMayCall(nodes, i + 1))
            {
                string t = NewTemp();
                Line("local " + t + " = " + s);
                s = t;
            }
            result.Add(s);
        }
        return result;
    }

    private static bool IsCapturedLocal(Node n)
    {
        if (n.Kind == NodeKind.Conv || n.Kind == NodeKind.Paren) return n.A != null && IsCapturedLocal(n.A);
        return n.Kind == NodeKind.Name && n.Info == RefKind.Local && n.Local != null && n.Local.Captured;
    }

    private static bool LaterMayCall(List<Node> nodes, int from)
    {
        for (int i = from; i < nodes.Count; i++)
        {
            if (MayCall(nodes[i])) return true;
        }
        return false;
    }

    // 式が関数の呼び出し (getter を含む) や代入を含みうるか
    private static bool MayCall(Node n)
    {
        switch (n.Kind)
        {
            case NodeKind.Call:
            case NodeKind.New:
            case NodeKind.Assign:
            case NodeKind.PostIncDec:
            case NodeKind.PreIncDec:
                return true;
            case NodeKind.Lambda:
                return false;
            case NodeKind.Member:
            case NodeKind.Name:
                if (n.Sym != null && n.Sym.Kind == SymKind.Property && !n.Sym.IsAuto) return true;
                break;
        }
        if (n.A != null && MayCall(n.A)) return true;
        if (n.B != null && MayCall(n.B)) return true;
        if (n.C != null && MayCall(n.C)) return true;
        if (n.List != null)
        {
            foreach (var x in n.List)
            {
                if (MayCall(x)) return true;
            }
        }
        return false;
    }

    private string BinaryText(Node e)
    {
        string op = e.Text;
        if (e.Sym != null)
        {
            var ops = new List<Node>();
            ops.Add(e.A!);
            ops.Add(e.B!);
            var t = EmitOperands(ops);
            CopyOperands(ops, t);
            return e.Sym.Owner!.LuaName + "." + e.Sym.LuaName + "(" + t[0] + ", " + t[1] + ")";
        }
        if (op == "&&" || op == "||") return LogicalText(e);
        if (op == "??") return CoalesceText(e);
        if (e.Info == 1) return ConcatText(e);
        var nodes = new List<Node>();
        nodes.Add(e.A!);
        nodes.Add(e.B!);
        var s = EmitOperands(nodes);
        string a = s[0];
        string b = s[1];
        var lt = e.A!.Type!;
        if (e.Info == 3 && lt.Decl != null)
        {
            string eq = lt.Decl.LuaName + ".__equals(" + a + ", " + b + ")";
            return op == "==" ? eq : "(not " + eq + ")";
        }
        switch (op)
        {
            case "==": return "(" + a + " == " + b + ")";
            case "!=": return "(" + a + " ~= " + b + ")";
            case "<":
            case ">":
            case "<=":
            case ">=":
                return "(" + a + " " + op + " " + b + ")";
            case "&":
            case "|":
            case "^":
                if (lt.Kind == TypeKind.Bool)
                {
                    if (op == "^") return "(" + a + " ~= " + b + ")";
                    a = Spill(a);
                    b = Spill(b);
                    return "(" + a + (op == "&" ? " and " : " or ") + b + ")";
                }
                return "(" + a + " " + (op == "^" ? "~" : op) + " " + b + ")";
        }
        return ArithText(op, a, b, e.Type!, e.Type!);
    }

    private string ArithText(string op, string a, string b, TypeSym t, TypeSym resultType)
    {
        bool isFloat = t.Kind == TypeKind.Float || t.Kind == TypeKind.Double;
        string r;
        switch (op)
        {
            case "+": r = "(" + a + " + " + b + ")"; break;
            case "-": r = "(" + a + " - " + b + ")"; break;
            case "*": r = "(" + a + " * " + b + ")"; break;
            case "/": r = isFloat ? "(" + a + " / " + b + ")" : "__tcs_idiv(" + a + ", " + b + ")"; break;
            case "%": r = isFloat ? "math.fmod(" + a + ", " + b + ")" : "__tcs_irem(" + a + ", " + b + ")"; break;
            case "<<": r = "__tcs_shl(" + a + ", " + b + ")"; break;
            case ">>": r = "__tcs_shr(" + a + ", " + b + ")"; break;
            case "&": r = resultType.Kind == TypeKind.Bool ? "(" + a + " and " + b + ")" : "(" + a + " & " + b + ")"; break;
            case "|": r = resultType.Kind == TypeKind.Bool ? "(" + a + " or " + b + ")" : "(" + a + " | " + b + ")"; break;
            case "^": r = resultType.Kind == TypeKind.Bool ? "(" + a + " ~= " + b + ")" : "(" + a + " ~ " + b + ")"; break;
            default: r = "nil"; break;
        }
        // 複合代入の結果を元の型へ (int への float の代入など)
        if (resultType.Kind == TypeKind.Char && !isFloat) r = "__tcs_char(" + r + ")";
        return r;
    }

    // && と ||。右の operand が前置きの文を出すなら if にする
    private string LogicalText(Node e)
    {
        bool and = e.Text == "&&";
        string a = Expr(e.A!);
        int mark = _out.Count;
        string b = Expr(e.B!);
        if (_out.Count == mark) return "(" + a + (and ? " and " : " or ") + b + ")";
        var pre = Extract(mark);
        string t = NewTemp();
        Line("local " + t + " = " + a);
        Line(and ? "if " + t + " then" : "if not " + t + " then");
        _indent++;
        foreach (var p in pre) _out.Add("  " + p);
        Line(t + " = " + b);
        _indent--;
        Line("end");
        return t;
    }

    private string CoalesceText(Node e)
    {
        string a = Val(e.A!);
        int mark = _out.Count;
        string b = Val(e.B!);
        var lt = e.A!.Type!;
        bool falsyOk = lt.Kind != TypeKind.Nullable || lt.Elem.Kind != TypeKind.Bool;
        if (_out.Count == mark && falsyOk) return "(" + a + " or " + b + ")";
        var pre = Extract(mark);
        string t = NewTemp();
        Line("local " + t + " = " + a);
        Line("if " + t + " == nil then");
        _indent++;
        foreach (var p in pre) _out.Add("  " + p);
        Line(t + " = " + b);
        _indent--;
        Line("end");
        return t;
    }

    // 文字列の連結の鎖を 1 つの .. にまとめる
    private string ConcatText(Node e)
    {
        var operands = new List<Node>();
        FlattenConcat(e, operands);
        var texts = EmitOperands(operands);
        var parts = new List<string>();
        for (int i = 0; i < operands.Count; i++) parts.Add(StringOperand(texts[i], operands[i].Type!, operands[i]));
        return "(" + string.Join(" .. ", parts) + ")";
    }

    private static void FlattenConcat(Node e, List<Node> into)
    {
        if (e.Kind == NodeKind.Binary && e.Info == 1 && e.Text == "+" && !e.HasConst)
        {
            FlattenConcat(e.A!, into);
            FlattenConcat(e.B!, into);
            return;
        }
        into.Add(e);
    }

    private string UnaryText(Node e)
    {
        if (e.Sym != null) return e.Sym.Owner!.LuaName + "." + e.Sym.LuaName + "(" + Val(e.A!) + ")";
        string a = Expr(e.A!);
        switch (e.Text)
        {
            case "!": return "(not " + a + ")";
            case "-": return "(-" + Paren(a) + ")";
            case "+": return a;
            case "~": return "(~" + Paren(a) + ")";
        }
        return a;
    }

    private string ConditionalText(Node e)
    {
        string c = Expr(e.A!);
        string t = NewTemp();
        Line("local " + t);
        Line("if " + c + " then");
        _indent++;
        Line(t + " = " + Val(e.B!));
        _indent--;
        Line("else");
        _indent++;
        Line(t + " = " + Val(e.C!));
        _indent--;
        Line("end");
        return t;
    }

    private string IsText(Node e)
    {
        string v = Expr(e.A!);
        if (!IsSimpleName(v))
        {
            string t = NewTemp();
            Line("local " + t + " = " + v);
            v = t;
        }
        AssignDesignations(e.B!, v);
        return PatternCond(e.B!, v, e.A!.Type!);
    }

    private string AsText(Node e)
    {
        string v = Spill(Expr(e.A!));
        var t = e.Type!;
        string test = TypeTest(v, e.A!.Type!, t);
        string r = NewTemp();
        Line("local " + r + " = nil");
        Line("if " + test + " then " + r + " = " + v + " end");
        return r;
    }

    private string CastText(Node e)
    {
        string v = Expr(e.B!);
        switch (e.Info)
        {
            case ConvKind.FloatToInt: return "__tcs_trunc(" + v + ")";
            case ConvKind.IntToFloat: return "(" + v + " * 1.0)";
            case ConvKind.IntToChar: return "__tcs_char(" + v + ")";
            case ConvKind.CastClass: return "__tcs_cast(" + v + ", " + e.Type!.Decl!.LuaName + ")";
            case ConvKind.CastInterface: return "__tcs_icast(" + v + ", " + LuaString(e.Type!.Decl!.LuaName) + ")";
            case ConvKind.NullableValue: return "__tcs_nval(" + v + ")";
            case ConvKind.Unbox: return "__tcs_ncast(" + v + ", \"integer\")";
            case ConvKind.UnboxFloat: return "__tcs_ncast(" + v + ", \"float\")";
            case ConvKind.UnboxBool: return "__tcs_vcast(" + v + ", \"boolean\")";
            case ConvKind.UnboxString: return "__tcs_tcast(" + v + ", \"string\")";
        }
        return v;
    }

    private string ConvText(Node e)
    {
        switch (e.Info)
        {
            case ConvKind.IntToFloat: return "(" + Expr(e.A!) + " * 1.0)";
            case ConvKind.NullableIntToFloat: return "__tcs_tofloat(" + Expr(e.A!) + ")";
            case ConvKind.MethodGroup: return MethodGroupText(e.A!, e.A!.Kind == NodeKind.Member ? e.A.A : null);
        }
        return Expr(e.A!);
    }

    // ---- lambda ----

    private string LambdaText(Node e)
    {
        var del = e.Type!;
        var saveOut = _out;
        var saveIndent = _indent;
        var saveFn = _fn;
        var saveLoops = _loops;
        _out = new List<string>();
        _loops = new List<LoopCtx>();
        _indent = saveIndent + 1;
        var fn = new FnCtx();
        fn.IsLambda = true;
        fn.DescViaSelf = saveFn.DescViaSelf;
        fn.Temp = saveFn.Temp + 100;
        fn.Parent = saveFn;
        _fn = fn;
        var ps = new List<string>();
        if (e.List != null)
        {
            foreach (var p in e.List)
            {
                string pn = p.Local != null ? p.Local.LuaName : LuaNames.Local(p.Text);
                ps.Add(pn);
                // 可変 struct の parameter は呼ぶ側 (LINQ など) の値を書き換えないように copy する
                if (p.Local != null && IsMutableStruct(p.Local.Type)) Line(pn + " = " + p.Local.Type.Decl!.LuaName + ".__copy(" + pn + ")");
            }
        }
        if (e.A != null)
        {
            if (del.Ret != null && del.Ret.Kind == TypeKind.Void) EmitExprStatement(e.A);
            else
            {
                string v = Val(e.A);
                Line("return " + v);
            }
        }
        else if (e.B != null) EmitStatements(e.B);
        var body = _out;
        _out = saveOut;
        _indent = saveIndent;
        saveFn.Temp = _fn.Temp;
        _fn = saveFn;
        _loops = saveLoops;
        if (body.Count == 1)
        {
            return "function(" + string.Join(", ", ps) + ") " + body[0].Trim() + " end";
        }
        return "function(" + string.Join(", ", ps) + ")\n" + string.Join("\n", body) + "\n" + Indent() + "end";
    }

    // ---- new ----

    private string NewText(Node e)
    {
        var t = e.Type!;
        string obj;
        switch (e.Info)
        {
            case NewKind.Class:
            case NewKind.Struct:
                {
                    var ctor = e.Sym;
                    var args = ctor != null ? CallArgs(e, ctor) : new List<string>();
                    if (ctor == null && t.Args != null && t.Kind == TypeKind.Class)
                    {
                        foreach (var ta in t.Args) args.Add(DescText(ta));
                    }
                    string name = ctor != null ? ctor.LuaName : "new";
                    obj = t.Decl!.LuaName + "." + name + "(" + string.Join(", ", args) + ")";
                    break;
                }
            case NewKind.List:
                obj = ListLiteral(e.B, t);
                if (e.B != null && e.B.Kind == NodeKind.CollectionInit) return obj;
                break;
            case NewKind.ListCopy:
                {
                    // 可変 struct の要素は copy する
                    string? cf = IsMutableStruct(t.Elem) ? t.Elem.Decl!.LuaName + ".__copy" : null;
                    obj = "List.Copy(" + Expr(e.Item(0).A!) + (cf != null ? ", " + cf : "") + ")";
                    break;
                }
            case NewKind.Dict:
                if (e.B != null) return DictLiteral(e.B, t);
                obj = "{}";
                break;
            case NewKind.HashSet:
                obj = "TcsHashSet.new()";
                if (e.B != null && e.B.Kind == NodeKind.CollectionInit)
                {
                    string hs = NewTemp();
                    Line("local " + hs + " = " + obj);
                    foreach (var x in e.B.List!) Line("TcsHashSet.Add(" + hs + ", " + Expr(x) + ")");
                    return hs;
                }
                break;
            case NewKind.Queue:
                obj = "TcsQueue.new()";
                break;
            case NewKind.Utf8Bytes:
                if (e.Value == 2) return "TinySystem.Utf8.Default()";
                return "TinySystem.Utf8.New(" + Expr(e.Item(0).A!) + ")";
            case NewKind.Random:
                return "Random.new(" + (e.Count > 0 ? Expr(e.Item(0).A!) : "") + ")";
            case NewKind.TypeParam:
                return "__tcs_nt(" + DescText(t) + ")";
            default:
                obj = "nil";
                break;
        }
        if (e.B == null || e.B.Kind != NodeKind.ObjectInit || e.B.Count == 0) return obj;
        string tmp = NewTemp();
        Line("local " + tmp + " = " + obj);
        foreach (var item in e.B.List!)
        {
            if (item.Kind == NodeKind.MemberInit)
            {
                var sym = item.Sym;
                if (sym == null) continue;
                string v = Val(item.A!);
                if (sym.Kind == SymKind.Property && !IsFieldBacked(sym)) Line(tmp + ":set_" + sym.Name + "(" + v + ")");
                else Line(tmp + FieldAccess(sym.Name) + " = " + v);
            }
            else
            {
                string k = Expr(item.A!);
                string v = Expr(item.B!);
                Line(tmp + "[" + k + "] = " + v);
            }
        }
        return tmp;
    }

    private string ListLiteral(Node? init, TypeSym t)
    {
        if (init == null || init.Kind != NodeKind.CollectionInit || init.List == null) return "{}";
        var texts = EmitOperands(init.List);
        CopyOperands(init.List, texts);
        bool nil = NilElements(t);
        if (nil) return "{" + string.Join(", ", texts) + (texts.Count > 0 ? ", " : "") + "n = " + texts.Count + "}";
        return "{" + string.Join(", ", texts) + "}";
    }

    private string DictLiteral(Node init, TypeSym dictType)
    {
        if (init.Kind == NodeKind.ObjectInit)
        {
            var parts = new List<string>();
            foreach (var item in init.List!)
            {
                if (item.Kind != NodeKind.IndexInit) continue;
                parts.Add("[" + DictKey(Expr(item.A!), dictType) + "] = " + Val(item.B!));
            }
            return "{" + string.Join(", ", parts) + "}";
        }
        var ps = new List<string>();
        if (init.List != null)
        {
            foreach (var item in init.List)
            {
                if (item.Kind != NodeKind.ArrayInit || item.Count != 2) continue;
                ps.Add("[" + DictKey(Expr(item.Item(0)), dictType) + "] = " + Val(item.Item(1)));
            }
        }
        return "{" + string.Join(", ", ps) + "}";
    }

    private string NewArrayText(Node e)
    {
        if (e.C != null) return ArrayInitText(e.C);
        var elem = e.Type!.Elem;
        string len = Expr(e.B!);
        if (elem.Kind == TypeKind.Struct && elem.Decl != null) return "__tcs_arr(" + len + ", " + elem.Decl.LuaName + ".new)";
        string? d = DefaultValue(elem);
        if (d == null || d == "nil") return "{}";
        return "__tcs_arr(" + len + ", " + d + ")";
    }

    private string ArrayInitText(Node e)
    {
        if (e.List == null) return "{}";
        var texts = EmitOperands(e.List);
        CopyOperands(e.List, texts);
        return "{" + string.Join(", ", texts) + "}";
    }

    private string CollectionText(Node e)
    {
        if (e.List == null || e.List.Count == 0) return "{}";
        var texts = EmitOperands(e.List);
        if (e.Type!.Kind == TypeKind.List && NilElements(e.Type)) return "{" + string.Join(", ", texts) + ", n = " + texts.Count + "}";
        return "{" + string.Join(", ", texts) + "}";
    }

    private string SwitchExprText(Node e)
    {
        string gv = Spill(Expr(e.A!));
        string r = NewTemp();
        Line("local " + r);
        foreach (var arm in e.List!)
        {
            if (arm.DeclLocals != null)
            {
                var names = new List<string>();
                foreach (var l in arm.DeclLocals) names.Add(l.LuaName);
                Line("local " + string.Join(", ", names));
            }
            AssignDesignations(arm.A!, gv);
        }
        Line("repeat");
        _indent++;
        foreach (var arm in e.List)
        {
            string c = PatternCond(arm.A!, gv, e.A!.Type!);
            int mark = _out.Count;
            string guard = arm.B != null ? Expr(arm.B) : "";
            if (_out.Count > mark)
            {
                var pre = Extract(mark);
                Line("if " + c + " then");
                _indent++;
                foreach (var p in pre) _out.Add("  " + p);
                Line("if " + guard + " then");
                _indent++;
                Line(r + " = " + Val(arm.C!));
                Line("break");
                _indent--;
                Line("end");
                _indent--;
                Line("end");
                continue;
            }
            if (guard != "") c = "(" + c + " and " + guard + ")";
            if (c == "true")
            {
                Line(r + " = " + Val(arm.C!));
                Line("break");
                break;
            }
            Line("if " + c + " then");
            _indent++;
            Line(r + " = " + Val(arm.C!));
            Line("break");
            _indent--;
            Line("end");
        }
        Line("error(\"The switch expression does not handle the value\")");
        _indent--;
        Line("until true");
        return r;
    }


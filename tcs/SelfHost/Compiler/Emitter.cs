                    Line(l + ".n = nil");
                    return "";
                }
            case "List.Sort": return t.Count == 0 ? "List.Sort(" + recv + ")" : "List.Sort(" + recv + ", " + a0 + ")";
            case "List.FindIndex": return "List.FindIndex(" + recv + ", " + a0 + ")";
            case "List.RemoveAll": return "List.RemoveAll(" + recv + ", " + a0 + ")";

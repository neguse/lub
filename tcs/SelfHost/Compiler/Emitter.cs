            case "Enum.ToString": return "String.FormatEnum(" + recv + ", " + LuaString(EnumSpec(rt!.Decl!)) + ")";
            case "Math.CompareTo": return "Math.CompareTo(" + recv + ", " + a0 + ")";
            case "Char.ConvertFromUtf32": return "Char.ConvertFromUtf32(" + a0 + ")";
            case "Math.Min": return "__tcs_min(" + a0 + ", " + a1 + ")";
            case "Math.Max": return "__tcs_max(" + a0 + ", " + a1 + ")";
            case "Math.Abs": return "math.abs(" + a0 + ")";
            case "Math.Clamp": return "Math.Clamp(" + args + ")";
            case "Math.Sign": return "Math.Sign(" + a0 + ")";
            case "Math.Floor": return "((" + a0 + ") // 1)";
            case "Math.Ceiling": return "(-((-(" + a0 + ")) // 1))";
            case "Math.Sqrt": return "math.sqrt(" + a0 + ")";
            case "Math.Round": return "Math.Round(" + a0 + ")";
            case "Math.Truncate": return "(__tcs_trunc(" + a0 + ") * 1.0)";
            case "Math.Sin": return "tcs_math.sin(" + a0 + ")";
            case "Math.Cos": return "tcs_math.cos(" + a0 + ")";
            case "Math.Tan": return "tcs_math.tan(" + a0 + ")";
            case "Math.Asin": return "tcs_math.asin(" + a0 + ")";
            case "Math.Acos": return "tcs_math.acos(" + a0 + ")";
            case "Math.Atan": return "tcs_math.atan(" + a0 + ")";
            case "Math.Atan2": return "tcs_math.atan2(" + a0 + ", " + a1 + ")";
            case "Math.Exp": return "tcs_math.exp(" + a0 + ")";
            case "Math.Log": return "tcs_math.log(" + a0 + ")";
            case "Math.Log10": return "tcs_math.log10(" + a0 + ")";
            case "Math.Pow": return "tcs_math.pow(" + a0 + ", " + a1 + ")";
            case "Console.WriteLine":
                if (t.Count == 0) return "print(\"\")";
                return "print(" + StringOperand(a0, e.Item(0).A!.Type!, e.Item(0).A) + ")";
            case "Console.Write":
                return "io.write(" + StringOperand(a0, e.Item(0).A!.Type!, e.Item(0).A) + ")";
            case "Utf8.Slice": return "TinySystem.Utf8.Slice(" + recv + ", " + a0 + ", " + a1 + ")";
            case "Utf8.ToString": return "TinySystem.Utf8.ToString(" + recv + ")";
            case "Nullable.GetValueOrDefault": return "__tcs_nget(" + recv + ", " + (DefaultValue(rt!.Elem) ?? "nil") + ")";
            case "Delegate.Invoke": return Paren(recv) + "(" + args + ")";
        }
        if (m.Builtin.StartsWith("Char.")) return m.Builtin + "(" + a0 + ")";
        return "nil";
    }

    private string SpillForStatement(string v)
    {
        if (IsSimpleName(v)) return v;
        var u = new Utf8Bytes(v);
        // a.b.c の形はそのまま (評価は 1 回で副作用が無い)
        bool simplePath = true;
        for (int i = 0; i < u.Length; i++)
        {
            int c = u[i];
            if (!(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c == '_' || c >= '0' && c <= '9' || c == '.')) simplePath = false;
        }
        if (simplePath) return v;
        return Spill(v);
    }


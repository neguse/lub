using System.Collections.Generic;
using TinySystem.Text;

namespace TcsSelf;

// 関数 (method、constructor、lambda) ごとの出力の文脈
sealed class FnCtx
{
    public List<string> OutNames = new List<string>();
    public bool IsCtor;
    public bool IsInit;
    public bool IsLambda;
    public bool HasReturnValue;
    public int Temp;
    public FnCtx? Parent;
    // 型の型引数の記述子を self の field から読む (instance の member)。false なら引数 __tcs_dc_T
    public bool DescViaSelf;
}

// ループの continue の行き先
sealed class LoopCtx
{
    public string Label = "";
    public bool UsesContinue;
}

// 束縛済みの構文木から Lua を出す
public sealed class Emitter
{
    private readonly Compilation _c;
    private List<string> _out = new List<string>();
    private int _indent;
    private FnCtx _fn = new FnCtx();
    private List<LoopCtx> _loops = new List<LoopCtx>();
    private int _labels;
    private TypeDeclSym? _type;
    private Dictionary<Node, string> _condRecv = new Dictionary<Node, string>();

    public Emitter(Compilation c)
    {
        _c = c;
    }

    // ---- 出力の道具 ----

    private void Line(string s)
    {
        if (_indent == 0)
        {
            _out.Add(s);
            return;
        }
        _out.Add(Indent() + s);
    }

    private string Indent()
    {
        switch (_indent)
        {
            case 1: return "  ";
            case 2: return "    ";
            case 3: return "      ";
            case 4: return "        ";
        }
        var parts = new List<string>();
        for (int i = 0; i < _indent; i++) parts.Add("  ");
        return string.Join("", parts);
    }

    private string NewTemp()
    {
        _fn.Temp++;
        return "__t" + _fn.Temp;
    }

    private string NewLabel()
    {
        _labels++;
        return "__c" + _labels;
    }

    // ---- 全体 ----

    public string EmitProgram(string? entry)
    {
        _out = new List<string>();
        Line("-- Generated by TinyC# self-hosted compiler");
        var types = new List<TypeDeclSym>();
        foreach (var t in _c.Types)
        {
            if (!t.IsRef) types.Add(t);
        }
        if (types.Count > 0 && types.Count <= 150)
        {
            var names = new List<string>();
            foreach (var t in types) names.Add(t.LuaName);
            Line("local " + string.Join(", ", names));
        }
        foreach (var t in types) EmitTypeTable(t);
        foreach (var t in types)
        {
            if (!t.IsEnum && !t.IsInterface) EmitTypeMembers(t);
        }
        EmitStaticInit(types);
        foreach (var unit in _c.Units)
        {
            if (unit.List2 == null || unit.File.IsRef) continue;
            _fn = new FnCtx();
            _type = null;
            foreach (var st in unit.List2) EmitStatement(st);
        }
        if (entry != null && entry != "")
        {
            TypeDeclSym? et = null;
            foreach (var t in types)
            {
                if (t.Name == entry || t.FullName == entry || t.LuaName == entry) et = t;
            }
            if (et == null) _c.Diags.Error("TCS0001", "entry class not found: " + entry, null, 0);
            else Line("return " + et.LuaName);
        }
        return string.Join("\n", _out) + "\n";
    }

    private void EmitTypeTable(TypeDeclSym t)
    {
        string n = t.LuaName;
        Line(n + " = {}; _ENV." + n + " = " + n);
        if (t.IsEnum)
        {
            foreach (var m in t.Members)
            {
                if (m.Kind == SymKind.EnumMember) Line(n + "." + LuaNames.Member(m.Name) + " = " + IntLiteral(m.ConstVal != null ? m.ConstVal.I : 0));
            }
            Line("");
            return;
        }
        if (t.IsInterface || t.IsStruct)
        {
            // struct は metatable の無い table (値の copy は __copy)
            Line("");
            return;
        }
        Line(n + ".__index = " + n);
        var ifaces = new List<string>();
        CollectInterfaces(t, ifaces);
        if (ifaces.Count > 0)
        {
            var parts = new List<string>();
            foreach (var i in ifaces) parts.Add("[" + LuaString(i) + "] = true");
            Line(n + ".__interfaces = {" + string.Join(", ", parts) + "}");
        }
        Line("");
    }

    private void CollectInterfaces(TypeDeclSym t, List<string> into)
    {
        foreach (var i in t.Interfaces)
        {
            if (i.Decl == null) continue;
            if (!into.Contains(i.Decl.LuaName)) into.Add(i.Decl.LuaName);
            CollectInterfaces(i.Decl, into);
        }
    }

    private void EmitTypeMembers(TypeDeclSym t)
    {
        _type = t;
        // constructor
        if (t.IsStruct) EmitStructCore(t);
        else if (!t.IsStatic) EmitCtors(t);
        if (t.IsRecord && !t.IsStruct) EmitRecordClassCore(t);
        foreach (var m in t.Members)
        {
            if (m.Decl == null) continue;
            if (m.Kind == SymKind.Method) EmitMethod(t, m);
            else if (m.Kind == SymKind.Property && m.Decl.Kind == NodeKind.Property) EmitProperty(t, m);
        }
        EmitInterfaceAliases(t);
        _type = null;
    }

    // interface の member の Lua 名と実装の Lua 名が違うときの別名、自動実装の property の accessor
    private void EmitInterfaceAliases(TypeDeclSym t)
    {
        var seen = new HashSet<string>();
        var ifaces = new List<TypeDeclSym>();
        CollectInterfaceDecls(t, ifaces);
        foreach (var iface in ifaces)
        {
            foreach (var im in iface.Members)
            {
                var impls = t.Lookup(im.Name);
                if (impls == null) continue;
                if (im.Kind == SymKind.Method)
                {
                    foreach (var cm in impls)
                    {
                        if (cm.Kind != SymKind.Method || !SameSignature(cm, im)) continue;
                        if (cm.LuaName != im.LuaName && seen.Add(im.LuaName))
                            Line(t.LuaName + "." + im.LuaName + " = " + t.LuaName + "." + cm.LuaName);
                    }
                }
                else if (im.Kind == SymKind.Property)
                {
                    var cp = impls[0];
                    if (cp.Kind == SymKind.Property && IsFieldBacked(cp) && seen.Add(im.Name))
                    {
                        Line("function " + t.LuaName + ":get_" + im.Name + "() return self." + LuaNames.Member(cp.Name) + " end");
                        Line("function " + t.LuaName + ":set_" + im.Name + "(v) self." + LuaNames.Member(cp.Name) + " = v end");
                    }
                    else if (cp.Kind == SymKind.Field && seen.Add(im.Name))
                    {
                        Line("function " + t.LuaName + ":get_" + im.Name + "() return self." + LuaNames.Member(cp.Name) + " end");
                        Line("function " + t.LuaName + ":set_" + im.Name + "(v) self." + LuaNames.Member(cp.Name) + " = v end");
                    }
                }
            }
        }
    }

    private void CollectInterfaceDecls(TypeDeclSym t, List<TypeDeclSym> into)
    {
        foreach (var i in t.Interfaces)
        {
            if (i.Decl == null || into.Contains(i.Decl)) continue;
            into.Add(i.Decl);
            CollectInterfaceDecls(i.Decl, into);
        }
    }

    private static bool SameSignature(Symbol a, Symbol b)
    {
        if (a.ParamCount != b.ParamCount) return false;
        for (int i = 0; i < a.ParamCount; i++)
        {
            if (!TypeSym.Same(a.Params![i].Type, b.Params![i].Type)) return false;
        }
        return true;
    }

    // field に値を持つ property (自動実装と record の positional)
    private static bool IsFieldBacked(Symbol p) => p.IsAuto;

    // ---- static field の初期化 ----

    // 参照実装 (StaticInitOrder) と同じ規則: 全ての型の static field を既定値にしてから、
    // 型を宣言順に DFS で辿り、依存 (初期化子とそこから呼ぶ method の推移閉包が触る static field の型) を
    // 先に初期化する。lambda と method group の中は辿らない。循環は先に触った型が既定値のまま読まれる
    private void EmitStaticInit(List<TypeDeclSym> types)
    {
        foreach (var t in types)
        {
            if (t.IsEnum || t.IsInterface) continue;
            foreach (var m in t.Members)
            {
                if (!m.IsStatic || m.Decl == null) continue;
                if (m.Kind == SymKind.Field && m.IsConst)
                {
                    if (m.ConstVal != null) Line(t.LuaName + FieldAccess(m.Name) + " = " + ConstText(m.ConstVal, m.Type));
                    continue;
                }
                if (m.Kind == SymKind.Field || m.Kind == SymKind.Property && m.Decl.Kind == NodeKind.Property && m.IsAuto)
                {
                    string? d = DefaultValue(m.Type);
                    if (d != null && d != "nil") Line(t.LuaName + FieldAccess(m.Name) + " = " + d);
                }
            }
        }
        var seen = new HashSet<TypeDeclSym>();
        foreach (var t in types) EmitStaticInitOf(t, seen);
    }

    private static Node? StaticInitializer(Symbol m)
    {
        if (!m.IsStatic || m.Decl == null) return null;
        if (m.Kind == SymKind.Field && !m.IsConst) return m.Decl.A;
        if (m.Kind == SymKind.Property && m.Decl.Kind == NodeKind.Property && m.IsAuto) return m.Decl.D;
        return null;
    }

    private void EmitStaticInitOf(TypeDeclSym t, HashSet<TypeDeclSym> seen)
    {
        if (t.IsEnum || t.IsInterface || t.IsRef) return;
        if (!seen.Add(t)) return;
        var deps = new List<TypeDeclSym>();
        var visited = new HashSet<Node>();
        foreach (var m in t.Members)
        {
            var init = StaticInitializer(m);
            if (init != null) CollectStaticDeps(init, deps, visited);
        }
        foreach (var d in deps)
        {
            if (d != t) EmitStaticInitOf(d, seen);
        }
        _type = t;
        _fn = new FnCtx();
        foreach (var m in t.Members)
        {
            var init = StaticInitializer(m);
            if (init != null) EmitStaticAssign(t, m, init);
        }
        _type = null;
    }

    // 初期化子が (呼ぶ method を通して) 触る static field の型
    private void CollectStaticDeps(Node n, List<TypeDeclSym> into, HashSet<Node> visited)
    {
        if (n.Kind == NodeKind.Lambda) return;
        if (n.Kind == NodeKind.Conv && n.Info == ConvKind.MethodGroup) return;
        var sym = n.Sym;
        if (sym != null && sym.Owner != null && sym.Builtin == "" && n.Kind != NodeKind.PropSub)
        {
            if (sym.IsStatic && (sym.Kind == SymKind.Field && !sym.IsConst || sym.Kind == SymKind.Property && sym.IsAuto))
            {
                if (!into.Contains(sym.Owner)) into.Add(sym.Owner);
            }
            if (n.Kind == NodeKind.Call || n.Kind == NodeKind.Name || n.Kind == NodeKind.Member || n.Kind == NodeKind.New || n.Kind == NodeKind.Binary || n.Kind == NodeKind.Unary || n.Kind == NodeKind.Assign)
            {
                if (sym.Kind == SymKind.Method || sym.Kind == SymKind.Ctor || sym.Kind == SymKind.Property && !sym.IsAuto)
                {
                    if (n.Info != RefKind.MethodGroup || n.Kind == NodeKind.Call) FollowMember(sym, into, visited);
                }
            }
        }
        if (n.Kind == NodeKind.New && n.Type != null && n.Type.Decl != null)
        {
            // instance の field の初期化子
            foreach (var m in n.Type.Decl.Members)
            {
                if (m.IsStatic || m.Decl == null) continue;
                Node? init = m.Kind == SymKind.Field ? m.Decl.A : m.Kind == SymKind.Property && m.Decl.Kind == NodeKind.Property ? m.Decl.D : null;
                if (init != null && visited.Add(init)) CollectStaticDeps(init, into, visited);
            }
        }
        if (n.A != null) CollectStaticDeps(n.A, into, visited);
        if (n.B != null) CollectStaticDeps(n.B, into, visited);
        if (n.C != null) CollectStaticDeps(n.C, into, visited);
        if (n.D != null) CollectStaticDeps(n.D, into, visited);
        if (n.List != null)
        {
            foreach (var x in n.List) CollectStaticDeps(x, into, visited);
        }
        if (n.List2 != null)
        {
            foreach (var x in n.List2) CollectStaticDeps(x, into, visited);
        }
    }

    // 呼ばれる member の本体を辿る (interface の member は全ての実装)
    private void FollowMember(Symbol sym, List<TypeDeclSym> into, HashSet<Node> visited)
    {
        var owner = sym.Owner!;
        if (owner.IsInterface)
        {
            foreach (var impl in _c.Types)
            {
                if (impl.IsInterface || !impl.Implements(owner)) continue;
                var list = impl.Lookup(sym.Name);
                if (list == null) continue;
                foreach (var m in list)
                {
                    if (m.Kind == sym.Kind) FollowMember(m, into, visited);
                }
            }
            return;
        }
        var decl = sym.Decl;
        if (decl == null || !visited.Add(decl)) return;
        CollectStaticDeps(decl, into, visited);
    }

    private void EmitStaticAssign(TypeDeclSym t, Symbol m, Node? init)
    {
        string target = t.LuaName + FieldAccess(m.Name);
        if (init == null)
        {
            string? d = DefaultValue(m.Type);
            if (d != null) Line(target + " = " + d);
            return;
        }
        int mark = _out.Count;
        Line("do");
        _indent++;
        string v = init.Kind == NodeKind.ArrayInit ? Expr(init) : Val(init);
        Line(target + " = " + v);
        _indent--;
        Line("end");
        CollapseDo(mark);
    }

    // do ... end の中が 1 行なら do / end を外す
    private void CollapseDo(int mark)
    {
        if (_out.Count == mark + 3)
        {
            string body = _out[mark + 1];
            if (!body.StartsWith(Indent() + "  local "))
            {
                _out.RemoveAt(mark + 2);
                _out.RemoveAt(mark);
                _out[mark] = Indent() + body.Trim();
            }
        }
    }

    private void CollectTypeRefs(Node n, List<TypeDeclSym> into)
    {
        if (n.Sym != null && n.Sym.Owner != null && n.Sym.IsStatic && !into.Contains(n.Sym.Owner)) into.Add(n.Sym.Owner);
        if (n.Kind == NodeKind.New && n.Type != null && n.Type.Decl != null && !into.Contains(n.Type.Decl)) into.Add(n.Type.Decl);
        if (n.A != null) CollectTypeRefs(n.A, into);
        if (n.B != null) CollectTypeRefs(n.B, into);
        if (n.C != null) CollectTypeRefs(n.C, into);
        if (n.D != null) CollectTypeRefs(n.D, into);
        if (n.List != null)
        {
            foreach (var x in n.List) CollectTypeRefs(x, into);
        }
        if (n.List2 != null)
        {
            foreach (var x in n.List2) CollectTypeRefs(x, into);
        }
    }

    // ---- struct ----

    // struct の instance の field (自動実装の property を含む)
    private static List<Symbol> InstanceFields(TypeDeclSym t)
    {
        var result = new List<Symbol>();
        foreach (var m in t.Members)
        {
            if (m.IsStatic) continue;
            if (m.Kind == SymKind.Field || m.Kind == SymKind.Property && m.IsAuto) result.Add(m);
        }
        return result;
    }

    private void EmitStructCore(TypeDeclSym t)
    {
        string n = t.LuaName;
        var fields = InstanceFields(t);
        // 既定値
        var parts = new List<string>();
        foreach (var f in fields)
        {
            string? d = DefaultValue(f.Type);
            if (d != null && d != "nil") parts.Add(FieldKey(f.Name) + " = " + d);
        }
        Line("function " + n + ".new()");
        Line("  return {" + string.Join(", ", parts) + "}");
        Line("end");
        Line("");
        // copy (入れ子の可変 struct も copy する)
        var cps = new List<string>();
        foreach (var f in fields) cps.Add(FieldKey(f.Name) + " = " + CopyText("s" + FieldAccess(f.Name), f.Type));
        Line("function " + n + ".__copy(s)");
        Line("  return {" + string.Join(", ", cps) + "}");
        Line("end");
        Line("");
        Line(n + ".__tcs_td = {__tcs_td = true, n = function() return " + n + ".new() end, c = function(v) return " + n + ".__copy(v) end}");
        Line("");
        Line("function " + n + ".__ncopy(s)");
        Line("  if s == nil then return nil end");
        Line("  return " + n + ".__copy(s)");
        Line("end");
        Line("");
        // memberwise の等価 (List.Contains などが使う。float は NaN 同士も等しい)
        var eqs = new List<string>();
        foreach (var f in fields) eqs.Add(FieldEquals("a" + FieldAccess(f.Name), "b" + FieldAccess(f.Name), f.Type));
        Line("function " + n + ".__equals(a, b)");
        Line("  return " + (eqs.Count == 0 ? "true" : string.Join(" and ", eqs)));
        Line("end");
        Line("");
        foreach (var c in t.Ctors)
        {
            var decl = c.Decl!;
            var ps = ParamNames(decl, c);
            Line("function " + n + "." + c.LuaName + "(" + string.Join(", ", ps) + ")");
            _indent++;
            _fn = new FnCtx();
            _fn.IsCtor = true;
            Line("local self = " + n + ".new()");
            if (decl.Kind == NodeKind.Ctor && decl.D != null && decl.D.Sym != null)
            {
                var target = decl.D.Sym;
                var args = CallArgs(decl.D, target);
                Line("self = " + n + "." + target.LuaName + "(" + string.Join(", ", args) + ")");
            }
            else EmitFieldInits(t);
            if (t.IsRecord && decl.Kind == NodeKind.Param)
            {
                foreach (var p in t.RecordParams!) Line("self." + LuaNames.Member(p.Name) + " = " + LuaNames.Local(p.Name));
            }
            if (decl.Kind == NodeKind.Ctor)
            {
                if (decl.B != null) EmitStatements(decl.B);
                else if (decl.C != null) EmitExprStatement(decl.C);
            }
            Line("return self");
            _indent--;
            Line("end");
            Line("");
        }
    }

    // record class の値の等価 (== と != は Lua の __eq) と with の複製
    private void EmitRecordClassCore(TypeDeclSym t)
    {
        string n = t.LuaName;
        var fields = InstanceFields(t);
        var eqs = new List<string>();
        eqs.Add("getmetatable(a) == getmetatable(b)");
        foreach (var f in fields) eqs.Add(FieldEquals("a" + FieldAccess(f.Name), "b" + FieldAccess(f.Name), f.Type));
        Line("function " + n + ".__eq(a, b)");
        Line("  return " + string.Join(" and ", eqs));
        Line("end");
        Line("");
        var cps = new List<string>();
        foreach (var f in fields) cps.Add(FieldKey(f.Name) + " = " + CopyText("s" + FieldAccess(f.Name), f.Type));
        Line("function " + n + ".__clone(s)");
        Line("  return setmetatable({" + string.Join(", ", cps) + "}, " + n + ")");
        Line("end");
        Line("");
    }

    // 値の copy (可変 struct だけ。入れ子の field の copy に使う)
    private static string CopyText(string v, TypeSym t)
    {
        if (t.Kind == TypeKind.Struct && t.Decl != null && !t.Decl.IsImmutable) return t.Decl.LuaName + ".__copy(" + v + ")";
        return v;
    }

    private static string FieldEquals(string a, string b, TypeSym t)
    {
        if (t.Kind == TypeKind.Nullable && t.Elem.Kind == TypeKind.Struct && t.Elem.Decl != null)
            return "(" + a + " == nil and " + b + " == nil or " + a + " ~= nil and " + b + " ~= nil and " + t.Elem.Decl.LuaName + ".__equals(" + a + ", " + b + "))";
        if (t.Kind == TypeKind.Nullable && t.Elem.Kind == TypeKind.Float) return FieldEquals(a, b, t.Elem);
        if (t.Kind == TypeKind.Float) return "(" + a + " == " + b + " or " + a + " ~= " + a + " and " + b + " ~= " + b + ")";
        if (t.Kind == TypeKind.Struct && t.Decl != null) return t.Decl.LuaName + ".__equals(" + a + ", " + b + ")";
        return a + " == " + b;
    }

    private static bool IsMutableStruct(TypeSym? t) => t != null && t.Kind == TypeKind.Struct && t.Decl != null && !t.Decl.IsImmutable;

    // 式が変数 (局所変数、field、要素、property) を読むか。読んだ struct の値は別の場所へ移すときに copy する
    private static bool IsStorageRead(Node e)
    {
        switch (e.Kind)
        {
            case NodeKind.Conv:
                return e.Info == ConvKind.Identity && IsStorageRead(e.A!);
            case NodeKind.Paren:
                return IsStorageRead(e.A!);
            case NodeKind.Name:
            case NodeKind.Member:
                return e.Info == RefKind.Local || e.Info == RefKind.Field || e.Info == RefKind.Property;
            case NodeKind.Index:
            case NodeKind.This:
                return true;
        }
        return false;
    }

    // C# の変数 (局所変数、field、配列の要素、this)。List の要素と property は値の copy
    private static bool IsVariable(Node e)
    {
        switch (e.Kind)
        {
            case NodeKind.Conv:
            case NodeKind.Paren:
                return IsVariable(e.A!);
            case NodeKind.Name:
            case NodeKind.Member:
                return e.Info == RefKind.Local || e.Info == RefKind.Field;
            case NodeKind.Index:
                return e.A!.Type != null && e.A.Type.Kind == TypeKind.Array;
            case NodeKind.This:
                return true;
        }
        return false;
    }

    // 新しく作った値の式 (copy しなくても他の場所と table を共有しない)
    private static bool IsFresh(Node e)
    {
        switch (e.Kind)
        {
            case NodeKind.New:
            case NodeKind.DefaultLit:
            case NodeKind.SwitchExpr:
            case NodeKind.Conditional:
            case NodeKind.NullLit:
                return true;
            case NodeKind.Call:
                // user の method は値を copy して返す
                return e.Info == CallKind.Method || e.Info == CallKind.Extension;
            case NodeKind.Binary:
            case NodeKind.Unary:
                return e.Sym != null;
            case NodeKind.Paren:
                return IsFresh(e.A!);
            case NodeKind.Conv:
                return e.A != null && IsFresh(e.A);
        }
        return false;
    }

    // 可変 struct (またはその T?) の値を別の場所へ移すときの copy の式。要らなければ null
    private static string? CopyFunc(Node e)
    {
        var t = e.Type;
        if (t == null || IsFresh(e)) return null;
        if (IsMutableStruct(t)) return t.Decl!.LuaName + ".__copy";
        if (t.Kind == TypeKind.Nullable && IsMutableStruct(t.Elem)) return t.Elem.Decl!.LuaName + ".__ncopy";
        return null;
    }

    // 値として移す式 (可変 struct の値を他の場所と共有しないように copy)
    private string Val(Node e)
    {
        string v = Expr(e);
        string? f = CopyFunc(e);
        if (f != null) return f + "(" + v + ")";
        return v;
    }

    // operand の列のうち、値として移すもの (呼び出しの引数など) を copy する
    private void CopyOperands(List<Node> nodes, List<string> texts)
    {
        for (int i = 0; i < nodes.Count; i++)
        {
            string? f = CopyFunc(nodes[i]);
            if (f != null) texts[i] = f + "(" + texts[i] + ")";
        }
    }

    // ---- generic の型引数の記述子 ----

    // 型引数の既定値と struct の copy を表す値 (参照実装と同じ形): 数値は既定値、struct は __tcs_td、参照型は nil
    private string DescText(TypeSym t)
    {
        switch (t.Kind)
        {
            case TypeKind.Int:
            case TypeKind.Char:
            case TypeKind.Byte:
            case TypeKind.UInt:
            case TypeKind.Short:
            case TypeKind.Long:
                return "0";
            case TypeKind.Enum:
                // enum は名前の表を持つ記述子 (型引数の値の文字列化に使う)
                if (t.Decl != null) return "__tcs_etd(" + LuaString(EnumSpec(t.Decl)) + ")";
                return "0";
            case TypeKind.Float:
            case TypeKind.Double:
                return "0.0";
            case TypeKind.Bool:
                return "false";
            case TypeKind.Struct:
                if (t.Decl != null) return t.Decl.LuaName + ".__tcs_td";
                break;
            case TypeKind.Utf8Bytes:
                return "TinySystem.Utf8.Default()";
            case TypeKind.TypeParam:
                return DescVar(t);
        }
        return "nil";
    }

    private string DescVar(TypeSym tp)
    {
        if (tp.IsMethodParam) return "__tcs_dm_" + tp.Name;
        return (_fn.DescViaSelf ? "self.__tcs_dc_" : "__tcs_dc_") + tp.Name;
    }

    // 型の型引数の記述子の引数名
    private static List<string> ClassDescParams(TypeDeclSym t)
    {
        var r = new List<string>();
        foreach (var tp in t.TypeParams) r.Add("__tcs_dc_" + tp);
        return r;
    }

    // ---- constructor ----

    private void EmitCtors(TypeDeclSym t)
    {
        bool chained = false;
        foreach (var c in t.Ctors)
        {
            if (c.Decl != null && c.Decl.Kind == NodeKind.Ctor && c.Decl.D != null) chained = true;
        }
        var dcs = ClassDescParams(t);
        if (t.Ctors.Count == 0)
        {
            Line("function " + t.LuaName + ".new(" + string.Join(", ", dcs) + ")");
            _indent++;
            _fn = new FnCtx();
            _fn.IsCtor = true;
            EmitNewSelf(t);
            EmitFieldInits(t);
            Line("return self");
            _indent--;
            Line("end");
            Line("");
            return;
        }
        foreach (var c in t.Ctors)
        {
            var decl = c.Decl!;
            var ps = ParamNames(decl, c);
            foreach (var dc in dcs) ps.Add(dc);
            if (chained)
            {
                Line("function " + t.LuaName + ".__init_" + c.LuaName + "(" + JoinParams("self", ps) + ")");
                _indent++;
                _fn = new FnCtx();
                _fn.IsCtor = true;
                _fn.IsInit = true;
                EmitCtorBody(t, c, decl);
                _indent--;
                Line("end");
                Line("");
                Line("function " + t.LuaName + "." + c.LuaName + "(" + string.Join(", ", ps) + ")");
                var dfields = new List<string>();
                foreach (var dc in dcs) dfields.Add(dc + " = " + dc);
                Line("  local self = setmetatable({" + string.Join(", ", dfields) + "}, " + t.LuaName + ")");
                Line("  " + t.LuaName + ".__init_" + c.LuaName + "(" + JoinParams("self", ps) + ")");
                Line("  return self");
                Line("end");
                Line("");
                continue;
            }
            Line("function " + t.LuaName + "." + c.LuaName + "(" + string.Join(", ", ps) + ")");
            _indent++;
            _fn = new FnCtx();
            _fn.IsCtor = true;
            EmitNewSelf(t);
            EmitCtorBody(t, c, decl);
            Line("return self");
            _indent--;
            Line("end");
            Line("");
        }
    }

    private static string JoinParams(string first, List<string> rest)
    {
        if (rest.Count == 0) return first;
        return first + ", " + string.Join(", ", rest);
    }

    private void EmitCtorBody(TypeDeclSym t, Symbol c, Node decl)
    {
        if (decl.Kind == NodeKind.Ctor && decl.D != null && decl.D.Sym != null)
        {
            // this(...) の連鎖
            var target = decl.D.Sym;
            var args = CallArgs(decl.D, target);
            foreach (var dc in ClassDescParams(t)) args.Add(dc);
            Line(t.LuaName + ".__init_" + target.LuaName + "(" + JoinParams("self", args) + ")");
        }
        else
        {
            if (_fn.IsInit) EmitFieldDefaults(t);
            EmitFieldInits(t);
            if (t.IsRecord && decl.Kind == NodeKind.Param)
            {
                foreach (var p in t.RecordParams!) Line("self." + LuaNames.Member(p.Name) + " = " + LuaNames.Local(p.Name));
            }
        }
        if (decl.Kind != NodeKind.Ctor) return;
        if (decl.B != null) EmitStatements(decl.B);
        else if (decl.C != null) EmitExprStatement(decl.C);
    }

    private void EmitNewSelf(TypeDeclSym t)
    {
        var parts = new List<string>();
        foreach (var dc in ClassDescParams(t)) parts.Add(dc + " = " + dc);
        foreach (var m in t.Members)
        {
            if (m.IsStatic) continue;
            if (m.Kind != SymKind.Field && !(m.Kind == SymKind.Property && m.IsAuto)) continue;
            Node? init = m.Kind == SymKind.Field ? m.Decl != null ? m.Decl.A : null : m.Decl != null && m.Decl.Kind == NodeKind.Property ? m.Decl.D : null;
            if (init != null && !init.HasConst) continue;
            string? v = init != null ? ConstText(init.Const!, m.Type) : DefaultValue(m.Type);
            if (m.Type.Kind == TypeKind.TypeParam && init == null) v = "__tcs_dv(" + DescText(m.Type) + ")";
            if (v == null || v == "nil") continue;
            parts.Add(FieldKey(m.Name) + " = " + v);
        }
        Line("local self = setmetatable({" + string.Join(", ", parts) + "}, " + t.LuaName + ")");
    }

    // __init_ の中の field の既定値 (setmetatable の table に入れられない場合)
    private void EmitFieldDefaults(TypeDeclSym t)
    {
        foreach (var m in t.Members)
        {
            if (m.IsStatic) continue;
            if (m.Kind != SymKind.Field && !(m.Kind == SymKind.Property && m.IsAuto)) continue;
            Node? init = m.Kind == SymKind.Field ? m.Decl != null ? m.Decl.A : null : m.Decl != null && m.Decl.Kind == NodeKind.Property ? m.Decl.D : null;
            if (init != null && !init.HasConst) continue;
            string? v = init != null ? ConstText(init.Const!, m.Type) : DefaultValue(m.Type);
            if (m.Type.Kind == TypeKind.TypeParam && init == null) v = "__tcs_dv(" + DescText(m.Type) + ")";
            if (v == null || v == "nil") continue;
            Line("self" + FieldAccess(m.Name) + " = " + v);
        }
    }

    // 定数でない field の初期化子 (宣言順)。struct の constructor は定数の初期化子も実行する
    // (struct の既定値 new() は初期化子を含まない)
    private void EmitFieldInits(TypeDeclSym t)
    {
        foreach (var m in t.Members)
        {
            if (m.IsStatic) continue;
            if (m.Kind != SymKind.Field && !(m.Kind == SymKind.Property && m.IsAuto)) continue;
            Node? init = m.Kind == SymKind.Field ? m.Decl != null ? m.Decl.A : null : m.Decl != null && m.Decl.Kind == NodeKind.Property ? m.Decl.D : null;
            if (init == null || init.HasConst && !t.IsStruct) continue;
            int mark = _out.Count;
            Line("do");
            _indent++;
            string v = Val(init);
            Line("self" + FieldAccess(m.Name) + " = " + v);
            _indent--;
            Line("end");
            CollapseDo(mark);
        }
    }

    private static string FieldKey(string name)
    {
        if (LuaNames.IsLuaKeyword(name)) return "[" + LuaString(name) + "]";
        return name;
    }

    private static string FieldAccess(string name)
    {
        if (LuaNames.IsLuaKeyword(name)) return "[" + LuaString(name) + "]";
        return "." + name;
    }

    // ---- method と property ----

    private List<string> ParamNames(Node decl, Symbol m)
    {
        var ps = new List<string>();
        if (decl.Kind == NodeKind.Param)
        {
            // record の positional parameter
            foreach (var p in decl.List!) ps.Add(LuaNames.Local(p.Text));
            return ps;
        }
        if (decl.List == null) return ps;
        for (int i = 0; i < decl.List.Count; i++)
        {
            var p = decl.List[i];
            if (m.Params != null && i < m.Params.Count && m.Params[i].IsOut) continue;
            ps.Add(p.Local != null ? p.Local.LuaName : LuaNames.Local(p.Text));
        }
        return ps;
    }

    private void EmitMethod(TypeDeclSym t, Symbol m)
    {
        var decl = m.Decl!;
        if (decl.B == null && decl.C == null) return;
        var ps = ParamNames(decl, m);
        string sep = m.IsStatic ? "." : ":";
        if (t.IsStruct && !m.IsStatic)
        {
            // struct の instance の method は self を最初の引数に取る静的な関数
            sep = ".";
            ps.Insert(0, "self");
        }
        // generic の記述子: method の型引数と、generic な型の static な member の型の型引数
        if (m.TypeParams != null)
        {
            foreach (var tp in m.TypeParams) ps.Add("__tcs_dm_" + tp);
        }
        if (m.IsStatic)
        {
            foreach (var dc in ClassDescParams(t)) ps.Add(dc);
        }
        Line("function " + t.LuaName + sep + m.LuaName + "(" + string.Join(", ", ps) + ")");
        _indent++;
        _fn = new FnCtx();
        _fn.DescViaSelf = !m.IsStatic;
        _fn.HasReturnValue = m.Type.Kind != TypeKind.Void;
        if (decl.List != null && m.Params != null)
        {
            for (int i = 0; i < decl.List.Count; i++)
            {
                if (m.Params[i].IsOut)
                {
                    string name = decl.List[i].Local!.LuaName;
                    _fn.OutNames.Add(name);
                    Line("local " + name);
                }
            }
        }
        EmitBody(decl, m.Type);
        _indent--;
        Line("end");
        Line("");
    }

    private void EmitBody(Node decl, TypeSym ret)
    {
        if (decl.B != null)
        {
            EmitStatements(decl.B);
            if (_fn.OutNames.Count > 0 && !_fn.HasReturnValue && !EndsWithReturn(decl.B)) Line("return " + string.Join(", ", _fn.OutNames));
        }
        else if (decl.C != null)
        {
            if (ret.Kind == TypeKind.Void)
            {
                EmitExprStatement(decl.C);
                if (_fn.OutNames.Count > 0) Line("return " + string.Join(", ", _fn.OutNames));
            }
            else
            {
                string v = Val(decl.C);
                Line("return " + ReturnList(v));
            }
        }
    }

    private static bool EndsWithReturn(Node block)
    {
        if (block.List == null || block.List.Count == 0) return false;
        return block.List[block.List.Count - 1].Kind == NodeKind.Return;
    }

    private string ReturnList(string v)
    {
        if (_fn.OutNames.Count == 0) return v;
        return v + ", " + string.Join(", ", _fn.OutNames);
    }

    private void EmitProperty(TypeDeclSym t, Symbol p)
    {
        if (p.IsAuto) return;
        var decl = p.Decl!;
        string sep = p.IsStatic ? "." : ":";
        string selfArg = "";
        if (t.IsStruct && !p.IsStatic)
        {
            sep = ".";
            selfArg = "self";
        }
        if (decl.B != null && (decl.B.A != null || decl.B.B != null))
        {
            Line("function " + t.LuaName + sep + "get_" + p.Name + "(" + selfArg + ")");
            _indent++;
            _fn = new FnCtx();
            _fn.DescViaSelf = !p.IsStatic;
            _fn.HasReturnValue = true;
            if (decl.B.A != null) EmitStatements(decl.B.A);
            else Line("return " + Val(decl.B.B!));
            _indent--;
            Line("end");
            Line("");
        }
        if (decl.C != null && (decl.C.A != null || decl.C.B != null))
        {
            Line("function " + t.LuaName + sep + "set_" + p.Name + "(" + (selfArg == "" ? "value" : "self, value") + ")");
            _indent++;
            _fn = new FnCtx();
            _fn.DescViaSelf = !p.IsStatic;
            if (decl.C.A != null) EmitStatements(decl.C.A);
            else EmitExprStatement(decl.C.B!);
            _indent--;
            Line("end");
            Line("");
        }
    }

    // ---- 文 ----

    private void EmitStatements(Node block)
    {
        if (block.List == null) return;
        int n = block.List.Count;
        for (int i = 0; i < n; i++)
        {
            var s = block.List[i];
            if (s.Kind == NodeKind.Return && i < n - 1)
            {
                // Lua の return はブロックの最後にしか書けない
                Line("do");
                _indent++;
                EmitStatement(s);
                _indent--;
                Line("end");
                continue;
            }
            EmitStatement(s);
        }
    }

    private void DeclareStmtLocals(Node s)
    {
        if (s.DeclLocals == null) return;
        var names = new List<string>();
        foreach (var l in s.DeclLocals) names.Add(l.LuaName);
        Line("local " + string.Join(", ", names));
    }

    private void EmitEmbedded(Node s)
    {
        if (s.Kind == NodeKind.Block) EmitStatements(s);
        else EmitStatement(s);
    }

    private void EmitStatement(Node s)
    {
        switch (s.Kind)
        {
            case NodeKind.Block:
                Line("do");
                _indent++;
                EmitStatements(s);
                _indent--;
                Line("end");
                return;
            case NodeKind.Empty:
            case NodeKind.Unsupported:
                return;
            case NodeKind.LocalDecl:
                EmitLocalDecl(s);
                return;
            case NodeKind.DeconstructDecl:
                {
                    var names = new List<string>();
                    foreach (var nm in s.List!) names.Add(nm.Local!.LuaName);
                    Line("local " + string.Join(", ", names));
                    Line("do");
                    _indent++;
                    string v = Spill(Expr(s.A!));
                    foreach (var nm in s.List)
                    {
                        if (nm.Sym != null) Line(nm.Local!.LuaName + " = " + CopyText(MemberValueText(v, nm.Sym, false), nm.Local.Type));
                    }
                    _indent--;
                    Line("end");
                    return;
                }
            case NodeKind.ExprStmt:
                DeclareStmtLocals(s);
                EmitWrapped(s.A!);
                return;
            case NodeKind.If:
                EmitIf(s);
                return;
            case NodeKind.While:
                EmitWhile(s);
                return;
            case NodeKind.DoWhile:
                EmitDoWhile(s);
                return;
            case NodeKind.For:
                EmitFor(s);
                return;
            case NodeKind.Foreach:
                EmitForeach(s);
                return;
            case NodeKind.Break:
                Line("break");
                return;
            case NodeKind.Continue:
                {
                    var loop = _loops[_loops.Count - 1];
                    loop.UsesContinue = true;
                    Line("goto " + loop.Label);
                    return;
                }
            case NodeKind.Return:
                EmitReturn(s);
                return;
            case NodeKind.Switch:
                EmitSwitch(s);
                return;
        }
    }

    // 式文。前置きの文を出したら do ... end で囲む
    private void EmitWrapped(Node e)
    {
        int mark = _out.Count;
        Line("do");
        _indent++;
        EmitExprStatement(e);
        _indent--;
        Line("end");
        CollapseDo(mark);
    }

    private void EmitLocalDecl(Node s)
    {
        DeclareStmtLocals(s);
        foreach (var v in s.List!)
        {
            var l = v.Local!;
            if (v.A == null)
            {
                Line("local " + l.LuaName);
                continue;
            }
            int mark = _out.Count;
            string value = v.A.Kind == NodeKind.ArrayInit ? Expr(v.A) : Val(v.A);
            if (_out.Count == mark)
            {
                Line("local " + l.LuaName + " = " + value);
                continue;
            }
            // 前置きの文があった: 宣言を前に出し、前置きを do で囲む
            var pre = Extract(mark);
            Line("local " + l.LuaName);
            Line("do");
            _indent++;
            foreach (var p in pre) _out.Add("  " + p);
            Line(l.LuaName + " = " + value);
            _indent--;
            Line("end");
        }
    }

    private List<string> Extract(int mark)
    {
        var lines = new List<string>();
        while (_out.Count > mark)
        {
            lines.Add(_out[mark]);
            _out.RemoveAt(mark);
        }
        return lines;
    }

    private void EmitIf(Node s)
    {
        DeclareStmtLocals(s);
        int mark = _out.Count;
        string cond = Expr(s.A!);
        bool wrapped = false;
        if (_out.Count > mark)
        {
            var pre = Extract(mark);
            Line("do");
            _indent++;
            foreach (var p in pre) _out.Add("  " + p);
            wrapped = true;
        }
        Line("if " + cond + " then");
        _indent++;
        EmitEmbedded(s.B!);
        _indent--;
        var els = s.C;
        while (els != null && els.Kind == NodeKind.If && els.DeclLocals == null)
        {
            int m2 = _out.Count;
            string c2 = Expr(els.A!);
            if (_out.Count > m2)
            {
                // 前置きのある else if は入れ子にする
                var pre2 = Extract(m2);
                Line("else");
                _indent++;
                foreach (var p in pre2) _out.Add("  " + p);
                Line("if " + c2 + " then");
                _indent++;
                EmitEmbedded(els.B!);
                _indent--;
                if (els.C != null)
                {
                    Line("else");
                    _indent++;
                    EmitEmbedded(els.C);
                    _indent--;
                }
                Line("end");
                _indent--;
                els = null;
                break;
            }
            Line("elseif " + c2 + " then");
            _indent++;
            EmitEmbedded(els.B!);
            _indent--;
            els = els.C;
        }
        if (els != null)
        {
            Line("else");
            _indent++;
            EmitEmbedded(els);
            _indent--;
        }
        Line("end");
        if (wrapped)
        {
            _indent--;
            Line("end");
        }
    }

    private LoopCtx PushLoop()
    {
        var l = new LoopCtx();
        l.Label = NewLabel();
        _loops.Add(l);
        return l;
    }

    private void PopLoop()
    {
        _loops.RemoveAt(_loops.Count - 1);
    }

    // ループの本体: continue の label を本体の後に置く。trailing は本体の後に文 (for の更新) が続くか
    private void EmitLoopBody(Node body, LoopCtx loop)
    {
        EmitLoopBody2(body, loop, false);
    }

    private void EmitLoopBody2(Node body, LoopCtx loop, bool trailing)
    {
        int mark = _out.Count;
        Line("do");
        _indent++;
        EmitEmbedded(body);
        _indent--;
        Line("end");
        if (loop.UsesContinue) Line("::" + loop.Label + "::");
        else if (trailing || EndsWithReturnStmt(body))
        {
            // return は Lua のブロックの最後にしか書けないので do ... end を残す
        }
        else
        {
            // continue が無ければ do ... end は要らない
            _out.RemoveAt(_out.Count - 1);
            _out.RemoveAt(mark);
            for (int i = mark; i < _out.Count; i++) _out[i] = Unindent(_out[i]);
        }
    }

    private static bool EndsWithReturnStmt(Node body)
    {
        if (body.Kind == NodeKind.Return) return true;
        if (body.Kind == NodeKind.Block && body.List != null && body.List.Count > 0) return EndsWithReturnStmt(body.List[body.List.Count - 1]);
        return false;
    }

    private static string Unindent(string line)
    {
        if (line.StartsWith("  ")) return new Utf8Bytes(line).Slice(2, new Utf8Bytes(line).Length - 2).ToString();
        return line;
    }

    private void EmitWhile(Node s)
    {
        DeclareStmtLocals(s);
        int mark = _out.Count;
        string cond = Expr(s.A!);
        var loop = PushLoop();
        if (_out.Count == mark)
        {
            Line("while " + cond + " do");
            _indent++;
            EmitLoopBody(s.B!, loop);
            _indent--;
            Line("end");
        }
        else
        {
            var pre = Extract(mark);
            Line("while true do");
            _indent++;
            foreach (var p in pre) _out.Add("  " + p);
            Line("if not " + Paren(cond) + " then break end");
            EmitLoopBody(s.B!, loop);
            _indent--;
            Line("end");
        }
        PopLoop();
    }

    private void EmitDoWhile(Node s)
    {
        DeclareStmtLocals(s);
        var loop = PushLoop();
        Line("while true do");
        _indent++;
        EmitLoopBody2(s.B!, loop, true);
        string cond = Expr(s.A!);
        Line("if not " + Paren(cond) + " then break end");
        _indent--;
        Line("end");
        PopLoop();
    }

    private void EmitFor(Node s)
    {
        if (TryNumericFor(s)) return;
        Line("do");
        _indent++;
        if (s.List != null)
        {
            foreach (var init in s.List)
            {
                if (init.Kind == NodeKind.LocalDecl) EmitLocalDecl(init);
                else
                {
                    DeclareStmtLocals(init);
                    EmitWrapped(init.A!);
                }
            }
        }
        var loop = PushLoop();
        string cond = "true";
        List<string>? pre = null;
        if (s.A != null)
        {
            int mark = _out.Count;
            cond = Expr(s.A);
            if (_out.Count > mark) pre = Extract(mark);
        }
        if (pre == null)
        {
            Line("while " + cond + " do");
            _indent++;
        }
        else
        {
            Line("while true do");
            _indent++;
            foreach (var p in pre) _out.Add("  " + p);
            Line("if not " + Paren(cond) + " then break end");
        }
        EmitLoopBody2(s.B!, loop, s.List2 != null && s.List2.Count > 0);
        if (s.List2 != null)
        {
            foreach (var inc in s.List2) EmitWrapped(inc);
        }
        _indent--;
        Line("end");
        PopLoop();
        _indent--;
        Line("end");
    }

    // for (int i = a; i < b; i++) で i も b も本体で書き換えないものは Lua の数値 for にする
    private bool TryNumericFor(Node s)
    {
        if (s.List == null || s.List.Count != 1 || s.List[0].Kind != NodeKind.LocalDecl) return false;
        var decl = s.List[0];
        if (decl.List!.Count != 1 || decl.DeclLocals != null) return false;
        var v = decl.List[0];
        var l = v.Local!;
        if (l.Type.Kind != TypeKind.Int || v.A == null || l.Captured) return false;
        if (s.A == null || s.A.Kind != NodeKind.Binary) return false;
        string op = s.A.Text;
        if (op != "<" && op != "<=") return false;
        if (!IsLocalRef(s.A.A!, l)) return false;
        var bound = s.A.B!;
        if (s.List2 == null || s.List2.Count != 1) return false;
        var inc = s.List2[0];
        bool isInc = (inc.Kind == NodeKind.PostIncDec || inc.Kind == NodeKind.PreIncDec) && inc.Text == "++" && IsLocalRef(inc.A!, l);
        if (!isInc) return false;
        // bound は定数か、本体で書き換えない局所変数
        LocalSym? boundLocal = null;
        if (!bound.HasConst)
        {
            var b = bound.Kind == NodeKind.Conv ? bound.A! : bound;
            if (b.Kind != NodeKind.Name || b.Info != RefKind.Local) return false;
            boundLocal = b.Local;
            if (boundLocal!.Captured) return false;
        }
        if (Writes(s.B!, l) || boundLocal != null && Writes(s.B!, boundLocal)) return false;
        if (v.A.Kind == NodeKind.Lambda) return false;
        int mark = _out.Count;
        string start = Expr(v.A);
        string limit = Expr(bound);
        bool hasPre = _out.Count > mark;
        if (op == "<") limit = Sub1(limit, bound);
        var loop = PushLoop();
        if (hasPre)
        {
            var pre = Extract(mark);
            Line("do");
            _indent++;
            foreach (var p in pre) _out.Add("  " + p);
        }
        Line("for " + l.LuaName + " = " + start + ", " + limit + " do");
        _indent++;
        EmitLoopBody(s.B!, loop);
        _indent--;
        Line("end");
        if (hasPre)
        {
            _indent--;
            Line("end");
        }
        PopLoop();
        return true;
    }

    private string Sub1(string limit, Node bound)
    {
        if (bound.HasConst && bound.Const!.Kind == ConstKind.Int) return IntLiteral(bound.Const.I - 1);
        return limit + " - 1";
    }

    private static bool IsLocalRef(Node n, LocalSym l)
    {
        if (n.Kind == NodeKind.Conv) return IsLocalRef(n.A!, l);
        return n.Kind == NodeKind.Name && n.Info == RefKind.Local && n.Local == l;
    }

    // n の中で局所変数 l を書き換えるか (代入、++ / --、out 引数)
    private static bool Writes(Node n, LocalSym l)
    {
        if ((n.Kind == NodeKind.Assign || n.Kind == NodeKind.PostIncDec || n.Kind == NodeKind.PreIncDec) && IsLocalRef(n.A!, l)) return true;
        if (n.Kind == NodeKind.Arg && n.Has(Mods.Out) && n.A != null && IsLocalRef(n.A, l)) return true;
        if (n.Kind == NodeKind.Lambda) return false;
        if (n.A != null && Writes(n.A, l)) return true;
        if (n.B != null && Writes(n.B, l)) return true;
        if (n.C != null && Writes(n.C, l)) return true;
        if (n.D != null && Writes(n.D, l)) return true;
        if (n.List != null)
        {
            foreach (var x in n.List)
            {
                if (Writes(x, l)) return true;
            }
        }
        if (n.List2 != null)
        {
            foreach (var x in n.List2)
            {
                if (Writes(x, l)) return true;
            }
        }
        return false;
    }

    private void EmitForeach(Node s)
    {
        int mark = _out.Count;
        string coll = Expr(s.B!);
        var loop = PushLoop();
        bool wrapped = false;
        if (_out.Count > mark || !IsSimpleName(coll))
        {
            var pre = Extract(mark);
            Line("do");
            _indent++;
            foreach (var p in pre) _out.Add("  " + p);
            wrapped = true;
            string t = NewTemp();
            Line("local " + t + " = " + coll);
            coll = t;
        }
        string var = s.Local != null ? s.Local.LuaName : "_";
        switch (s.Info)
        {
            case ForeachKind.List:
            case ForeachKind.Array:
                {
                    string i = NewTemp();
                    string len = s.Info == ForeachKind.Array || !NilElements(s.B!.Type!) ? "#" + coll : "(" + coll + ".n or #" + coll + ")";
                    Line("for " + i + " = 1, " + len + " do");
                    _indent++;
                    Line("local " + var + " = " + CopyText(coll + "[" + i + "]", ElemOf(s.B!.Type!)));
                    break;
                }
            case ForeachKind.Dict:
                {
                    bool fk = FloatKeyed(s.B!.Type);
                    if (s.List != null)
                    {
                        string k = s.List[0].Local!.LuaName;
                        string v = s.List.Count > 1 ? s.List[1].Local!.LuaName : "_";
                        Line("for " + k + ", " + v + " in pairs(" + coll + ") do");
                        _indent++;
                        if (fk) Line(k + " = Dict.FloatKeyOut(" + k + ")");
                    }
                    else
                    {
                        string k = NewTemp();
                        string v = NewTemp();
                        Line("for " + k + ", " + v + " in pairs(" + coll + ") do");
                        _indent++;
                        Line("local " + var + " = {Key = " + (fk ? "Dict.FloatKeyOut(" + k + ")" : k) + ", Value = " + v + "}");
                    }
                    break;
                }
            case ForeachKind.HashSet:
            case ForeachKind.Queue:
                {
                    // 要素の写しを長さで回る (null の要素で止まらない)
                    string l = NewTemp();
                    string i = NewTemp();
                    Line("local " + l + " = " + (s.Info == ForeachKind.HashSet ? "TcsHashSet" : "TcsQueue") + ".ToList(" + coll + ")");
                    Line("for " + i + " = 1, (" + l + ".n or #" + l + ") do");
                    _indent++;
                    Line("local " + var + " = " + l + "[" + i + "]");
                    break;
                }
            case ForeachKind.Runes:
                Line("for _, " + var + " in tcs_utf8.codes(" + coll + ") do");
                _indent++;
                break;
            default:
                Line("for _, " + var + " in ipairs(" + coll + ") do");
                _indent++;
                break;
        }
        if (s.Type2 != null) Line(var + " = " + CastValue(var, s.B!.Type!.Kind == TypeKind.Dict ? s.Type2 : ElemOf(s.B.Type!), s.Type2));
        EmitLoopBody(s.C!, loop);
        _indent--;
        Line("end");
        PopLoop();
        if (wrapped)
        {
            _indent--;
            Line("end");
        }
    }

    private static TypeSym ElemOf(TypeSym t) => t.Args != null && t.Args.Count > 0 ? t.Args[0] : TypeSym.ErrorType;

    private string CastValue(string v, TypeSym from, TypeSym to)
    {
        if (from.Kind == TypeKind.Float && to.IsIntegral) return "__tcs_trunc(" + v + ")";
        if (from.IsIntegral && to.Kind == TypeKind.Float) return "(" + v + " * 1.0)";
        if (to.Kind == TypeKind.Class && to.Decl != null && from.Kind != TypeKind.Class) return "__tcs_cast(" + v + ", " + to.Decl.LuaName + ")";
        if (to.Kind == TypeKind.Interface && to.Decl != null) return "__tcs_icast(" + v + ", " + LuaString(to.Decl.LuaName) + ")";
        return v;
    }

    private static bool IsSimpleName(string s)
    {
        var u = new Utf8Bytes(s);
        if (u.Length == 0) return false;
        for (int i = 0; i < u.Length; i++)
        {
            int c = u[i];
            if (!(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c == '_' || i > 0 && c >= '0' && c <= '9')) return false;
        }
        return true;
    }

    private void EmitReturn(Node s)
    {
        DeclareStmtLocals(s);
        if (_fn.IsCtor && !_fn.IsLambda)
        {
            Line(_fn.IsInit ? "return" : "return self");
            return;
        }
        if (s.A == null)
        {
            if (_fn.OutNames.Count > 0 && !_fn.IsLambda) Line("return " + string.Join(", ", _fn.OutNames));
            else Line("return");
            return;
        }
        int mark = _out.Count;
        string v = Val(s.A);
        if (_out.Count > mark)
        {
            var pre = Extract(mark);
            Line("do");
            _indent++;
            foreach (var p in pre) _out.Add("  " + p);
            Line("return " + (_fn.IsLambda ? v : ReturnList(v)));
            _indent--;
            Line("end");
            return;
        }
        Line("return " + (_fn.IsLambda ? v : ReturnList(v)));
    }

    // switch 文: repeat ... until true で囲み、C# の break を Lua の break にする
    private void EmitSwitch(Node s)
    {
        DeclareStmtLocals(s);
        Line("repeat");
        _indent++;
        string gv = Expr(s.A!);
        if (!IsSimpleName(gv) || IsMutableName(s.A!))
        {
            string t = NewTemp();
            Line("local " + t + " = " + gv);
            gv = t;
        }
        // pattern の変数を先に宣言して値を入れる
        foreach (var sec in s.List!)
        {
            DeclareStmtLocals(sec);
            foreach (var label in sec.List!)
            {
                if (label.Kind == NodeKind.CaseLabel) AssignDesignations(label.A!, gv);
            }
        }
        Node? defaultSec = null;
        bool first = true;
        int nested = 0;
        foreach (var sec in s.List)
        {
            bool isDefault = false;
            foreach (var label in sec.List!)
            {
                if (label.Kind == NodeKind.DefaultLabel) isDefault = true;
            }
            // default は位置によらず最後に照合する (同じ section の case は順に照合する)
            if (isDefault) defaultSec = sec;
            if (isDefault && sec.List.Count == 1) continue;
            var conds = new List<string>();
            int mark = _out.Count;
            foreach (var label in sec.List)
            {
                if (label.Kind == NodeKind.DefaultLabel) continue;
                string c = PatternCond(label.A!, gv, s.A!.Type!);
                if (label.B != null) c = "(" + c + " and " + Expr(label.B) + ")";
                conds.Add(c);
            }
            if (_out.Count > mark)
            {
                // when の前置きの文: else の中に入れ子の if を作る
                var pre = Extract(mark);
                if (!first)
                {
                    Line("else");
                    _indent++;
                    nested++;
                }
                foreach (var p in pre) _out.Add(Indent() + p.Trim());
                Line("if " + string.Join(" or ", conds) + " then");
                _indent++;
                EmitSectionBody(sec);
                _indent--;
                first = false;
                continue;
            }
            Line((first ? "if " : "elseif ") + string.Join(" or ", conds) + " then");
            _indent++;
            EmitSectionBody(sec);
            _indent--;
            first = false;
        }
        if (defaultSec != null)
        {
            if (first) EmitSectionBody(defaultSec);
            else
            {
                Line("else");
                _indent++;
                EmitSectionBody(defaultSec);
                _indent--;
            }
        }
        if (!first) Line("end");
        for (int i = 0; i < nested; i++)
        {
            _indent--;
            Line("end");
        }
        _indent--;
        Line("until true");
    }

    private static bool IsMutableName(Node e) => false;

    private void EmitSectionBody(Node sec)
    {
        if (sec.List2 == null) return;
        int n = sec.List2.Count;
        for (int i = 0; i < n; i++)
        {
            var st = sec.List2[i];
            // 最後の break は repeat を抜けるのと同じなので省ける (省かなくても正しい)
            if (st.Kind == NodeKind.Break && i == n - 1)
            {
                Line("break");
                continue;
            }
            if (st.Kind == NodeKind.Return && i < n - 1)
            {
                Line("do");
                _indent++;
                EmitStatement(st);
                _indent--;
                Line("end");
                continue;
            }
            EmitStatement(st);
        }
    }

    // pattern の変数に値を入れる (型の検査の前に入れてよい: 検査に失敗した変数は C# では読めない)
    private void AssignDesignations(Node p, string v)
    {
        switch (p.Kind)
        {
            case NodeKind.PatDecl:
            case NodeKind.PatVar:
                if (p.Local != null && p.Local.Name != "_") Line(p.Local.LuaName + " = " + v);
                return;
            case NodeKind.PatProp:
                if (p.Local != null) Line(p.Local.LuaName + " = " + v);
                return;
            case NodeKind.PatAnd:
            case NodeKind.PatOr:
                AssignDesignations(p.A!, v);
                AssignDesignations(p.B!, v);
                return;
            case NodeKind.PatNot:
                AssignDesignations(p.A!, v);
                return;
        }
    }

    // pattern が値 v に合うかの Lua の条件式
    private string PatternCond(Node p, string v, TypeSym input)
    {
        switch (p.Kind)
        {
            case NodeKind.PatDiscard:
            case NodeKind.PatVar:
                return "true";
            case NodeKind.PatType:
            case NodeKind.PatDecl:
                return TypeTest(v, input, p.Type!);
            case NodeKind.PatConst:
                {
                    var c = p.A!;
                    if (c.HasConst && c.Const!.Kind == ConstKind.Null) return "(" + v + " == nil)";
                    return "(" + v + " == " + Expr(c) + ")";
                }
            case NodeKind.PatRel:
                return "(" + v + " " + p.Text + " " + Expr(p.A!) + ")";
            case NodeKind.PatNot:
                return "(not " + PatternCond(p.A!, v, input) + ")";
            case NodeKind.PatAnd:
                return "(" + PatternCond(p.A!, v, input) + " and " + PatternCond(p.B!, v, NarrowType(p.A!, input)) + ")";
            case NodeKind.PatOr:
                return "(" + PatternCond(p.A!, v, input) + " or " + PatternCond(p.B!, v, input) + ")";
            case NodeKind.PatProp:
                {
                    var parts = new List<string>();
                    var t = p.Type!;
                    if (p.A != null) parts.Add(TypeTest(v, input, t));
                    else if (input.IsNullable) parts.Add("(" + v + " ~= nil)");
                    if (p.List != null)
                    {
                        foreach (var sub in p.List)
                        {
                            string mv = MemberValue(v, t, sub.Sym, sub.Info);
                            var sp = sub.A!;
                            bool computed = sub.Sym != null && (sub.Sym.Kind == SymKind.Property && !IsFieldBacked(sub.Sym) || sub.Sym.Builtin != "");
                            if (HasDesignation(sp) || computed && !IsSingleUse(sp))
                            {
                                // member を 1 度だけ読み、入れ子の pattern の変数に値を入れる
                                string pn = NewTemp();
                                var assigns = new List<string>();
                                DesignationAssignments(sp, pn, assigns);
                                string inner = PatternCond(sp, pn, sub.Type!);
                                parts.Add("(function(" + pn + ") " + string.Join(" ", assigns) + (assigns.Count > 0 ? " " : "") + "return " + inner + " end)(" + mv + ")");
                            }
                            else parts.Add(PatternCond(sp, mv, sub.Type!));
                        }
                    }
                    if (parts.Count == 0) return "true";
                    return "(" + string.Join(" and ", parts) + ")";
                }
        }
        return "false";
    }

    private static bool HasDesignation(Node p)
    {
        switch (p.Kind)
        {
            case NodeKind.PatDecl:
            case NodeKind.PatVar:
                return p.Local != null && p.Local.Name != "_";
            case NodeKind.PatProp:
                if (p.Local != null) return true;
                if (p.List != null)
                {
                    foreach (var sub in p.List)
                    {
                        if (HasDesignation(sub.A!)) return true;
                    }
                }
                return false;
            case NodeKind.PatAnd:
            case NodeKind.PatOr:
                return HasDesignation(p.A!) || HasDesignation(p.B!);
            case NodeKind.PatNot:
                return HasDesignation(p.A!);
        }
        return false;
    }

    // 値を 1 度だけ使う pattern (受け手を何度も読まない)
    private static bool IsSingleUse(Node p)
    {
        switch (p.Kind)
        {
            case NodeKind.PatConst:
            case NodeKind.PatRel:
            case NodeKind.PatDiscard:
            case NodeKind.PatType:
                return true;
            case NodeKind.PatNot:
                return IsSingleUse(p.A!);
        }
        return false;
    }

    // pattern の変数への代入 (入れ子の pattern を関数の中で評価するとき)
    private static void DesignationAssignments(Node p, string v, List<string> into)
    {
        switch (p.Kind)
        {
            case NodeKind.PatDecl:
            case NodeKind.PatVar:
                if (p.Local != null && p.Local.Name != "_") into.Add(p.Local.LuaName + " = " + v);
                return;
            case NodeKind.PatProp:
                if (p.Local != null) into.Add(p.Local.LuaName + " = " + v);
                return;
            case NodeKind.PatAnd:
            case NodeKind.PatOr:
                DesignationAssignments(p.A!, v, into);
                DesignationAssignments(p.B!, v, into);
                return;
            case NodeKind.PatNot:
                DesignationAssignments(p.A!, v, into);
                return;
        }
    }

    private static TypeSym NarrowType(Node p, TypeSym input)
    {
        if ((p.Kind == NodeKind.PatType || p.Kind == NodeKind.PatDecl) && p.Type != null) return p.Type;
        return input;
    }

    private string MemberValue(string v, TypeSym owner, Symbol? sym, int info)
    {
        if (sym == null) return "nil";
        if (sym.Builtin != "") return BuiltinPropValue(sym, v, owner);
        if (sym.Kind == SymKind.Property && (!sym.IsAuto || owner.Kind == TypeKind.Interface))
        {
            if (sym.Owner != null && sym.Owner.IsStruct) return sym.Owner.LuaName + ".get_" + sym.Name + "(" + v + ")";
            return v + ":get_" + sym.Name + "()";
        }
        return v + FieldAccess(sym.Name);
    }

    private string TypeTest(string v, TypeSym input, TypeSym t)
    {
        if (TypeSym.Same(input, t) || input.Kind == TypeKind.Nullable && TypeSym.Same(input.Elem, t)) return "(" + v + " ~= nil)";
        switch (t.Kind)
        {
            case TypeKind.Class:
                return "(getmetatable(" + v + ") == " + t.Decl!.LuaName + ")";
            case TypeKind.Interface:
                return "__tcs_implements(" + v + ", " + LuaString(t.Decl!.LuaName) + ")";
            case TypeKind.String:
                return "(type(" + v + ") == \"string\")";
            case TypeKind.Int:
                return "(math.type(" + v + ") == \"integer\")";
            case TypeKind.Float:
                return "(math.type(" + v + ") == \"float\")";
            case TypeKind.Bool:
                return "(type(" + v + ") == \"boolean\")";
        }
        return "(" + v + " ~= nil)";
    }


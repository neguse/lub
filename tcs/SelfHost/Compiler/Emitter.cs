            case "Math.Pow": return "Math.Pow(" + a0 + ", " + a1 + ")";
            case "Console.WriteLine":
                {
                    if (t.Count == 0) return "print(\"\")";
                    var v = Unconv(e.Item(0).A!);
                    return "print(" + StringOperand(a0, v.Type!, v) + ")";
                }
            case "Console.Write":
                {
                    var v = Unconv(e.Item(0).A!);
                    return "io.write(" + StringOperand(a0, v.Type!, v) + ")";
                }
            case "Utf8.Slice": return "TinySystem.Utf8.Slice(" + recv + ", " + a0 + ", " + a1 + ")";
            case "Utf8.ToString": return "TinySystem.Utf8.ToString(" + recv + ")";
            case "Nullable.GetValueOrDefault": return "__tcs_nget(" + recv + ", " + (DefaultValue(rt!.Elem) ?? "nil") + ")";
            case "Delegate.Invoke": return Paren(recv) + "(" + args + ")";
        }
        if (m.Builtin.StartsWith("Char.")) return m.Builtin + "(" + a0 + ")";
        return "nil";
    }

    // object への変換を外した元の式 (文字列化は元の型で決める)
    private static Node Unconv(Node n)
    {
        while (n.Kind == NodeKind.Conv && n.Info == ConvKind.Identity && n.A != null && n.A.Type != null && n.Type != null && n.Type.Kind == TypeKind.Object) n = n.A;
        return n;
    }

    // float の key は NaN を表せるように正規化する (参照実装と同じ Dict.FloatKey)
    private static bool FloatKeyed(TypeSym? dictType)
    {
        return dictType != null && dictType.Kind == TypeKind.Dict && dictType.Args != null && dictType.Args[0].Kind == TypeKind.Float;
    }

    private static string DictKey(string k, TypeSym? dictType) => FloatKeyed(dictType) ? "Dict.FloatKey(" + k + ")" : k;

    // struct の要素の List は memberwise の等価で比べる
    private static string EqArg(TypeSym? listType)
    {
        if (listType == null || listType.Args == null || listType.Args.Count == 0) return "";
        var el = listType.Args[0];
        if (el.Kind == TypeKind.Struct && el.Decl != null) return ", " + el.Decl.LuaName + ".__equals";
        return "";
    }

    private string SpillForStatement(string v)
    {
        if (IsSimpleName(v)) return v;
        var u = new Utf8Bytes(v);
        // a.b.c の形はそのまま (評価は 1 回で副作用が無い)
        bool simplePath = true;
        for (int i = 0; i < u.Length; i++)
        {
            int c = u[i];
            if (!(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c == '_' || c >= '0' && c <= '9' || c == '.')) simplePath = false;
        }
        if (simplePath) return v;
        return Spill(v);
    }

    // ---- 定数と既定値 ----

    private static string? DefaultValue(TypeSym t)
    {
        switch (t.Kind)
        {
            case TypeKind.Int:
            case TypeKind.Char:
            case TypeKind.Byte:
            case TypeKind.UInt:
            case TypeKind.Short:
            case TypeKind.Long:
            case TypeKind.Enum:
                return "0";
            case TypeKind.Float:
            case TypeKind.Double:
                return "0.0";
            case TypeKind.Bool:
                return "false";
            case TypeKind.Utf8Bytes:
                return "TinySystem.Utf8.Default()";
            case TypeKind.Struct:
                if (t.Decl != null) return t.Decl.LuaName + ".new()";
                break;
        }
        return "nil";
    }

    private static string ConstText(ConstValue c, TypeSym t)
    {
        switch (c.Kind)
        {
            case ConstKind.Int:
                if (t.Kind == TypeKind.Float || t.Kind == TypeKind.Double) return FloatLiteral(IntToFloat(c.I));
                if (t.Kind == TypeKind.Nullable && t.Elem.Kind == TypeKind.Float) return FloatLiteral(IntToFloat(c.I));
                return IntLiteral(c.I);
            case ConstKind.Float: return FloatLiteral(c.F);
            case ConstKind.Bool: return c.B ? "true" : "false";
            case ConstKind.String: return LuaString(c.S);
            case ConstKind.Null: return "nil";
        }
        return "nil";
    }

    private static float IntToFloat(int i) => i;

    public static string IntLiteral(int v)
    {
        if (v == -2147483647 - 1) return "(-2147483647 - 1)";
        if (v < 0) return "(" + v + ")";
        return "" + v;
    }

    // float.IsNaN は参照実装の Lua の runtime に無い (呼ぶと nil を呼ぶ) ので自前で比べる
    private static bool IsNaN(float f)
    {
        float g = f;
        return f != g;
    }

    public static string FloatLiteral(float f)
    {
        if (IsNaN(f)) return "(0.0 / 0.0)";
        if (f > 3.4028235e38f) return "math.huge";
        if (f < -3.4028235e38f) return "(-math.huge)";
        string s = f.ToString();
        var u = new Utf8Bytes(s);
        bool hasMark = false;
        for (int i = 0; i < u.Length; i++)
        {
            int c = u[i];
            if (c == '.' || c == 'E' || c == 'e') hasMark = true;
        }
        if (!hasMark) s = s + ".0";
        if (u.Length > 0 && u[0] == '-') return "(" + s + ")";
        return s;
    }

    public static string LuaString(string s)
    {
        var u = new Utf8Bytes(s);
        var parts = new List<string>();
        int run = 0;
        for (int i = 0; i < u.Length; i++)
        {
            int c = u[i];
            string? esc = null;
            if (c == '"') esc = "\\\"";
            else if (c == '\\') esc = "\\\\";
            else if (c == '\n') esc = "\\n";
            else if (c == '\r') esc = "\\r";
            else if (c == '\t') esc = "\\t";
            else if (c < 32 || c == 127)
            {
                esc = "\\" + Pad3(c);
            }
            if (esc != null)
            {
                if (i > run) parts.Add(u.Slice(run, i - run).ToString());
                parts.Add(esc);
                run = i + 1;
            }
        }
        if (run == 0) return "\"" + s + "\"";
        if (run < u.Length) parts.Add(u.Slice(run, u.Length - run).ToString());
        return "\"" + string.Join("", parts) + "\"";
    }

    private static string Pad3(int c)
    {
        if (c < 10) return "00" + c;
        if (c < 100) return "0" + c;
        return "" + c;
    }

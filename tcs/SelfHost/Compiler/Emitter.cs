            case "List.Contains": return "List.Contains(" + recv + ", " + a0 + ")";
            case "List.IndexOf": return "List.IndexOf(" + recv + ", " + a0 + ")";
            case "List.Clear":
                {
                    string l = SpillForStatement(recv);

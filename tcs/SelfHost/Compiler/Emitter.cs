    // 引数の Lua の式 (out 引数を除き、省略引数は既定値で埋める)
    private List<string> CallArgs(Node call, Symbol m)
    {
        var nodes = new List<Node>();
        int n = call.Count;
        for (int i = 0; i < n; i++)
        {
            var arg = call.Item(i);
            if (arg.Has(Mods.Out)) continue;
            nodes.Add(arg.A!);
        }
        var result = EmitOperands(nodes);
        CopyOperands(nodes, result);
        for (int i = n; i < m.ParamCount; i++)
        {
            var p = m.Params![i];
            if (p.IsOut) continue;
            var d = p.Default;
            if (d != null && d.HasConst) result.Add(ConstText(d.Const!, p.Type));
            else if (d != null) result.Add(DefaultValue(p.Type) ?? "nil");
            else result.Add("nil");
        }
        AppendDescs(call, m, result);
        return result;
    }

    // generic な method と、generic な型の static な member と constructor の呼び出しに記述子を足す
    private void AppendDescs(Node call, Symbol m, List<string> args)
    {
        if (m.TypeParams != null)
        {
            for (int i = 0; i < m.TypeParams.Count; i++)
            {
                var ta = call.TypeArgs != null && i < call.TypeArgs.Count ? call.TypeArgs[i] : null;
                args.Add(ta != null ? DescText(ta) : "nil");
            }
        }
        var owner = m.Owner;
        if (owner == null || owner.TypeParams.Count == 0) return;
        if (!(m.IsStatic || m.Kind == SymKind.Ctor)) return;
        // 型引数: new の型、修飾した型の名前、同じ型の中からの呼び出し
        List<TypeSym>? targs = null;
        if (call.Kind == NodeKind.New && call.Type != null) targs = call.Type.Args;
        else if (call.A != null && call.A.Kind == NodeKind.Member && call.A.A != null && call.A.A.Type != null) targs = call.A.A.Type.Args;
        for (int i = 0; i < owner.TypeParams.Count; i++)
        {
            if (targs != null && i < targs.Count) args.Add(DescText(targs[i]));
            else if (_type == owner) args.Add(DescVar(owner.SelfType().Args![i]));
            else args.Add("nil");
        }
    }

    // out 引数の代入先 (呼び出しの後に値を入れる)
    private List<LValue> OutTargets(Node call)
    {
        var result = new List<LValue>();
        int n = call.Count;
        for (int i = 0; i < n; i++)
        {
            var arg = call.Item(i);
            if (!arg.Has(Mods.Out)) continue;
            var a = arg.A!;
            var lv = new LValue();
            if (a.Kind == NodeKind.PatDecl)
            {
                lv.Name = a.Local!.LuaName;
            }
            else if (a.Kind == NodeKind.PatDiscard)
            {
                lv.Name = "";
            }
            else lv = EmitLValue(a);
            result.Add(lv);
        }
        return result;
    }

    // out のある呼び出し: 戻り値と out の値を temp で受け、代入先へ入れる
    private string CallWithOuts(string callText, Node call, bool hasValue, bool asStatement)
    {
        var targets = OutTargets(call);
        var temps = new List<string>();
        string? ret = null;
        if (hasValue)
        {
            ret = NewTemp();
            temps.Add(ret);
        }
        var outTemps = new List<string>();
        foreach (var lv in targets)
        {
            string t = NewTemp();
            temps.Add(t);
            outTemps.Add(t);
        }
        Line("local " + string.Join(", ", temps) + " = " + callText);
        for (int i = 0; i < targets.Count; i++)
        {
            var lv = targets[i];
            if (lv.Kind == LValue.Plain && lv.Name == "") continue;
            Line(lv.Write(outTemps[i]));
        }
        if (asStatement) return "";
        return ret ?? "nil";
    }

    private string EmitCall(Node e, bool asStatement)
    {
        if (e.Text == "with") return WithText(e);
        if (e.HasConst && e.Info == CallKind.Nameof) return asStatement ? "" : ConstText(e.Const!, e.Type!);
        var m = e.Sym;
        var callee = e.A!;
        if (e.Info == CallKind.Delegate && e.Value == 1)
        {
            // d?.Invoke(x)
            string f = Spill(Expr(callee));
            string r = NewTemp();
            if (!asStatement) Line("local " + r);
            Line("if " + f + " ~= nil then");
            _indent++;
            var argNodes = new List<Node>();
            for (int i = 0; i < e.Count; i++) argNodes.Add(e.Item(i).A!);
            var at = EmitOperands(argNodes);
            string c = f + "(" + string.Join(", ", at) + ")";
            if (asStatement) Line(c);
            else Line(r + " = " + c);
            _indent--;
            Line("end");
            return asStatement ? "" : r;
        }
        if (e.Info == CallKind.Delegate)
        {
            var nodes = new List<Node>();
            nodes.Add(callee);
            for (int i = 0; i < e.Count; i++) nodes.Add(e.Item(i).A!);
            var t = EmitOperands(nodes);
            CopyOperands(nodes, t);
            string f = t[0];
            t.RemoveAt(0);
            return Paren(f) + "(" + string.Join(", ", t) + ")";
        }
        if (m == null) return "nil";
        bool conditional = callee.Kind == NodeKind.Member && callee.Value == 1;
        if (conditional) return ConditionalCall(e, asStatement);
        if (e.Info == CallKind.Builtin) return BuiltinCall(e, m, asStatement);
        bool hasOut = m.HasOut;
        bool hasValue = m.Type.Kind != TypeKind.Void;
        string text;
        if (e.Info == CallKind.Extension)
        {
            var nodes = new List<Node>();
            nodes.Add(e.B!);
            for (int i = 0; i < e.Count; i++)
            {
                if (!e.Item(i).Has(Mods.Out)) nodes.Add(e.Item(i).A!);
            }
            var t = EmitOperands(nodes);
            CopyOperands(nodes, t);
            AppendDescs(e, m, t);
            text = m.Owner!.LuaName + "." + m.LuaName + "(" + string.Join(", ", t) + ")";
        }
        else if (m.IsStatic)
        {
            var args = CallArgs(e, m);
            text = m.Owner!.LuaName + "." + m.LuaName + "(" + string.Join(", ", args) + ")";
        }
        else if (m.Owner != null && m.Owner.IsStruct)
        {
            // struct の instance の method: Owner.M(recv, args)。変数でない受け手 (List の要素、property) は copy に対して呼ぶ
            string r0;
            if (callee.Kind == NodeKind.Member)
            {
                r0 = ReceiverText(callee.A!);
                var rtype = callee.A!.CondChain && callee.A.Type2 != null ? callee.A.Type2 : callee.A.Type;
                if (IsMutableStruct(rtype) && !IsVariable(callee.A)) r0 = m.Owner.LuaName + ".__copy(" + r0 + ")";
            }
            else r0 = "self";
            int mark = _out.Count;
            var args = CallArgs(e, m);
            if (_out.Count > mark && !IsSimpleName(r0))
            {
                var pre = Extract(mark);
                string tr = NewTemp();
                Line("local " + tr + " = " + r0);
                r0 = tr;
                foreach (var p in pre) _out.Add(p);
            }
            args.Insert(0, r0);
            text = m.Owner.LuaName + "." + m.LuaName + "(" + string.Join(", ", args) + ")";
        }
        else
        {
            string recv;
            if (callee.Kind == NodeKind.Member)
            {
                var nodes = new List<Node>();
                nodes.Add(callee.A!);
                string r0 = ReceiverText(callee.A!);
                int mark = _out.Count;
                var args = CallArgs(e, m);
                if (_out.Count > mark && !IsSimpleName(r0))
                {
                    var pre = Extract(mark);
                    string tr = NewTemp();
                    Line("local " + tr + " = " + r0);
                    r0 = tr;
                    foreach (var p in pre) _out.Add(p);
                }
                recv = Paren(r0);
                text = recv + ":" + m.LuaName + "(" + string.Join(", ", args) + ")";
            }
            else
            {
                var args = CallArgs(e, m);
                text = "self:" + m.LuaName + "(" + string.Join(", ", args) + ")";
            }
        }
        if (hasOut) return CallWithOuts(text, e, hasValue, asStatement);
        return text;
    }

    // record の with: 複製 (struct は __copy、record class は __clone) してから member を書く
    private string WithText(Node e)
    {
        var t = e.Type!;
        string src = Expr(e.A!);
        string tmp = NewTemp();
        if (t.Decl != null && t.Decl.IsStruct) Line("local " + tmp + " = " + t.Decl.LuaName + ".__copy(" + src + ")");
        else if (t.Decl != null) Line("local " + tmp + " = " + t.Decl.LuaName + ".__clone(" + src + ")");
        else Line("local " + tmp + " = " + src);
        if (e.B != null && e.B.List != null)
        {
            foreach (var item in e.B.List)
            {
                if (item.Kind != NodeKind.MemberInit || item.Sym == null) continue;
                string v = Val(item.A!);
                if (item.Sym.Kind == SymKind.Property && !IsFieldBacked(item.Sym)) Line(tmp + ":set_" + item.Sym.Name + "(" + v + ")");
                else Line(tmp + FieldAccess(item.Sym.Name) + " = " + v);
            }
        }
        return tmp;
    }

    private string ConditionalCall(Node e, bool asStatement)
    {
        var callee = e.A!;
        string recv = Spill(Expr(callee.A!));
        string r = NewTemp();
        if (!asStatement) Line("local " + r);
        Line("if " + recv + " ~= nil then");
        _indent++;
        _condRecv[callee.A!] = recv;
        callee.Value = 0;
        string v = EmitCall(e, asStatement);
        callee.Value = 1;
        _condRecv.Remove(callee.A!);
        if (asStatement)
        {
            if (v != "") EmitCallStatement(v);
        }
        else Line(r + " = " + v);
        _indent--;
        Line("end");
        return asStatement ? "" : r;
    }


    private void EmitExprStatement(Node e)
    {
        switch (e.Kind)
        {
            case NodeKind.Assign:
                EmitAssign(e, false);
                return;
            case NodeKind.PostIncDec:
            case NodeKind.PreIncDec:
                EmitIncDec(e, false);
                return;
            case NodeKind.Call:
                {
                    string c = EmitCall(e, true);
                    if (c != "") EmitCallStatement(c);
                    return;
                }
            case NodeKind.Conv:
                EmitExprStatement(e.A!);
                return;
        }
        string v = Expr(e);
        if (v != "") Line("local _ = " + v);
    }

    private void EmitCallStatement(string c)
    {
        // Lua の文になれるのは呼び出しだけ
        if (IsCallText(c)) Line(c);
        else Line("local _ = " + c);
    }

    private static bool IsCallText(string c)
    {
        var u = new Utf8Bytes(c);
        int n = u.Length;
        if (n == 0 || u[n - 1] != ')') return false;
        // 括弧で始まる式 ((f)(x) など) は文にできない
        if (u[0] == '(') return false;
        // 最後の ( に対応する ) までが呼び出し
        int depth = 0;
        for (int i = n - 1; i >= 0; i--)
        {
            int ch = u[i];
            if (ch == ')') depth++;
            else if (ch == '(')
            {
                depth--;
                if (depth == 0)
                {
                    if (i == 0) return false;
                    int prev = u[i - 1];
                    return prev >= 'a' && prev <= 'z' || prev >= 'A' && prev <= 'Z' || prev >= '0' && prev <= '9' || prev == '_' || prev == ']' || prev == ')';
                }
            }
        }
        return false;
    }


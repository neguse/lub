// 増分 session と module registry の snapshot (doc/incremental-module-compilation-design.md §7-§14)。
// compile はファイルごとの module (Session.ModuleArtifacts) を作り、型ごとの記録 (宣言の行と static の初期化の行の範囲) で
// define の chunk と初期化の thunk に分ける。範囲はみな RawLua の UTF-8 の byte の位置

// static field 1 個の記録 (Start と Length は初期化の行の範囲)
public sealed class ModuleStatic
{
    public string Key;
    public string Type;
    public string DefaultLua;
    public string? InitHash;
    public bool Pure;
    public int Start;
    public int Length;

    public ModuleStatic(string key, string type, string defaultLua, string? initHash, bool pure, int start, int length)
    {
        Key = key;
        Type = type;
        DefaultLua = defaultLua;
        InitHash = initHash;
        Pure = pure;
        Start = start;
        Length = length;
    }
}

// module の中の型 1 個の記録
public sealed class ModuleType
{
    public string Name = "";
    public string Kind = "";
    public string CSharpName = "";
    public string BaseName = "";
    public string InstanceShape = "";
    // `Name = {}` と static の pre-zero の行 (define の chunk から除き、registry の declare が担う)
    public List<int> DeclStarts = new List<int>();
    public List<int> DeclLengths = new List<int>();
    public List<ModuleStatic> StaticFields = new List<ModuleStatic>();
    public List<string> InitDependencies = new List<string>();
    // 定義が持つ型の table の key (new、__index、method、accessor、metamethod、enum の member)。hot apply の削除の差分に使う
    public List<string> DefinitionKeys = new List<string>();
    public List<string> EnumMemberNames = new List<string>();
    public List<int> EnumMemberValues = new List<int>();
}

public sealed class ModuleArtifact
{
    public string ModuleId = "";
    public string SourceHash = "";
    public string SurfaceHash = "";
    // RawLua の末尾の空白を除いて改行を 1 つ足したもの
    public string Lua = "";
    public string RawLua = "";
    public List<ModuleType> Types = new List<ModuleType>();
    // 出力の内容の hash。registry は hot apply で変わらない module を飛ばす (source が同じでも他の module の面の変更で出力は変わりうる)
    public string LuaHash = "";
}

public static class ModuleText
{
    // define の chunk: RawLua から宣言の行と static の初期化の行を除いたもの
    public static string DefineLua(string rawLua, List<ModuleType> types)
    {
        var starts = new List<int>();
        var ends = new List<int>();
        foreach (var t in types)
        {
            for (int i = 0; i < t.DeclStarts.Count; i++) AddCut(starts, ends, t.DeclStarts[i], t.DeclStarts[i] + t.DeclLengths[i]);
            foreach (var s in t.StaticFields) AddCut(starts, ends, s.Start, s.Start + s.Length);
        }
        var u = new Utf8Bytes(rawLua);
        var parts = new List<string>();
        int at = 0;
        for (int i = 0; i < starts.Count; i++)
        {
            if (starts[i] > at) parts.Add(u.Slice(at, starts[i] - at).ToString());
            if (ends[i] > at) at = ends[i];
        }
        if (at < u.Length) parts.Add(u.Slice(at, u.Length - at).ToString());
        return string.Join("", parts);
    }

    // 始まりの昇順に入れる
    private static void AddCut(List<int> starts, List<int> ends, int start, int end)
    {
        int k = starts.Count;
        while (k > 0 && starts[k - 1] > start) k--;
        starts.Insert(k, start);
        ends.Insert(k, end);
    }

    // 型 1 個の static の初期化の chunk (出力の順の初期化の行をつないだもの)
    public static string TypeInitializerLua(string rawLua, ModuleType type)
    {
        var u = new Utf8Bytes(rawLua);
        var parts = new List<string>();
        foreach (var s in type.StaticFields) parts.Add(u.Slice(s.Start, s.Length).ToString());
        return string.Join("", parts);
    }

    public static string FieldInitializerLua(string rawLua, ModuleStatic field)
    {
        return new Utf8Bytes(rawLua).Slice(field.Start, field.Length).ToString();
    }

    public static string EscapeLuaString(string s)
    {
        return "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n").Replace("\r", "\\r") + "\"";
    }

    public static string Hash(string s)
    {
        return IlExporter.Hash64(s);
    }
}

// bridge snapshot (§14.2)。全ての artifact から、空の registry からも起動できる単一の entry の Lua を組み立てる。
// 出力は冪等な bootstrap、registry:applyBatch、薄い entry の wrapper の return
public static class ModuleLinker
{
    // 失敗の理由 (LinkSnapshot が null を返したとき)
    public static string Error = "";

    public static string? LinkSnapshot(List<ModuleArtifact> artifacts, int revision, string entryClass, string tinySystemLua, string registryLua, bool emitAck)
    {
        Error = "";
        var parts = new List<string>();
        parts.Add("-- Generated by TinyC# transpiler (module snapshot rev " + revision + ")\n");
        // 冪等な bootstrap: 初めてだけ TinySystem の前置きと registry を作る。reload では今の identity を保つ (§14.2)
        parts.Add("local __rt = _G.__tcs_module_runtime\n");
        parts.Add("if not (__rt and __rt.abi == 1) then\n");
        parts.Add("  local TinySystem = (function()\n");
        AppendIndented(parts, tinySystemLua, "    ");
        parts.Add("  end)()\n");
        parts.Add("  _G.TinySystem = TinySystem\n");
        foreach (var name in Cli.RuntimeGlobalAliases) parts.Add("  _G." + name + " = TinySystem." + name + "\n");
        string[] direct = "idiv irem get set u8at count lchk lget lset cadd csub cmul cneg".Split(' ');
        foreach (var n in direct) parts.Add("  _G.__tcs_" + n + " = TinySystem." + n + "\n");
        parts.Add("  _G.__tcs_is = TinySystem.instanceof\n");
        parts.Add("  _G.__tcs_implements = TinySystem.implements\n");
        string[] casts = "cast icast tcast vcast ncast fstr bstr trunc char tofloat".Split(' ');
        foreach (var n in casts) parts.Add("  _G.__tcs_" + n + " = TinySystem." + n + "\n");
        parts.Add("  _G.__tcs_min = TinySystem.Math.Min\n");
        parts.Add("  _G.__tcs_max = TinySystem.Math.Max\n");
        string[] rest = "arr dv nt tc tstr etd shl shr mg".Split(' ');
        foreach (var n in rest) parts.Add("  _G.__tcs_" + n + " = TinySystem." + n + "\n");
        for (int arity = 2; arity <= 7; arity++) parts.Add("  _G.__tcs_tuple" + arity + " = TinySystem.tuple" + arity + "\n");
        string[] nullable = "nval nget nlift nlift1 ncmp nand nor nnot nstr".Split(' ');
        foreach (var n in nullable) parts.Add("  _G.__tcs_" + n + " = TinySystem." + n + "\n");
        string[] ops = "add sub mul div idiv irem fmod band bor bxor shl shr lt le gt ge neg bnot tofloat".Split(' ');
        foreach (var op in ops) parts.Add("  _G.__tcs_op_" + op + " = TinySystem.nops." + op + "\n");
        parts.Add("  local __registry_mod = (function()\n");
        AppendIndented(parts, registryLua, "    ");
        parts.Add("  end)()\n");
        parts.Add("  __rt = { abi = 1, registry = __registry_mod.new(_G) }\n");
        parts.Add("  _G.__tcs_module_runtime = __rt\n");
        parts.Add("end\n\n");

        parts.Add("local __result = __rt.registry:applyBatch({\n");
        parts.Add("  revision = " + revision + ",\n");
        if (emitAck) parts.Add("  ack = true,\n");
        if (entryClass != "")
        {
            var entry = FindEntry(artifacts, entryClass);
            if (entry == null) return null;
            parts.Add("  entry = { type = " + ModuleText.EscapeLuaString(TypeId(entry.ModuleId, entry.Type.Name)) + ", keys = { ");
            foreach (var k in entry.Type.DefinitionKeys)
            {
                if (!k.StartsWith("__")) parts.Add(ModuleText.EscapeLuaString(k) + ", ");
            }
            parts.Add("} },\n");
        }
        // 新しい型の初期化の thunk の実行の順 (StaticInitOrder)
        parts.Add("  init_order = {\n");
        foreach (var typeId in InitOrder(artifacts)) parts.Add("    " + ModuleText.EscapeLuaString(typeId) + ",\n");
        parts.Add("  },\n");
        parts.Add("  modules = {\n");
        foreach (var a in artifacts) AppendModuleDescriptor(parts, a);
        parts.Add("  },\n");
        parts.Add("})\n");
        parts.Add("return __result.wrapper\n");
        return string.Join("", parts);
    }

    private static ModuleEntry? FindEntry(List<ModuleArtifact> artifacts, string entryClass)
    {
        // 完全修飾名 (`A.Color`)、Lua の名前、simple な名前のどれでも引ける。simple な名前だけが複数の型に当たるなら曖昧
        var hits = new List<ModuleEntry>();
        foreach (var a in artifacts)
        {
            foreach (var t in a.Types)
            {
                if (t.Name == entryClass || t.CSharpName == entryClass || t.CSharpName.EndsWith("." + entryClass)) hits.Add(new ModuleEntry(a.ModuleId, t));
            }
        }
        if (hits.Count == 0)
        {
            Error = "entry class not found: " + entryClass;
            return null;
        }
        var exact = new List<ModuleEntry>();
        foreach (var h in hits)
        {
            if (h.Type.CSharpName == entryClass || h.Type.Name == entryClass) exact.Add(h);
        }
        if (exact.Count == 1) return exact[0];
        if (hits.Count > 1)
        {
            var names = new List<string>();
            foreach (var h in hits) names.Add(h.Type.CSharpName);
            Error = "entry class is ambiguous: " + entryClass + " (" + string.Join(", ", names) + ")";
            return null;
        }
        return hits[0];
    }

    private static List<string> InitOrder(List<ModuleArtifact> artifacts)
    {
        var names = new List<string>();
        var ids = new Dictionary<string, string>();
        var types = new Dictionary<string, ModuleType>();
        foreach (var a in artifacts)
        {
            foreach (var t in a.Types)
            {
                names.Add(t.Name);
                ids[t.Name] = TypeId(a.ModuleId, t.Name);
                types[t.Name] = t;
            }
        }
        var deps = new Dictionary<string, List<string>>();
        foreach (var name in names)
        {
            var list = new List<string>();
            foreach (var d in types[name].InitDependencies)
            {
                if (types.ContainsKey(d)) list.Add(d);
            }
            deps[name] = list;
        }
        var result = new List<string>();
        foreach (var name in StaticInitOrder.Order(names, deps))
        {
            if (types[name].StaticFields.Count > 0) result.Add(ids[name]);
        }
        return result;
    }

    public static string TypeId(string moduleId, string typeName)
    {
        return moduleId + "#" + typeName;
    }

    private static void AppendModuleDescriptor(List<string> parts, ModuleArtifact a)
    {
        parts.Add("    {\n");
        parts.Add("      id = " + ModuleText.EscapeLuaString(a.ModuleId) + ",\n");
        parts.Add("      hash = " + ModuleText.EscapeLuaString(a.LuaHash) + ",\n");
        parts.Add("      types = {\n");
        foreach (var t in a.Types)
        {
            parts.Add("        { id = " + ModuleText.EscapeLuaString(TypeId(a.ModuleId, t.Name)) + ", name = " + ModuleText.EscapeLuaString(t.Name) + ", kind = " + ModuleText.EscapeLuaString(t.Kind));
            if (t.BaseName != "") parts.Add(", base = " + ModuleText.EscapeLuaString(t.BaseName));
            parts.Add(",\n          statics = { ");
            foreach (var s in t.StaticFields)
                parts.Add("{ key = " + ModuleText.EscapeLuaString(s.Key) + ", default = " + s.DefaultLua + ", pure = " + (s.Pure ? "true" : "false") + " }, ");
            parts.Add("},\n          keys = { ");
            foreach (var k in t.DefinitionKeys) parts.Add(ModuleText.EscapeLuaString(k) + ", ");
            foreach (var s in t.StaticFields) parts.Add(ModuleText.EscapeLuaString(s.Key) + ", ");
            parts.Add("} },\n");
        }
        parts.Add("      },\n");
        // define と初期化子は _ENV を受ける関数の literal として埋め込む。本文の global の参照は registry の読み取り専用の module の環境に解決される
        parts.Add("      define = function(_ENV)\n");
        parts.Add(ModuleText.DefineLua(a.RawLua, a.Types));
        parts.Add("\n      end,\n");
        parts.Add("      inits = {\n");
        foreach (var t in a.Types)
        {
            if (t.StaticFields.Count == 0) continue;
            parts.Add("        [" + ModuleText.EscapeLuaString(TypeId(a.ModuleId, t.Name)) + "] = function(_ENV)\n");
            parts.Add(ModuleText.TypeInitializerLua(a.RawLua, t));
            parts.Add("        end,\n");
        }
        parts.Add("      },\n");
        // 副作用が無いと分かった static field だけ、hot apply の新しい field の初期化のために field ごとの thunk を持つ (§11.3)
        parts.Add("      initfns = {\n");
        foreach (var t in a.Types)
        {
            bool anyPure = false;
            foreach (var s in t.StaticFields)
            {
                if (s.Pure) anyPure = true;
            }
            if (!anyPure) continue;
            parts.Add("        [" + ModuleText.EscapeLuaString(TypeId(a.ModuleId, t.Name)) + "] = {\n");
            foreach (var s in t.StaticFields)
            {
                if (!s.Pure) continue;
                parts.Add("          [" + ModuleText.EscapeLuaString(s.Key) + "] = function(_ENV)\n");
                parts.Add(ModuleText.FieldInitializerLua(a.RawLua, s));
                parts.Add("          end,\n");
            }
            parts.Add("        },\n");
        }
        parts.Add("      },\n");
        parts.Add("    },\n");
    }

    private static void AppendIndented(List<string> parts, string source, string indent)
    {
        string text = Cli.TrimEnd(source.Replace("\r\n", "\n"));
        foreach (var line in text.Split('\n'))
        {
            if (line == "") parts.Add("\n");
            else parts.Add(indent + line + "\n");
        }
    }
}


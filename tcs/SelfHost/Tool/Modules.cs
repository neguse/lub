// 1 回の更新の結果
public sealed class ModuleUpdate
{
    public bool Success;
    public bool FastPath;
    // live に当てられない変更 (§11.3)。host は snapshot を hotswap ではなく VM を作り直して当てる。fast path では常に false
    public bool RequiresRestart;
    public List<string> RestartReasons = new List<string>();
    public List<string> Errors = new List<string>();
    // この revision で差し替えた module (誤りのときは空 = 最後に成功した artifact を保つ)
    public List<ModuleArtifact> ChangedArtifacts = new List<ModuleArtifact>();
    public int ParsedTreeCount;
    public int EmittedModuleCount;
}

// 増分 session (§7-§9)。parse は内容の変わったファイルだけをやり直し、宣言、束縛、出力は毎回全体で行う。
// 次の全てを満たす編集は fast path (編集したファイルの module だけを差し替える):
//   変更の範囲が method / constructor / accessor の本文に収まる、本文の外の token (面) が変わらない、
//   直前の revision に誤りが無い (復帰はいつも全体)、top-level の文を含まない。
// それ以外は全ての module を差し替え、hot apply できない変更 (ReloadRules) を判定する
public sealed class ModuleSession
{
    private Session _compiler = new Session("");
    private List<string> _paths = new List<string>();
    private Dictionary<string, string> _texts = new Dictionary<string, string>();
    private Dictionary<string, ModuleArtifact> _lastGood = new Dictionary<string, ModuleArtifact>();
    private List<string> _artifactOrder = new List<string>();
    private List<string> _errors = new List<string>();
    private List<string> _warnings = new List<string>();
    private bool _hasErrors;
    private bool _hasTopLevel;
    // 開いたときの誤り (OpenProject は投げる代わりにここに理由を置く)
    public string OpenError = "";
    // artifact を更新した revision (成功した Open / Update ごとに増える)
    public int Revision;

    public ModuleSession(List<string> referenceSources)
    {
        _compiler.ModuleArtifacts = true;
        for (int i = 0; i < referenceSources.Count; i++) _compiler.SetReference("<ref" + i + ">", referenceSources[i]);
        _compiler.SetLibrary("TinySystem/Linq.cs", TcsHost.ToolFile("lib/TinySystem/Linq.cs"));
        _compiler.SetLibrary("TinySystem/ValueTuple.cs", TcsHost.ToolFile("lib/TinySystem/ValueTuple.cs"));
    }

    public void Open(List<string> paths, List<string> texts)
    {
        OpenError = "";
        foreach (var p in _paths) _compiler.Remove(p);
        _paths = new List<string>();
        _texts = new Dictionary<string, string>();
        _lastGood = new Dictionary<string, ModuleArtifact>();
        _artifactOrder = new List<string>();
        for (int i = 0; i < paths.Count; i++)
        {
            if (IsReservedLibraryPath(paths[i], texts[i]))
            {
                OpenError = "module path is reserved for the bundled library: " + paths[i];
                return;
            }
            _paths.Add(paths[i]);
            _texts[paths[i]] = texts[i];
            _compiler.SetSource(paths[i], texts[i]);
        }
        var result = Compile();
        if (_hasErrors) return;
        foreach (var a in BuildArtifacts(result)) _lastGood[a.ModuleId] = a;
        _artifactOrder = ModulePaths(result);
        Revision++;
    }

    public bool Has(string path)
    {
        return _texts.ContainsKey(path);
    }

    public string TextOf(string path)
    {
        string? t;
        if (_texts.TryGetValue(path, out t)) return t;
        return "";
    }

    public List<string> Paths()
    {
        return _paths;
    }

    public ModuleUpdate Update(string path, string newContent)
    {
        string oldText = _texts[path];
        var oldUnit = _compiler.ParsedUnit(path);
        MinimalChange(oldText, newContent, out int start, out int oldLength);
        _texts[path] = newContent;
        _compiler.SetSource(path, newContent);
        var newUnit = _compiler.ParsedUnit(path);
        ModuleArtifact? prev;
        bool fastEligible = !_hasTopLevel && !_hasErrors && oldUnit != null && newUnit != null
            && Surface.InsideBody(oldUnit, start, start + oldLength)
            && _lastGood.TryGetValue(path, out prev) && Surface.Hash(newUnit.File, newUnit) == prev.SurfaceHash;
        var result = Compile();
        var update = new ModuleUpdate();
        update.FastPath = fastEligible;
        update.ParsedTreeCount = 1;
        if (_hasErrors)
        {
            update.Success = false;
            foreach (var e in _errors) update.Errors.Add(e);
            return update;
        }
        var next = BuildArtifacts(result);
        var prevArtifacts = _lastGood;
        var order = ModulePaths(result);
        bool libraryChanged = !SameList(order, _artifactOrder);
        _lastGood = new Dictionary<string, ModuleArtifact>();
        foreach (var a in next) _lastGood[a.ModuleId] = a;
        _artifactOrder = order;
        Revision++;
        update.Success = true;
        // 本文だけの編集は面が同じなので、他の module の出力を変えない。編集した module だけを差し替える
        if (fastEligible && !libraryChanged)
        {
            foreach (var a in next)
            {
                if (a.ModuleId == path) update.ChangedArtifacts.Add(a);
            }
            update.EmittedModuleCount = update.ChangedArtifacts.Count;
            return update;
        }
        update.FastPath = false;
        foreach (var a in next)
        {
            update.ChangedArtifacts.Add(a);
            ModuleArtifact? old;
            if (!prevArtifacts.TryGetValue(a.ModuleId, out old)) continue;
            foreach (var r in ReloadRules.RestartReasons(ReloadTypes(old), ReloadTypes(a), false)) update.RestartReasons.Add(a.ModuleId + ": " + r);
        }
        update.RequiresRestart = update.RestartReasons.Count > 0;
        update.EmittedModuleCount = next.Count;
        return update;
    }

    public List<ModuleArtifact> Artifacts()
    {
        var list = new List<ModuleArtifact>();
        foreach (var p in _artifactOrder)
        {
            ModuleArtifact? a;
            if (_lastGood.TryGetValue(p, out a)) list.Add(a);
        }
        return list;
    }

    public List<string> Errors()
    {
        return _errors;
    }

    public List<string> Warnings()
    {
        return _warnings;
    }

    private static bool SameList(List<string> a, List<string> b)
    {
        if (a.Count != b.Count) return false;
        for (int i = 0; i < a.Count; i++)
        {
            if (a[i] != b[i]) return false;
        }
        return true;
    }

    private static List<string> ModulePaths(CompileResult result)
    {
        var list = new List<string>();
        foreach (var m in result.Modules) list.Add(m.Path);
        return list;
    }

    private CompileResult Compile()
    {
        var result = _compiler.Compile();
        _errors = new List<string>();
        _warnings = new List<string>();
        foreach (var d in result.Diagnostics)
        {
            if (Cli.IsWarning(d)) _warnings.Add(d);
            else _errors.Add(d);
        }
        _hasErrors = !result.Ok || _errors.Count > 0;
        if (_hasErrors && _errors.Count == 0) _errors.Add("compile failed");
        _hasTopLevel = false;
        foreach (var p in _paths)
        {
            var unit = _compiler.ParsedUnit(p);
            if (unit != null && unit.Count2 > 0) _hasTopLevel = true;
        }
        return result;
    }

    private List<ModuleArtifact> BuildArtifacts(CompileResult result)
    {
        var artifacts = new List<ModuleArtifact>();
        foreach (var m in result.Modules)
        {
            // chunk の番号 → RawLua の byte の位置
            var offsets = new List<int>();
            int at = 0;
            offsets.Add(0);
            foreach (var c in m.Chunks)
            {
                at = at + Strings.ByteLength(c);
                offsets.Add(at);
            }
            string raw = string.Join("", m.Chunks);
            var a = new ModuleArtifact();
            a.ModuleId = m.Path;
            string? text;
            a.SourceHash = ModuleText.Hash(_texts.TryGetValue(m.Path, out text) ? text : m.Path);
            var unit = _compiler.ParsedUnit(m.Path);
            a.SurfaceHash = unit != null ? Surface.Hash(unit.File, unit) : "";
            a.RawLua = raw;
            a.Lua = Cli.TrimEnd(raw) + "\n";
            a.LuaHash = ModuleText.Hash(a.Lua);
            foreach (var t in m.Types) a.Types.Add(ConvertType(t, offsets));
            artifacts.Add(a);
        }
        return artifacts;
    }

    private static ModuleType ConvertType(EmittedTypeInfo t, List<int> offsets)
    {
        var info = new ModuleType();
        info.Name = t.Name;
        info.Kind = t.Kind;
        info.CSharpName = t.CSharpName;
        info.BaseName = t.BaseName;
        info.InstanceShape = t.InstanceShape;
        foreach (var d in t.InitDependencies) info.InitDependencies.Add(d);
        foreach (var s in t.StaticFields)
            info.StaticFields.Add(new ModuleStatic(s.Key, s.Type, s.DefaultLua, s.InitHash, s.Pure, offsets[s.Start], offsets[s.End] - offsets[s.Start]));
        for (int i = 0; i < t.DeclStarts.Count; i++)
        {
            info.DeclStarts.Add(offsets[t.DeclStarts[i]]);
            info.DeclLengths.Add(offsets[t.DeclEnds[i]] - offsets[t.DeclStarts[i]]);
        }
        foreach (var k in t.DefinitionKeys) info.DefinitionKeys.Add(k);
        foreach (var n in t.EnumMemberNames) info.EnumMemberNames.Add(n);
        foreach (var v in t.EnumMemberValues) info.EnumMemberValues.Add(v);
        return info;
    }

    private static List<ReloadType> ReloadTypes(ModuleArtifact a)
    {
        var list = new List<ReloadType>();
        foreach (var t in a.Types)
        {
            var r = new ReloadType(t.Name, t.Kind);
            r.BaseName = t.BaseName;
            r.InstanceShape = t.InstanceShape;
            foreach (var s in t.StaticFields) r.Statics.Add(new ReloadStatic(s.Key, s.Type, s.InitHash, s.Pure));
            foreach (var n in t.EnumMemberNames) r.EnumMemberNames.Add(n);
            foreach (var v in t.EnumMemberValues) r.EnumMemberValues.Add(v);
            list.Add(r);
        }
        return list;
    }

    // 同梱の library の path は、その library の namespace を宣言する手元の版にだけ使える
    public static bool IsReservedLibraryPath(string path, string text)
    {
        if (path != "TinySystem/Linq.cs" && path != "TinySystem/ValueTuple.cs") return false;
        if (path == "TinySystem/ValueTuple.cs") return true;
        var file = new SourceFile(0, path, text, false);
        var unit = Parser.ParseFile(file, new Diagnostics());
        var declared = new HashSet<string>();
        Session.CollectNamespaces(unit, "", declared, new HashSet<string>());
        return !declared.Contains("TinySystem.Linq");
    }

    // 旧い全文から新しい全文への最小の単一の置き換え (共通の前と後ろを除く)。位置は UTF-8 の byte
    public static void MinimalChange(string oldText, string newText, out int start, out int oldLength)
    {
        var a = new Utf8Bytes(oldText);
        var b = new Utf8Bytes(newText);
        int prefix = 0;
        int max = a.Length < b.Length ? a.Length : b.Length;
        while (prefix < max && a[prefix] == b[prefix]) prefix++;
        int suffix = 0;
        int maxSuffix = max - prefix;
        while (suffix < maxSuffix && a[a.Length - 1 - suffix] == b[b.Length - 1 - suffix]) suffix++;
        start = prefix;
        oldLength = a.Length - prefix - suffix;
    }

    // 本文を除いた宣言の token の列の hash (空白と comment は含めない)
    public static string SurfaceHashOf(string text)
    {
        var file = new SourceFile(0, "", text, false);
        var unit = Parser.ParseFile(file, new Diagnostics());
        return Surface.Hash(file, unit);
    }
}

// --snapshot: module registry の bridge snapshot (registry に当てる単一の entry の Lua) を出す。module の ID は与えた入力の path そのもの
public sealed class SnapshotRun
{
    private CliOptions _o;

    public SnapshotRun(CliOptions o)
    {
        _o = o;
    }

    public int Step()
    {
        var paths = new List<string>();
        foreach (var p in _o.InputPaths) paths.Add(p.Replace("\\", "/"));
        var session = new ModuleSession(Cli.ReadAll(_o.RefPaths));
        session.Open(paths, Cli.ReadAll(_o.InputPaths));
        if (session.OpenError != "") return Cli.Error(session.OpenError);
        foreach (var w in session.Warnings()) TcsHost.WriteErr(w + "\n");
        if (session.Errors().Count > 0)
        {
            foreach (var e in session.Errors()) TcsHost.WriteErr(e + "\n");
            return 1;
        }
        var tinySystem = Cli.RuntimeFile("runtime/tinysystem.lua");
        if (tinySystem == null) return 1;
        var registry = Cli.RuntimeFile("runtime/module_registry.lua");
        if (registry == null) return 1;
        var lua = ModuleLinker.LinkSnapshot(session.Artifacts(), session.Revision, _o.EntryClass, tinySystem, registry, true);
        if (lua == null) return Cli.Error(ModuleLinker.Error);
        if (_o.OutputPath == "")
        {
            TcsHost.WriteOut(lua);
            return 0;
        }
        string failure = TcsHost.WriteFileAtomic(_o.OutputPath, lua);
        if (failure != "") return Cli.Error(failure);
        TcsHost.WriteErr("Wrote " + _o.OutputPath + "\n");
        return 0;
    }
}

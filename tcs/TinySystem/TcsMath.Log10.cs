    static float Log10Special(float x)
    {
        uint ux = AsUInt(x), ax = ux << 1;
        if (ax == 0u)
            return AsFloat(0x1ffu << 23);
        if (ux == 0x7f800000u)
            return x;
        if (ax > 0xff000000u)
            return x + x;
        return AsFloat(0x1ff8u << 19);
    }


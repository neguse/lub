    public static float Log10(float x)
    {
        // ln(2)/ln(10)
        const double ln10 = 0.3010299956639812, ln10h = 0.30102999566398125, ln10l = -5.8314879359043e-17;
        uint ux = AsUInt(x);
        if (ux >= 0x7f800000u)
            return Log10Special(x);
        if (ux == AsUInt(Log10St[(ux >> 24) & 0xf]))
        {
            uint je = (uint)(((int)ux >> 23) - 126);
            je = (je * 0x4d104d4u) >> 28;
            return (float)je;
        }
        if (ux < 0x00800000u)
        {
            if (ux == 0u)
                return Log10Special(x);
            int n = Clz32(ux) - 8;
            ux <<= n;
            ux -= (uint)n << 23;
        }
        int e = ((int)ux >> 23) - 127;
        long m = ux & ((1 << 23) - 1), j = (m + (1 << (23 - 7))) >> (23 - 6);
        double z = AsDouble(((ulong)m << (52 - 23)) | (0x3fful << 52)) * Log10Tr[j] - 1, z2 = z * z;
        double r = ((e * ln10 + Log10Tl[j]) + z * Log10B[0]) + z2 * (Log10B[1] + z * Log10B[2]);
        float ub = (float)r, lb = (float)(r + 9.802997302799099e-11);
        if (ub != lb)
        {
            double f = z * ((Log10C[0] + z * Log10C[1])
                + z2 * ((Log10C[2] + z * Log10C[3]) + z2 * (Log10C[4] + z * Log10C[5] + z2 * Log10C[6])));
            f += ln10l * e;
            f += Log10Tl[j] - Log10Tl[0];
            double el = e * ln10h;
            r = el + f;
            ub = (float)r;
            if ((AsULong(r) & ((1 << 28) - 1)) == 0)
            {
                double dr = (el - r) + f;
                r += dr * 32;
                ub = (float)r;
            }
        }
        return ub;
    }

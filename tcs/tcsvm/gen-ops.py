"""Generates VmBackend/Op.cs from TVM_OPS in tcsvm/vm/tcsvm_ops.h.
Usage: python3 -I tcsvm/gen-ops.py (run it when the order changes; a mismatch stops at load time via the abi)"""
import os
import re

root = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(root, 'vm', 'tcsvm_ops.h'), encoding='utf-8').read()
block = src.split('#define TVM_OPS(X)')[1].split('enum {')[0]
names = re.findall(r'X\((\w+)\)', block)
body = '\n'.join(f'    {n},' for n in names)
# abi that the VM compares with its own list at load time: FNV-1a of the name sequence (32 bit)
h = 2166136261
for n in names:
    for ch in n.encode():
        h = ((h ^ ch) * 16777619) & 0xFFFFFFFF
    h = ((h ^ ord(',')) * 16777619) & 0xFFFFFFFF
signed = h - (1 << 32) if h >= 1 << 31 else h
cs = f'''// Generated by tcsvm/gen-ops.py from tcsvm/vm/tcsvm_ops.h. Do not edit by hand
namespace TcsVm;

/// <summary>List of instructions. Same order as TVM_OPS in tcsvm/vm/tcsvm_ops.h (the format is described in the notes in that header).</summary>
public enum Op
{{
{body}
}}

public static class OpAbi
{{
    /// <summary>FNV-1a of the name sequence (as a 32-bit pattern). The VM compares it with its own list when loading.</summary>
    public const int Hash = {signed};
}}
'''
open(os.path.join(os.path.dirname(root), 'VmBackend', 'Op.cs'), 'w', encoding='utf-8').write(cs)
print(f'{len(names)} ops')

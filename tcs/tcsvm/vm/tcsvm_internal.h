/* Same byte layout as tcs2c's TcsString ({ size_t length; data[] }) (little
   endian, pad is always 0, len is less than 2^31): in shared heap, strings are
   passed to C modules without copying (doc/object-model.md §10.6) */
typedef struct TvmString {
  int32_t len;
#if SIZE_MAX > 0xFFFFFFFFu
  int32_t pad; /* 64-bit: the upper half of size_t (with a 32-bit size_t, only
                  len) */
#endif
  /* Followed by len bytes and a terminating '\0' */
} TvmString;
_Static_assert(sizeof(TvmString) == sizeof(size_t),
               "TvmString must match TcsString");
#if defined(__BYTE_ORDER__) && __BYTE_ORDER__ != __ORDER_LITTLE_ENDIAN__
#error                                                                         \
    "tcsvm assumes little endian (TvmString shares its layout with TcsString)"
#endif

#define STR_DATA(s) ((char *)(s) + sizeof(TvmString))

typedef struct TvmList {
  int32_t count, cap;
  char *data;
} TvmList;

/* Dictionary: the list of entries in insertion order (enumeration is in
   insertion order, support-matrix §18; removed entries are holes with live = 0,
   compacted on growth) and an open addressing table that looks up entry
   indices. An entry is { hash, live, key, value (sequence of the type's leaves)
   } */
typedef struct TvmDictEntry {
  uint32_t hash;
  uint32_t live;
  TvmSlot key;
  /* Followed by the value (type->elem_size bytes, aligned to 8) */
} TvmDictEntry;

#define DICT_VALUE(e) ((char *)(e) + sizeof(TvmDictEntry))

typedef struct TvmDict {
  int32_t count; /* Live entries */
  int32_t used;  /* Pushed entries (including removed ones) */
  int32_t cap;   /* Capacity of the entry list */
  int32_t nbuckets;
  int32_t version;  /* Incremented each time a new key is added or Clear is
                       called (foreach faults on additions during enumeration) */
  char *entries;    /* blob */
  int32_t *buckets; /* blob: entry index + 1. 0 is empty, -1 is removed */
} TvmDict;

#define DICT_ENTRY(d, i)                                                       \
  ((TvmDictEntry *)((d)->entries + (size_t)(i) * TVM_TYPE(d)->dict_entry))


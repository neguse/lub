/* Relative branch offset: a signed 24-bit value in bits 40..63. Sign-extended
 * without a signed shift */
#define OFF24_OF(ins)                                                          \
  ((int32_t)((uint32_t)((ins) >> 40) ^ 0x800000u) - 0x800000)


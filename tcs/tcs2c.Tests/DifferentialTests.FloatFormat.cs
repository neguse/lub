    [CFact]
    public void FloatFormat_GAndEMatchDotnet()
    {
        foreach (var (value, texts) in FloatFormatTexts)
            Assert.Equal(texts, string.Join("|", FloatFormats.Select(f => value.ToString(f, CultureInfo.InvariantCulture))));

        var holes = string.Join("|", FloatFormats.Select(f => "{f:" + f + "}"));
        var calls = string.Concat(FloatFormatTexts.Select(c => $"        Show({FloatLiteral(c.Value)});\n"));
        var output = Backends.AssertParity("""
            using System;
            public class P
            {
                static float p = 0f;

            """ + "    static void Show(float f) { Console.WriteLine($\"" + holes + "\"); }\n" + """

                public static void Main()
                {
                    float? n = 0.5f;
                    float? none = null;
                    Console.WriteLine($"{n:E2}|{none:E2}|{none:G3}|{n:g}|{1234567f,14:E2}|{0.5f,-8:G}|");
            """ + calls + "    }\n}\n", "P");
        Assert.Equal("5.00E-001|||0.5|     1.23E+006|0.5     |\n"
            + string.Join("\n", FloatFormatTexts.Select(c => c.Texts)), output);
    }

    // 広い指数の範囲 (非正規化数を含む) の値を書式つきで文字列にした hash を、テストのプロセスの .NET と比べる
    [CFact]
    public void FloatFormat_WideRangeHashMatchesDotnet()
    {
        var output = Backends.AssertParity("""
            using System;
            public class P
            {
                static int state = 12345;

                static int Step()
                {
                    state = state * 1664525 + 1013904223;
                    return (state >> 8) & 0xffffff;
                }

                // [1, 2) の仮数に 2^e (e は -149..127) を掛けて符号を付ける
                static float Next()
                {
                    float x = 1f + (Step() & 0x7fffff) / 8388608f;
                    int e = Step() % 277 - 149;
                    while (e > 0) { x *= 2f; e--; }
                    while (e < 0) { x *= 0.5f; e++; }
                    return (Step() & 1) == 0 ? x : -x;
                }

                public static void Main()
                {
                    int h = 0;
                    for (int i = 0; i < 20000; i++)
                    {
                        float x = Next();
                        string s = $"{x:G}|{x:g}|{x:G1}|{x:G3}|{x:G6}|{x:G9}|{x:G12}|{x:E}|{x:E0}|{x:E3}|{x:E9}|{x:e12}";
                        for (int j = 0; j < s.Length; j++) h = h * 31 + s[j];
                    }
                    Console.WriteLine(h);
                }
            }
            """, "P");
        Assert.Equal(DotnetFormatHash().ToString(CultureInfo.InvariantCulture), output);
    }

    private static int DotnetFormatHash()
    {
        string[] formats = ["G", "g", "G1", "G3", "G6", "G9", "G12", "E", "E0", "E3", "E9", "e12"];
        int state = 12345, h = 0;
        int Step()
        {
            state = unchecked(state * 1664525 + 1013904223);
            return (state >> 8) & 0xffffff;
        }
        for (int i = 0; i < 20000; i++)
        {
            float x = 1f + (Step() & 0x7fffff) / 8388608f;
            int e = Step() % 277 - 149;
            while (e > 0) { x *= 2f; e--; }
            while (e < 0) { x *= 0.5f; e++; }
            x = (Step() & 1) == 0 ? x : -x;
            var s = string.Join("|", formats.Select(f => x.ToString(f, CultureInfo.InvariantCulture)));
            foreach (var c in s) h = unchecked(h * 31 + c);
        }
        return h;
    }

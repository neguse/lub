using System.Text;

namespace TinyCs;

public sealed record LuaRuntimeBundle(string Lua, int SourceMapLineOffset);

public static class LuaRuntime
{
    private const string RuntimeRelativePath = "runtime/tinysystem.lua";
    public const string RegistryRelativePath = "runtime/module_registry.lua";

    public static LuaRuntimeBundle EmbedRuntime(string lua)
    {
        var prelude = CreateEmbeddedPrelude(File.ReadAllText(FindRuntimePath()));
        return new LuaRuntimeBundle(prelude + lua, CountNewLines(prelude));
    }

    // バイナリの隣の runtime lua を読む (wasm は埋め込み resource)。
    public static string LoadRuntimeFile(string relativePath) =>
        File.ReadAllText(FindPath(relativePath));

    public static string LoadTinySystemSource() =>
        File.ReadAllText(FindRuntimePath());

    public static string CreateEmbeddedPrelude(string runtimeSource)
    {
        var sb = new StringBuilder();
        sb.AppendLine("-- Generated by TinyC# transpiler");
        sb.AppendLine("-- TinyC# embedded runtime prelude");
        sb.AppendLine("do");
        sb.AppendLine("  local TinySystem = (function()");

        var normalizedRuntime = runtimeSource.Replace("\r\n", "\n").TrimEnd();
        foreach (var line in normalizedRuntime.Split('\n'))
            sb.AppendLine($"    {line}");

        sb.AppendLine("  end)()");
        sb.AppendLine("  _G.TinySystem = TinySystem");
        // global alias の集合は診断 (RuntimeGlobalIdentifier) と共有する
        foreach (var name in TinyCsComplianceFacts.RuntimeGlobalAliases)
            sb.AppendLine($"  _G.{name} = TinySystem.{name}");
        sb.AppendLine("end");
        sb.AppendLine();
        return sb.ToString();
    }

    private static string FindRuntimePath() => FindPath(RuntimeRelativePath);

    // runtime は生成物に埋め込まれてホストで実行されるコードなので、バイナリの隣からだけ読む
    private static string FindPath(string relativePath)
    {
        var path = Path.Combine(AppContext.BaseDirectory, relativePath);
        return File.Exists(path) ? path : throw new FileNotFoundException(
            $"TinyC# runtime file not found: {path}");
    }

    private static int CountNewLines(string text)
    {
        var count = 0;
        foreach (var ch in text)
        {
            if (ch == '\n') count++;
        }
        return count;
    }
}
